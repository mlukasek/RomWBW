;======================================================================
;	SHARP MZ-800 GDG BITMAP VIDEO DRIVER
;	80X25 TEXT ON THE 640X200 MONOCHROME SCREEN
;======================================================================
;
; THE MZ-800 GDG HAS NO TEXT MODE IN MZ-800 MODE.  CHARACTERS ARE DRAWN
; FROM THE 8X8 FONT INTO THE 640X200 BITMAP.  THE CPU SEES THE BITMAP AS
; 80 BYTES PER RASTER LINE FROM $8000 (BIT 0 = LEFTMOST PIXEL), SO A TEXT
; ROW IS 640 CONTIGUOUS BYTES AND A CHARACTER CELL IS 8 BYTES 80 APART.
;
; SCROLLING USES THE GDG HARDWARE SCROLL (SOF, 40 UNITS PER TEXT ROW).
; CPU ACCESSES TO VRAM GO THROUGH THE SAME ADDRESS TRANSLATION AS THE
; DISPLAY, SO THE DRIVER ALWAYS WORKS IN SCREEN COORDINATES.
;
; VRAM IS MAPPED AT $8000-$BFFF ONLY AFTER IN A,($E0), WHICH ALSO MAPS
; THE CG-ROM AT $1000-$1FFF.  CODE AND DATA USED WHILE VRAM IS MAPPED
; MUST THEREFORE BE OUTSIDE $1000-$1FFF AND $8000-$BFFF (CHECKED AT
; ASSEMBLY TIME BELOW) AND INTERRUPTS ARE DISABLED WHILE IT IS MAPPED.
;
;======================================================================
; MZV DRIVER - CONSTANTS
;======================================================================
;
MZV_DMD		.EQU	$CE		; GDG DISPLAY MODE (W), STATUS (R)
MZV_WF		.EQU	$CC		; GDG WRITE FORMAT
MZV_RF		.EQU	$CD		; GDG READ FORMAT
MZV_PAL		.EQU	$F0		; GDG PALETTE
MZV_SOFL	.EQU	$01CF		; SCROLL OFFSET, LOW 8 BITS (OUT (C))
MZV_SOFH	.EQU	$02CF		; SCROLL OFFSET, HIGH 2 BITS (OUT (C))
MZV_SW		.EQU	$03CF		; SCROLL WIDTH (OUT (C))
MZV_SSA		.EQU	$04CF		; SCROLL START ADDRESS (OUT (C))
MZV_SEA		.EQU	$05CF		; SCROLL END ADDRESS (OUT (C))
MZV_BCOL	.EQU	$06CF		; BORDER COLOR (OUT (C))
MZV_VRAMON	.EQU	$E0		; IN: MAP CG-ROM AND VRAM
MZV_VRAMOFF	.EQU	$E1		; IN: UNMAP CG-ROM AND VRAM
;
MZV_VRAM	.EQU	$8000		; VRAM BASE IN CPU SPACE
MZV_ROWS	.EQU	25		; TEXT ROWS
MZV_COLS	.EQU	80		; TEXT COLUMNS
MZV_LINE	.EQU	80		; BYTES PER RASTER LINE
MZV_ROWSZ	.EQU	MZV_LINE * 8	; BYTES PER TEXT ROW
MZV_SOFROW	.EQU	40		; SOF UNITS PER TEXT ROW
MZV_SOFMAX	.EQU	MZV_SOFROW * MZV_ROWS	; SOF WRAP VALUE
MZV_SWVAL	.EQU	$7D		; SCROLL WIDTH, 200 RASTER LINES
MZV_FG		.EQU	$0F		; FOREGROUND COLOR (IGRB, WHITE)
MZV_BG		.EQU	$00		; BACKGROUND COLOR (IGRB, BLACK)
;
	DEVECHO	"MZV: MODE=640X200, TEXT=80X25\n"
;
TERMENABLE	.SET	TRUE		; INCLUDE TERMINAL PSEUDODEVICE DRIVER
MZKENABLE	.SET	TRUE		; INCLUDE MZ-800 KEYBOARD SUPPORT
;
;--------------------------------------------------------------------------------------------------
;   HBIOS MODULE HEADER
;--------------------------------------------------------------------------------------------------
;
ORG_MZV	.EQU	$
;
	.DW	SIZ_MZV			; MODULE SIZE
	.DW	MZV_INITPHASE		; ADR OF INIT PHASE HANDLER
;
MZV_INITPHASE:
	; INIT PHASE HANDLER, A=PHASE
	CP	HB_PHASE_PREINIT	; PREINIT PHASE?
	JP	Z,MZV_PREINIT		; DO PREINIT
	CP	HB_PHASE_INIT		; INIT PHASE?
	JP	Z,MZV_INIT		; DO INIT
	RET				; DONE
;
; EVERYTHING BELOW IS USED WHILE VRAM AND THE CG-ROM ARE MAPPED, SO IT
; MUST NOT BE IN $1000-$1FFF.  IF THE MODULE STARTS BELOW $2000, SKIP
; TO $2000 (THE HBIOS BANK NEVER REACHES $8000).
;
#IF ($ < $2000)
	.FILL	$2000 - $,$FF
#ENDIF
MZV_BODY	.EQU	$
;
;======================================================================
; MZV DRIVER - INITIALIZATION
;======================================================================
;
MZV_PREINIT:
	CALL	MZV_HWINIT		; PROGRAM THE GDG, CLEAR THE SCREEN
	JP	MZK_PREINIT		; INITIALIZE KEYBOARD
;
MZV_INIT:
	CALL	MZV_LOADFONT		; FONT FROM HBIOS FONT STORE
	JR	Z,MZV_INIT1		; CONTINUE IF OK
	CALL	NEWLINE
	PRTX(MZV_STRNOFNT)
	OR	$FF			; SIGNAL FAILURE
	RET
;
MZV_INIT1:
	CALL	MZV_VDARES		; RESET DISPLAY, CLEAR SCREEN
	CALL	MZK_INIT		; INITIALIZE KEYBOARD DRIVER
;
	; ADD OURSELVES TO VDA DISPATCH TABLE
	LD	BC,MZV_FNTBL		; BC := FUNCTION TABLE ADDRESS
	LD	DE,MZV_IDAT		; DE := INSTANCE DATA PTR
	CALL	VDA_ADDENT		; ADD ENTRY, A := UNIT ASSIGNED
;
	; INITIALIZE EMULATION
	LD	C,A			; C := ASSIGNED VIDEO DEVICE NUM
	LD	DE,MZV_FNTBL		; DE := FUNCTION TABLE ADDRESS
	LD	HL,MZV_IDAT		; HL := INSTANCE DATA PTR
	CALL	TERM_ATTACH		; DO IT
;
	; THERE IS NO OTHER CONSOLE ON THE MZ-800, SO THE TERMINAL IS
	; NORMALLY THE CONSOLE FROM HERE ON AND THIS LINE IS VISIBLE
	CALL	NEWLINE
	PRTX(MZV_STRINIT)
;
	XOR	A			; SIGNAL SUCCESS
	RET
;
;======================================================================
; MZV DRIVER - VIDEO DISPLAY ADAPTER (VDA) FUNCTIONS
;======================================================================
;
MZV_FNTBL:
	.DW	MZV_VDAINI
	.DW	MZV_VDAQRY
	.DW	MZV_VDARES
	.DW	MZV_VDADEV
	.DW	MZV_VDASCS
	.DW	MZV_VDASCP
	.DW	MZV_VDASAT
	.DW	MZV_VDASCO
	.DW	MZV_VDAWRC
	.DW	MZV_VDAFIL
	.DW	MZV_VDACPY
	.DW	MZV_VDASCR
	.DW	MZK_STAT
	.DW	MZK_FLUSH
	.DW	MZK_READ
	.DW	MZV_VDARDC
#IF (($ - MZV_FNTBL) != (VDA_FNCNT * 2))
	.ECHO	"*** INVALID MZV FUNCTION TABLE ***\n"
	!!!!!
#ENDIF
;
MZV_VDAINI:
	; CURRENTLY IGNORES VIDEO MODE AND BITMAP DATA
	JP	MZV_VDARES		; RESET VDA
;
MZV_VDAQRY:
	LD	C,$00			; MODE ZERO IS ALL WE KNOW
	LD	D,MZV_ROWS		; ROWS
	LD	E,MZV_COLS		; COLS
	LD	HL,0			; EXTRACTION OF BITMAP DATA NOT SUPPORTED
	XOR	A			; SIGNAL SUCCESS
	RET
;
MZV_VDARES:
	XOR	A
	LD	(MZV_INV),A		; NO REVERSE VIDEO
	LD	(MZV_UL),A		; NO UNDERLINE
	LD	(MZV_CURVIS),A		; CURSOR NOT DRAWN
	CALL	MZV_HWINIT		; PROGRAM GDG, CLEAR SCREEN
	LD	DE,0			; HOME
	LD	(MZV_POS),DE
	CALL	MZV_CURON		; SHOW CURSOR
	XOR	A			; SIGNAL SUCCESS
	RET
;
MZV_VDADEV:
	LD	D,VDADEV_MZV		; D := DEVICE TYPE
	LD	E,0			; E := PHYSICAL UNIT IS ALWAYS ZERO
	LD	H,0			; H := 0, DRIVER HAS NO MODES
	LD	L,MZV_DMD		; L := BASE I/O ADDRESS
	XOR	A			; SIGNAL SUCCESS
	RET
;
MZV_VDASCS:
	SYSCHKERR(ERR_NOTIMPL)		; NOT IMPLEMENTED (YET)
	RET
;
MZV_VDASCP:
	; D=ROW, E=COL
	CALL	MZV_CUROFF		; REMOVE CURSOR
	LD	(MZV_POS),DE		; NEW POSITION
	CALL	MZV_CURON		; SHOW CURSOR
	XOR	A			; SIGNAL SUCCESS
	RET
;
MZV_VDASAT:
	; E = -----RUB (R=REVERSE, U=UNDERLINE, B=BLINK)
	; BLINK IS NOT SUPPORTED
	XOR	A			; ASSUME OFF
	BIT	2,E			; REVERSE?
	JR	Z,MZV_VDASAT1		; IF NOT, SKIP
	DEC	A			; $FF
MZV_VDASAT1:
	LD	(MZV_INV),A		; SAVE REVERSE MASK
	XOR	A			; ASSUME OFF
	BIT	1,E			; UNDERLINE?
	JR	Z,MZV_VDASAT2		; IF NOT, SKIP
	DEC	A			; $FF
MZV_VDASAT2:
	LD	(MZV_UL),A		; SAVE UNDERLINE FLAG
	XOR	A			; SIGNAL SUCCESS
	RET
;
MZV_VDASCO:
	; MONOCHROME, COLORS ARE IGNORED
	XOR	A			; SIGNAL SUCCESS
	RET
;
MZV_VDAWRC:
	; E = CHARACTER, WRITTEN AT CURSOR, CURSOR ADVANCES
	CALL	MZV_CUROFF		; REMOVE CURSOR
	LD	A,E			; CHARACTER
	PUSH	AF			; SAVE IT
	LD	DE,(MZV_POS)		; CURRENT POSITION
	CALL	MZV_XY2ADR		; HL := CELL ADDRESS
	POP	AF			; RECOVER CHARACTER
	CALL	MZV_DRAW		; DRAW IT
	LD	DE,(MZV_POS)		; CURRENT POSITION
	CALL	MZV_NEXT		; ADVANCE
	LD	(MZV_POS),DE		; SAVE IT
	CALL	MZV_CURON		; SHOW CURSOR
	XOR	A			; SIGNAL SUCCESS
	RET
;
MZV_VDAFIL:
	; E = CHARACTER, HL = COUNT, FILL FROM CURSOR, CURSOR UNCHANGED
	CALL	MZV_CUROFF		; REMOVE CURSOR
	LD	A,E			; FILL CHARACTER
	LD	(MZV_FILCH),A		; SAVE IT
	LD	DE,(MZV_POS)		; START AT CURSOR
MZV_VDAFIL1:
	LD	A,H			; DONE?
	OR	L
	JR	Z,MZV_VDAFIL9		; IF SO, FINISH
	LD	A,E			; AT START OF A ROW?
	OR	A
	JR	NZ,MZV_VDAFIL2		; IF NOT, DO ONE CELL
	LD	BC,MZV_COLS		; AT LEAST ONE FULL ROW LEFT?
	OR	A			; CLEAR CARRY
	SBC	HL,BC
	JR	C,MZV_VDAFIL3		; IF NOT, UNDO AND DO ONE CELL
	CALL	MZV_FILROW		; FILL ROW D
	INC	D			; NEXT ROW
	LD	A,D
	CP	MZV_ROWS		; PAST BOTTOM?
	JR	C,MZV_VDAFIL1		; IF NOT, LOOP
	LD	D,0			; WRAP TO TOP
	JR	MZV_VDAFIL1		; LOOP
MZV_VDAFIL3:
	ADD	HL,BC			; UNDO SUBTRACTION
MZV_VDAFIL2:
	PUSH	HL			; SAVE COUNT
	PUSH	DE			; SAVE POSITION
	CALL	MZV_XY2ADR		; HL := CELL ADDRESS
	LD	A,(MZV_FILCH)		; FILL CHARACTER
	CALL	MZV_DRAW		; DRAW IT
	POP	DE			; RECOVER POSITION
	POP	HL			; RECOVER COUNT
	DEC	HL			; COUNT IT
	CALL	MZV_NEXT		; NEXT POSITION
	JR	MZV_VDAFIL1		; LOOP
MZV_VDAFIL9:
	CALL	MZV_CURON		; SHOW CURSOR
	XOR	A			; SIGNAL SUCCESS
	RET
;
MZV_VDACPY:
	; DE = SOURCE ROW/COL, HL = COUNT, DESTINATION IS THE CURSOR
	; POSITION, CURSOR UNCHANGED
	CALL	MZV_CUROFF		; REMOVE CURSOR
	LD	(MZV_CPYCNT),HL		; SAVE COUNT
	LD	(MZV_CPYSRC),DE		; SAVE SOURCE
	LD	BC,(MZV_POS)		; DESTINATION
	LD	(MZV_CPYDST),BC		; SAVE IT
;
	; WHOLE ROW FAST PATH (ANSI INSERT/DELETE LINE)
	LD	A,E			; SOURCE COLUMN
	OR	C			; DESTINATION COLUMN
	JR	NZ,MZV_VDACPY1		; NOT BOTH ZERO, GENERIC PATH
	LD	A,H			; COUNT MUST BE ONE ROW
	OR	A
	JR	NZ,MZV_VDACPY1
	LD	A,L
	CP	MZV_COLS
	JR	NZ,MZV_VDACPY1
	CALL	MZV_CPYROW		; COPY ROW D TO ROW B
	JR	MZV_VDACPY9		; DONE
;
MZV_VDACPY1:
	; GENERIC PATH, CELL BY CELL.  IF THE SOURCE IS BEFORE THE
	; DESTINATION, COPY BACKWARDS FROM THE END SO OVERLAPPING
	; RANGES WORK.
	CALL	MZV_XY2IDX		; HL := SOURCE INDEX
	PUSH	HL			; SAVE IT
	LD	D,B			; DESTINATION ROW/COL
	LD	E,C
	CALL	MZV_XY2IDX		; HL := DESTINATION INDEX
	POP	DE			; DE := SOURCE INDEX
	OR	A			; CLEAR CARRY
	SBC	HL,DE			; DESTINATION - SOURCE
	JR	Z,MZV_VDACPY9		; SAME PLACE, NOTHING TO DO
	JR	C,MZV_VDACPY4		; DESTINATION BEFORE SOURCE, FORWARD
;
	; BACKWARD: MOVE BOTH POSITIONS TO THE LAST CELL
	LD	HL,(MZV_CPYCNT)		; COUNT
	LD	A,H
	OR	L
	JR	Z,MZV_VDACPY9		; NOTHING TO COPY
	DEC	HL			; COUNT - 1
MZV_VDACPY2:
	LD	A,H			; ADVANCE COUNT - 1 TIMES
	OR	L
	JR	Z,MZV_VDACPY3
	DEC	HL
	LD	DE,(MZV_CPYSRC)
	CALL	MZV_NEXT
	LD	(MZV_CPYSRC),DE
	LD	DE,(MZV_CPYDST)
	CALL	MZV_NEXT
	LD	(MZV_CPYDST),DE
	JR	MZV_VDACPY2
MZV_VDACPY3:
	LD	A,$FF			; BACKWARD
	JR	MZV_VDACPY5
MZV_VDACPY4:
	XOR	A			; FORWARD
MZV_VDACPY5:
	LD	(MZV_CPYDIR),A		; SAVE DIRECTION
	LD	HL,(MZV_CPYCNT)		; COUNT
MZV_VDACPY6:
	LD	A,H			; DONE?
	OR	L
	JR	Z,MZV_VDACPY9
	PUSH	HL			; SAVE COUNT
	CALL	MZV_CPYCELL		; COPY ONE CELL
	LD	DE,(MZV_CPYSRC)		; STEP SOURCE
	CALL	MZV_STEP
	LD	(MZV_CPYSRC),DE
	LD	DE,(MZV_CPYDST)		; STEP DESTINATION
	CALL	MZV_STEP
	LD	(MZV_CPYDST),DE
	POP	HL			; RECOVER COUNT
	DEC	HL			; COUNT IT
	JR	MZV_VDACPY6		; LOOP
;
MZV_VDACPY9:
	CALL	MZV_CURON		; SHOW CURSOR
	XOR	A			; SIGNAL SUCCESS
	RET
;
MZV_VDASCR:
	; E = LINES TO SCROLL, POSITIVE = FORWARD (UP), NEGATIVE = REVERSE
	CALL	MZV_CUROFF		; REMOVE CURSOR
MZV_VDASCR1:
	LD	A,E			; LINES LEFT
	OR	A			; SET FLAGS
	JR	Z,MZV_VDASCR9		; DONE IF ZERO
	PUSH	DE			; SAVE COUNT
	JP	M,MZV_VDASCR2		; NEGATIVE, REVERSE SCROLL
	CALL	MZV_SCRUP		; FORWARD ONE LINE
	POP	DE			; RECOVER COUNT
	DEC	E			; COUNT IT
	JR	MZV_VDASCR1		; LOOP
MZV_VDASCR2:
	CALL	MZV_SCRDN		; REVERSE ONE LINE
	POP	DE			; RECOVER COUNT
	INC	E			; COUNT IT
	JR	MZV_VDASCR1		; LOOP
MZV_VDASCR9:
	CALL	MZV_CURON		; SHOW CURSOR
	XOR	A			; SIGNAL SUCCESS
	RET
;
MZV_VDARDC:
	; READING CHARACTERS BACK IS NOT SUPPORTED
	OR	$FF			; UNSUPPORTED FUNCTION
	RET
;
;======================================================================
; MZV DRIVER - PRIVATE DRIVER FUNCTIONS
;======================================================================
;
;----------------------------------------------------------------------
; PROGRAM THE GDG FOR 640X200 MONOCHROME, NO SCROLL, CLEAR THE SCREEN
;----------------------------------------------------------------------
;
MZV_HWINIT:
	LD	A,$04			; 640X200, 2 COLORS, MZ-800 MODE
	OUT	(MZV_DMD),A
	LD	A,$00 | MZV_BG		; PALETTE 0 := BACKGROUND
	OUT	(MZV_PAL),A
	LD	A,$10 | MZV_FG		; PALETTE 1 := FOREGROUND
	OUT	(MZV_PAL),A
	LD	A,MZV_BG		; BORDER := BACKGROUND
	LD	BC,MZV_BCOL
	OUT	(C),A
	LD	A,$01			; WF: SINGLE WRITE, PLANE I
	OUT	(MZV_WF),A
	LD	A,$01			; RF: SINGLE READ, PLANE I
	OUT	(MZV_RF),A
	LD	HL,0			; NO SCROLL OFFSET
	CALL	MZV_SETSOF		; MUST BE ZERO BEFORE AREA CHANGES
	XOR	A			; SCROLL AREA IS THE WHOLE SCREEN
	LD	BC,MZV_SSA
	OUT	(C),A
	LD	A,MZV_SWVAL
	LD	BC,MZV_SEA
	OUT	(C),A
	LD	BC,MZV_SW
	OUT	(C),A
;
	; CLEAR THE WHOLE BITMAP
	CALL	MZV_VON			; MAP VRAM
	LD	HL,MZV_VRAM		; FILL FROM START
	LD	DE,MZV_VRAM + 1
	LD	BC,(MZV_ROWSZ * MZV_ROWS) - 1
	LD	(HL),0
	LDIR
	JP	MZV_VOFF		; UNMAP VRAM AND RETURN
;
;----------------------------------------------------------------------
; MAP VRAM (AND CG-ROM) WITH INTERRUPTS DISABLED, AND UNMAP IT AGAIN.
; MZV_VOFF ENABLES INTERRUPTS ONLY IF HBIOS HAS ENABLED THEM.
; A IS DESTROYED.
;----------------------------------------------------------------------
;
MZV_VON:
	HB_DI				; NO INTERRUPTS WHILE MAPPED
	IN	A,(MZV_VRAMON)		; MAP VRAM AND CG-ROM
	RET
;
MZV_VOFF:
	IN	A,(MZV_VRAMOFF)		; UNMAP VRAM AND CG-ROM
#IF (INTMODE > 0)
	LD	A,(INTSENAB)		; INTERRUPTS ENABLED BY HBIOS?
	OR	A
	RET	Z			; IF NOT, LEAVE THEM OFF
	EI				; ELSE ENABLE AGAIN
#ENDIF
	RET
;
;----------------------------------------------------------------------
; LOAD THE 8X8 FONT INTO MZV_FONT, MIRRORING EVERY BYTE BECAUSE THE
; MZ-800 SHOWS BIT 0 AS THE LEFTMOST PIXEL.  RETURNS NZ ON ERROR.
;----------------------------------------------------------------------
;
MZV_LOADFONT:
	LD	A,FONTID_8X8		; DESIRED FONT
	CALL	FNT_SELECT		; SELECT IT
	RET	NZ			; ERROR RETURN
	LD	HL,MZV_FONT		; DESTINATION
	LD	DE,256 * 8		; BYTE COUNT
MZV_LOADFONT1:
	CALL	FNT_NEXT		; A := NEXT FONT BYTE
	LD	C,A			; MIRROR IT INTO A
	LD	B,8
MZV_LOADFONT2:
	RR	C			; LOW BIT OF C INTO CARRY
	RLA				; CARRY INTO LOW BIT OF A
	DJNZ	MZV_LOADFONT2
	LD	(HL),A			; STORE MIRRORED BYTE
	INC	HL
	DEC	DE			; COUNT IT
	LD	A,D
	OR	E
	JR	NZ,MZV_LOADFONT1	; LOOP TILL DONE
	XOR	A			; SIGNAL SUCCESS
	RET
;
;----------------------------------------------------------------------
; CELL ADDRESS: HL := VRAM ADDRESS OF ROW D, COLUMN E
; ROW * 640 = (ROW * 5) * 128.  ONLY HL AND A ARE CHANGED.
;----------------------------------------------------------------------
;
MZV_XY2ADR:
	LD	A,D			; ROW
	ADD	A,A			; * 2
	ADD	A,A			; * 4
	ADD	A,D			; * 5
	LD	H,A			; HL := ROW * 5 * 256
	LD	L,0
	SRL	H			; HL := ROW * 5 * 128
	RR	L
	LD	A,H			; ADD VRAM BASE
	OR	MZV_VRAM >> 8
	LD	H,A
	LD	A,L			; ADD COLUMN
	ADD	A,E
	LD	L,A
	RET	NC
	INC	H
	RET
;
;----------------------------------------------------------------------
; LINEAR INDEX: HL := ROW D * 80 + COLUMN E.  ONLY HL AND A ARE CHANGED.
;----------------------------------------------------------------------
;
MZV_XY2IDX:
	PUSH	DE			; SAVE ROW/COL
	LD	L,D			; HL := ROW
	LD	H,0
	ADD	HL,HL			; * 2
	ADD	HL,HL			; * 4
	ADD	HL,HL			; * 8
	ADD	HL,HL			; * 16
	LD	E,L			; DE := ROW * 16
	LD	D,H
	ADD	HL,HL			; * 32
	ADD	HL,HL			; * 64
	ADD	HL,DE			; * 80
	POP	DE			; RECOVER ROW/COL
	LD	A,E			; ADD COLUMN
	ADD	A,L
	LD	L,A
	RET	NC
	INC	H
	RET
;
;----------------------------------------------------------------------
; NEXT / PREVIOUS POSITION WITH WRAP: D=ROW, E=COL.  ONLY DE, A CHANGED.
; MZV_STEP GOES FORWARD OR BACKWARD ACCORDING TO MZV_CPYDIR.
;----------------------------------------------------------------------
;
MZV_STEP:
	LD	A,(MZV_CPYDIR)		; DIRECTION
	OR	A			; FORWARD?
	JR	NZ,MZV_PREV		; IF NOT, GO BACKWARD
;
MZV_NEXT:
	INC	E			; NEXT COLUMN
	LD	A,E
	CP	MZV_COLS		; PAST RIGHT EDGE?
	RET	C			; IF NOT, DONE
	LD	E,0			; FIRST COLUMN
	INC	D			; NEXT ROW
	LD	A,D
	CP	MZV_ROWS		; PAST BOTTOM?
	RET	C			; IF NOT, DONE
	LD	D,0			; WRAP TO TOP
	RET
;
MZV_PREV:
	DEC	E			; PREVIOUS COLUMN
	RET	P			; DONE IF STILL >= 0
	LD	E,MZV_COLS - 1		; LAST COLUMN
	DEC	D			; PREVIOUS ROW
	RET	P			; DONE IF STILL >= 0
	LD	D,MZV_ROWS - 1		; WRAP TO BOTTOM
	RET
;
;----------------------------------------------------------------------
; GLYPH ADDRESS: DE := FONT ADDRESS OF CHARACTER A.  HL PRESERVED.
;----------------------------------------------------------------------
;
MZV_GLYPH:
	PUSH	HL			; SAVE HL
	LD	L,A			; HL := CHAR * 8
	LD	H,0
	ADD	HL,HL
	ADD	HL,HL
	ADD	HL,HL
	LD	DE,MZV_FONT		; + FONT BASE
	ADD	HL,DE
	EX	DE,HL			; DE := GLYPH
	POP	HL			; RECOVER HL
	RET
;
;----------------------------------------------------------------------
; DRAW CHARACTER A INTO THE CELL AT VRAM ADDRESS HL USING THE CURRENT
; ATTRIBUTES.  BC, DE, HL ARE DESTROYED.
;----------------------------------------------------------------------
;
MZV_DRAW:
	CALL	MZV_GLYPH		; DE := GLYPH
	LD	A,(MZV_INV)		; C := REVERSE MASK
	LD	C,A
	LD	B,7			; FIRST 7 LINES
	CALL	MZV_VON			; MAP VRAM
MZV_DRAW1:
	LD	A,(DE)			; GLYPH LINE
	XOR	C			; APPLY REVERSE
	LD	(HL),A			; TO VRAM
	INC	DE			; NEXT GLYPH LINE
	LD	A,L			; NEXT RASTER LINE
	ADD	A,MZV_LINE
	LD	L,A
	JR	NC,MZV_DRAW2
	INC	H
MZV_DRAW2:
	DJNZ	MZV_DRAW1		; LOOP
	LD	A,(MZV_UL)		; UNDERLINE?
	OR	A
	LD	A,(DE)			; LAST GLYPH LINE
	JR	Z,MZV_DRAW3		; IF NO UNDERLINE, USE IT
	LD	A,$FF			; ELSE A FULL LINE
MZV_DRAW3:
	XOR	C			; APPLY REVERSE
	LD	(HL),A			; TO VRAM
	JP	MZV_VOFF		; UNMAP VRAM AND RETURN
;
;----------------------------------------------------------------------
; FILL TEXT ROW D WITH CHARACTER (MZV_FILCH) USING THE CURRENT
; ATTRIBUTES.  ALL REGISTERS EXCEPT AF ARE PRESERVED.
;----------------------------------------------------------------------
;
MZV_FILROW:
	PUSH	BC			; SAVE REGS
	PUSH	DE
	PUSH	HL
	LD	E,0			; COLUMN 0
	CALL	MZV_XY2ADR		; HL := ROW ADDRESS
	LD	A,(MZV_FILCH)		; CHARACTER
	CALL	MZV_GLYPH		; DE := GLYPH
	LD	B,8			; 8 RASTER LINES
	CALL	MZV_VON			; MAP VRAM
MZV_FILROW1:
	LD	A,(MZV_INV)		; REVERSE MASK
	LD	C,A			; ... IN C
	LD	A,B			; LAST LINE?
	DEC	A
	JR	NZ,MZV_FILROW2		; IF NOT, NORMAL
	LD	A,(MZV_UL)		; UNDERLINE?
	OR	A
	JR	Z,MZV_FILROW2		; IF NOT, NORMAL
	LD	A,$FF			; FULL LINE
	JR	MZV_FILROW3
MZV_FILROW2:
	LD	A,(DE)			; GLYPH LINE
MZV_FILROW3:
	XOR	C			; APPLY REVERSE
	PUSH	BC			; SAVE LINE COUNT
	PUSH	DE			; SAVE GLYPH POINTER
	LD	(HL),A			; FIRST BYTE OF THE LINE
	LD	D,H			; REPLICATE ACROSS THE LINE
	LD	E,L
	INC	DE
	LD	BC,MZV_LINE - 1
	LDIR
	EX	DE,HL			; HL := START OF NEXT LINE
	POP	DE			; RECOVER GLYPH POINTER
	POP	BC			; RECOVER LINE COUNT
	INC	DE			; NEXT GLYPH LINE
	DJNZ	MZV_FILROW1		; LOOP
	CALL	MZV_VOFF		; UNMAP VRAM
	POP	HL			; RESTORE REGS
	POP	DE
	POP	BC
	RET
;
;----------------------------------------------------------------------
; COPY TEXT ROW D TO TEXT ROW B (640 BYTES)
;----------------------------------------------------------------------
;
MZV_CPYROW:
	LD	E,0			; COLUMN 0
	CALL	MZV_XY2ADR		; HL := SOURCE ROW ADDRESS
	PUSH	HL			; SAVE IT
	LD	D,B			; DESTINATION ROW
	CALL	MZV_XY2ADR		; HL := DESTINATION ROW ADDRESS
	EX	DE,HL			; DE := DESTINATION
	POP	HL			; HL := SOURCE
	LD	BC,MZV_ROWSZ		; ONE TEXT ROW
	CALL	MZV_VON			; MAP VRAM
	LDIR				; COPY
	JP	MZV_VOFF		; UNMAP VRAM AND RETURN
;
;----------------------------------------------------------------------
; COPY ONE CELL FROM (MZV_CPYSRC) TO (MZV_CPYDST)
;----------------------------------------------------------------------
;
MZV_CPYCELL:
	LD	DE,(MZV_CPYDST)		; DESTINATION POSITION
	CALL	MZV_XY2ADR		; HL := DESTINATION ADDRESS
	PUSH	HL			; SAVE IT
	LD	DE,(MZV_CPYSRC)		; SOURCE POSITION
	CALL	MZV_XY2ADR		; HL := SOURCE ADDRESS
	POP	DE			; DE := DESTINATION ADDRESS
	LD	B,8			; 8 RASTER LINES
	LD	C,MZV_LINE		; LINE STRIDE
	CALL	MZV_VON			; MAP VRAM
MZV_CPYCELL1:
	LD	A,(HL)			; COPY ONE BYTE
	LD	(DE),A
	LD	A,L			; NEXT SOURCE LINE
	ADD	A,C
	LD	L,A
	JR	NC,MZV_CPYCELL2
	INC	H
MZV_CPYCELL2:
	LD	A,E			; NEXT DESTINATION LINE
	ADD	A,C
	LD	E,A
	JR	NC,MZV_CPYCELL3
	INC	D
MZV_CPYCELL3:
	DJNZ	MZV_CPYCELL1		; LOOP
	JP	MZV_VOFF		; UNMAP VRAM AND RETURN
;
;----------------------------------------------------------------------
; HARDWARE SCROLL ONE TEXT ROW UP (MZV_SCRUP) OR DOWN (MZV_SCRDN) AND
; CLEAR THE ROW THAT COMES INTO VIEW
;----------------------------------------------------------------------
;
MZV_SCRUP:
	LD	HL,(MZV_SOF)		; CURRENT OFFSET
	LD	DE,MZV_SOFROW		; + ONE TEXT ROW
	ADD	HL,DE
	LD	DE,MZV_SOFMAX		; WRAP AT SOFMAX
	OR	A
	SBC	HL,DE
	JR	NC,MZV_SCRUP1		; IF >= SOFMAX, KEEP WRAPPED VALUE
	ADD	HL,DE			; ELSE UNDO
MZV_SCRUP1:
	CALL	MZV_SETSOF		; SET IT
	LD	D,MZV_ROWS - 1		; CLEAR BOTTOM ROW
	JR	MZV_CLRROW
;
MZV_SCRDN:
	LD	HL,(MZV_SOF)		; CURRENT OFFSET
	LD	DE,MZV_SOFROW		; - ONE TEXT ROW
	OR	A
	SBC	HL,DE
	JR	NC,MZV_SCRDN1		; IF >= 0, OK
	LD	DE,MZV_SOFMAX		; ELSE WRAP
	ADD	HL,DE
MZV_SCRDN1:
	CALL	MZV_SETSOF		; SET IT
	LD	D,0			; CLEAR TOP ROW
;
MZV_CLRROW:
	LD	A,' '			; BLANKS
	LD	(MZV_FILCH),A
	JP	MZV_FILROW		; FILL ROW D AND RETURN
;
MZV_SETSOF:
	; SET SCROLL OFFSET TO HL (0 .. MZV_SOFMAX - 1)
	LD	(MZV_SOF),HL		; SAVE IT
	LD	A,L			; LOW 8 BITS
	LD	BC,MZV_SOFL
	OUT	(C),A
	LD	A,H			; HIGH 2 BITS
	LD	BC,MZV_SOFH
	OUT	(C),A
	RET
;
;----------------------------------------------------------------------
; CURSOR: AN INVERTED BOTTOM RASTER LINE OF THE CELL AT MZV_POS.
; MZV_CURON DRAWS IT, MZV_CUROFF REMOVES IT, EACH ONLY IF NEEDED.
; ALL REGISTERS EXCEPT AF ARE PRESERVED.
;----------------------------------------------------------------------
;
MZV_CURON:
	LD	A,(MZV_CURVIS)		; ALREADY DRAWN?
	OR	A
	RET	NZ			; IF SO, DONE
	JR	MZV_CURTOG		; ELSE DRAW IT
;
MZV_CUROFF:
	LD	A,(MZV_CURVIS)		; DRAWN?
	OR	A
	RET	Z			; IF NOT, DONE
;
MZV_CURTOG:
	CPL				; TOGGLE FLAG
	LD	(MZV_CURVIS),A
	PUSH	DE			; SAVE REGS
	PUSH	HL
	LD	DE,(MZV_POS)		; CURSOR POSITION
	CALL	MZV_XY2ADR		; HL := CELL ADDRESS
	LD	DE,MZV_LINE * 7		; BOTTOM RASTER LINE
	ADD	HL,DE
	CALL	MZV_VON			; MAP VRAM
	LD	A,(HL)			; INVERT THE LINE
	CPL
	LD	(HL),A
	CALL	MZV_VOFF		; UNMAP VRAM
	POP	HL			; RESTORE REGS
	POP	DE
	RET
;
;==================================================================================================
;   MZV DRIVER - DATA
;==================================================================================================
;
MZV_POS		.DW	0		; CURSOR POSITION (LOW = COLUMN, HIGH = ROW)
MZV_SOF		.DW	0		; CURRENT HARDWARE SCROLL OFFSET
MZV_INV		.DB	0		; $FF = REVERSE VIDEO
MZV_UL		.DB	0		; $FF = UNDERLINE
MZV_CURVIS	.DB	0		; NON-ZERO WHEN THE CURSOR IS DRAWN
MZV_FILCH	.DB	' '		; CHARACTER FOR ROW FILLS
MZV_CPYSRC	.DW	0		; VDACPY SOURCE POSITION
MZV_CPYDST	.DW	0		; VDACPY DESTINATION POSITION
MZV_CPYCNT	.DW	0		; VDACPY COUNT
MZV_CPYDIR	.DB	0		; VDACPY DIRECTION ($FF = BACKWARD)
;
MZV_FONT	.FILL	256 * 8,0	; MIRRORED 8X8 FONT
;
; PRTS() TRUNCATES LONG STRINGS (TASM MACRO ARGUMENT LIMIT), SO THESE
; ARE PRINTED WITH PRTX()
;
MZV_STRINIT	.DB	"MZV: MODE=640X200 TEXT=80X25$"
MZV_STRNOFNT	.DB	"MZV: FONT NOT FOUND$"
