;==================================================================================================
;   UNICARD RAM DISK DRIVER (SHARP MZ-700/800/1500 UNICARD, MZ-1R18 COMPATIBLE PORTS)
;==================================================================================================
;
; THE UNICARD EMULATES THE SHARP MZ-1R18 RAM DISK WITH AN IMAGE FILE ON ITS SD CARD (NAMED IN
; /UNICARD/RAMDISC.CFG), 64K TO 16M.  THE SAME PORTS ARE USED BY MZPICO AND THE MZ-1R18 ITSELF:
;
;   $E9 (OUT)	BANK OF 64K
;   $EB (OUT)	ADDRESS: LOW BYTE AS DATA, HIGH BYTE ON A8-A15, SO OUT (C),R WITH B = HIGH BYTE
;   $EA (I/O)	DATA, THE ADDRESS INCREMENTS AFTER EVERY ACCESS (WRAPS INSIDE THE BANK)
;
; EVERY ACCESS HOLDS THE CPU IN WAIT UNTIL THE CARD IS DONE, SO INIR/OTIR WORK.  BANKS ABOVE THE
; IMAGE SIZE ALIAS ONTO LOWER BANKS (MASK OR MODULO), WHICH IS HOW THE SIZE IS DETECTED.
;
; PRESENTATION:
;   8M OR MORE:	MID_HD WITH A SYNTHESIZED MBR AT LBA 0 HOLDING ONE CP/M PARTITION (TYPE $2E)
;		FROM LBA 1 OVER WHOLE 8M SLICES.  PHYSICAL SECTOR N IS LBA N + 1.  A 16M IMAGE
;		IS THEN EXACTLY TWO HD1K SLICES WITHOUT A PREFIX, SO THE RAW IMAGE FILE CAN BE
;		USED ON A PC WITH CPMTOOLS (WBW_HD1K, OFFSETS 0 AND 8M).  THE MBR IS READ ONLY.
;   4M TO 8M:	MID_RF (4M RAM FLOPPY FORMAT) OVER THE FIRST 4M, PHYSICAL SECTOR N IS LBA N.
;   SMALLER:	NOT USED.
;
UCRD_BANK	.EQU	$E9		; BANK REGISTER
UCRD_DATA	.EQU	$EA		; DATA PORT
UCRD_ADDR	.EQU	$EB		; ADDRESS REGISTER (HIGH BYTE ON A8-A15)
;
UCRD_TESTADR	.EQU	$01F0		; TEST LOCATION IN EVERY BANK (INSIDE SECTOR 0 OF THE BANK)
UCRD_SPS	.EQU	16384		; SECTORS PER HD1K SLICE (8M)
;
; DEVICE STATUS / MODE (UCRD_MODE)
UCRD_MNONE	.EQU	0		; NO USABLE RAM DISK
UCRD_MRF	.EQU	1		; 4M RAM FLOPPY
UCRD_MHD	.EQU	2		; HARD DISK WITH SYNTHESIZED MBR
;
	DEVECHO	"UCRD: IO="
	DEVECHO	UCRD_BANK
	DEVECHO	"\n"
;
;--------------------------------------------------------------------------------------------------
;   HBIOS MODULE HEADER
;--------------------------------------------------------------------------------------------------
;
ORG_UCRD	.EQU	$
;
	.DW	SIZ_UCRD		; MODULE SIZE
	.DW	UCRD_INITPHASE		; ADR OF INIT PHASE HANDLER
;
UCRD_INITPHASE:
	; INIT PHASE HANDLER, A=PHASE
	CP	HB_PHASE_INIT		; INIT PHASE?
	JP	Z,UCRD_INIT		; DO INIT
	RET				; DONE
;
; DEVICE CONFIG (ONE UNIT), IY POINTS HERE FOR THE DISK FUNCTIONS
;
UCRD_CFG:
UCRD_DEV	.DB	0		; DRIVER DEVICE NUMBER
UCRD_STAT	.DB	0		; DEVICE STATUS
UCRD_LBA	.DW	0,0		; CURRENT LBA
;
UCRD_CFG_LBA	.EQU	UCRD_LBA - UCRD_CFG
;
;--------------------------------------------------------------------------------------------------
;   INITIALIZATION
;--------------------------------------------------------------------------------------------------
;
UCRD_INIT:
	CALL	NEWLINE			; FORMATTING
	PRTS("UCRD: IO=0x$")
	LD	A,UCRD_BANK
	CALL	PRTHEXBYTE
;
	CALL	UCRD_SIZE		; A := NUMBER OF 64K BANKS (0 = 256), CF = NONE
	LD	(UCRD_BANKS),A
	JR	NC,UCRD_INIT1
	PRTS(" NOT PRESENT$")
	OR	$FF			; SIGNAL FAILURE
	RET
;
UCRD_INIT1:
	; DISPLAY SIZE IN KB (BANKS * 64)
	PRTS(" SIZE=$")
	LD	L,A			; HL := BANKS (1-256, 0 MEANS 256)
	LD	H,0
	OR	A
	JR	NZ,UCRD_INIT2
	INC	H			; 256 BANKS
UCRD_INIT2:
	ADD	HL,HL			; * 64
	ADD	HL,HL
	ADD	HL,HL
	ADD	HL,HL
	ADD	HL,HL
	ADD	HL,HL
	CALL	PRTDEC
	PRTS("KB$")
;
	; CHOOSE THE PRESENTATION
	LD	A,(UCRD_BANKS)
	OR	A			; 256 BANKS (16M)?
	JR	Z,UCRD_INIT3
	CP	128			; 8M OR MORE?
	JR	NC,UCRD_INIT3
	CP	64			; 4M OR MORE?
	JR	NC,UCRD_INIT4
	PRTS(" TOO SMALL$")
	XOR	A			; NOT USABLE, BUT NOT AN ERROR
	RET
;
UCRD_INIT3:
	; HARD DISK: SLICES := BANKS / 128, PARTITION := SLICES * 16384 SECTORS
	LD	A,UCRD_MHD
	LD	(UCRD_MODE),A
	LD	A,(UCRD_BANKS)
	OR	A
	LD	B,2			; 256 BANKS: 2 SLICES
	JR	Z,UCRD_INIT3A
	LD	B,1			; 128-255 BANKS: 1 SLICE
UCRD_INIT3A:
	LD	A,B
	LD	(UCRD_SLICES),A
	PRTS(" SLICES=$")
	CALL	PRTDECB
	JR	UCRD_INIT5
;
UCRD_INIT4:
	LD	A,UCRD_MRF		; 4M RAM FLOPPY
	LD	(UCRD_MODE),A
	PRTS(" RAMF=4MB$")
;
UCRD_INIT5:
	LD	BC,UCRD_FNTBL		; BC := FUNC TABLE ADR
	LD	DE,UCRD_CFG		; DE := CONFIG
	CALL	DIO_ADDENT		; ADD ENTRY
	XOR	A			; INIT SUCCEEDED
	RET
;
;--------------------------------------------------------------------------------------------------
; IMAGE SIZE: A := NUMBER OF 64K BANKS (1-255, 0 = 256), CARRY SET IF THERE IS NO RAM DISK.
; A TEST BYTE IN BANK 0 IS COMPARED WITH THE SAME BYTE OF BANKS 1, 2, ...: THE FIRST BANK THAT
; ALIASES BANK 0 GIVES THE SIZE.  ALL TEST BYTES ARE RESTORED.
;--------------------------------------------------------------------------------------------------
;
UCRD_SIZE:
	; PRESENCE: BANK 0 TEST BYTE MUST HOLD WHAT IS WRITTEN
	XOR	A
	CALL	UCRD_RDTST		; A := BANK 0 TEST BYTE
	LD	(UCRD_SAVE0),A		; SAVE IT
	LD	E,$A5			; FIRST PATTERN
	XOR	A
	CALL	UCRD_WRTST
	XOR	A
	CALL	UCRD_RDTST
	CP	$A5
	JR	NZ,UCRD_SIZE9		; NOT STORED: NO RAM DISK
	LD	E,$5A			; SECOND PATTERN
	XOR	A
	CALL	UCRD_WRTST
	XOR	A
	CALL	UCRD_RDTST
	CP	$5A
	JR	NZ,UCRD_SIZE9		; NOT STORED: NO RAM DISK
;
	; BANK 0 HOLDS $5A.  FOR BANK N = 1, 2, ...: SAVE ITS BYTE, WRITE $A5, CHECK BANK 0.
	LD	C,1			; BANK N
UCRD_SIZE1:
	LD	A,C
	CALL	UCRD_RDTST		; SAVE BANK N TEST BYTE
	LD	D,A
	LD	E,$A5
	LD	A,C
	CALL	UCRD_WRTST		; BANK N := $A5
	XOR	A
	CALL	UCRD_RDTST		; BANK 0 CHANGED?
	CP	$A5
	JR	Z,UCRD_SIZE2		; YES: BANK N IS BANK 0, SIZE = N
	LD	E,D			; NO: RESTORE BANK N
	LD	A,C
	CALL	UCRD_WRTST
	INC	C			; NEXT BANK
	JR	NZ,UCRD_SIZE1		; UP TO 255
	; NO ALIAS UP TO BANK 255: 256 BANKS (C = 0)
UCRD_SIZE2:
	LD	A,(UCRD_SAVE0)		; RESTORE BANK 0 (= BANK N)
	LD	E,A
	XOR	A
	CALL	UCRD_WRTST
	LD	A,C			; SIZE IN BANKS
	OR	A			; CLEAR CARRY: PRESENT
	RET
;
UCRD_SIZE9:
	LD	A,(UCRD_SAVE0)		; RESTORE AND REPORT NONE
	LD	E,A
	XOR	A
	CALL	UCRD_WRTST
	SCF				; CARRY: NO RAM DISK
	RET
;
UCRD_RDTST:
	; A := TEST BYTE OF BANK A
	OUT	(UCRD_BANK),A
	PUSH	BC
	LD	BC,(UCRD_TESTADR & $FF00) | UCRD_ADDR
	LD	A,UCRD_TESTADR & $FF
	OUT	(C),A
	POP	BC
	IN	A,(UCRD_DATA)
	RET
;
UCRD_WRTST:
	; TEST BYTE OF BANK A := E
	OUT	(UCRD_BANK),A
	PUSH	BC
	LD	BC,(UCRD_TESTADR & $FF00) | UCRD_ADDR
	LD	A,UCRD_TESTADR & $FF
	OUT	(C),A
	POP	BC
	LD	A,E
	OUT	(UCRD_DATA),A
	RET
;
;--------------------------------------------------------------------------------------------------
;   DISK FUNCTIONS
;--------------------------------------------------------------------------------------------------
;
UCRD_FNTBL:
	.DW	UCRD_STATUS
	.DW	UCRD_RESET
	.DW	UCRD_SEEK
	.DW	UCRD_READ
	.DW	UCRD_WRITE
	.DW	UCRD_VERIFY
	.DW	UCRD_FORMAT
	.DW	UCRD_DEVICE
	.DW	UCRD_MEDIA
	.DW	UCRD_DEFMED
	.DW	UCRD_CAP
	.DW	UCRD_GEOM
#IF (($ - UCRD_FNTBL) != (DIO_FNCNT * 2))
	.ECHO	"*** INVALID UCRD FUNCTION TABLE ***\n"
	!!!!!
#ENDIF
;
UCRD_VERIFY:
UCRD_FORMAT:
UCRD_DEFMED:
	SYSCHKERR(ERR_NOTIMPL)		; INVALID SUB-FUNCTION
	RET
;
UCRD_STATUS:
UCRD_RESET:
	XOR	A			; ALWAYS OK
	RET
;
UCRD_CAP:
	; DE:HL := NUMBER OF 512 BYTE SECTORS, BC := 512
	LD	BC,512
	LD	A,(UCRD_MODE)
	CP	UCRD_MHD
	JR	Z,UCRD_CAP1
	LD	DE,0			; RAM FLOPPY: 4M = 8192 SECTORS
	LD	HL,8192
	XOR	A
	RET
UCRD_CAP1:
	; HARD DISK: BANKS * 128 SECTORS + 1 (THE SYNTHESIZED MBR)
	LD	DE,0
	LD	A,(UCRD_BANKS)		; BANKS (0 = 256)
	LD	H,A			; HL := BANKS * 256
	LD	L,0
	OR	A
	JR	NZ,UCRD_CAP2
	LD	HL,$8000		; 256 BANKS: $8000 SECTORS
	JR	UCRD_CAP3
UCRD_CAP2:
	SRL	H			; BANKS * 128 = BANKS * 256 / 2
	RR	L
UCRD_CAP3:
	INC	HL			; + MBR
	XOR	A
	RET
;
UCRD_GEOM:
	; FOR LBA, WE SIMULATE CHS ACCESS USING 16 HEADS AND 16 SECTORS
	; RETURN HS:CC -> DE:HL, SET HIGH BIT OF D TO INDICATE LBA CAPABLE
	CALL	UCRD_CAP		; GET TOTAL BLOCKS IN DE:HL, BLOCK SIZE TO BC
	LD	L,H			; DIVIDE BY 256 FOR # TRACKS
	LD	H,E			; ... HIGH BYTE DISCARDED, RESULT IN HL
	LD	D,16 | $80		; HEADS / CYL = 16, SET LBA CAPABILITY BIT
	LD	E,16			; SECTORS / TRACK = 16
	RET				; DONE, A STILL HAS UCRD_CAP STATUS
;
UCRD_DEVICE:
	LD	D,DIODEV_UCRD		; D := DEVICE TYPE
	LD	E,(IY+0)		; E := PHYSICAL DEVICE NUMBER
	LD	A,(UCRD_MODE)
	CP	UCRD_MHD
	LD	C,%00010111		; C := ATTRIBUTES, NON-REMOVABLE RAM FLOPPY
	JR	NZ,UCRD_DEVICE1
	LD	C,%00110101		; ... OR HIGH CAPACITY RAM DISK (HARD DISK STYLE)
UCRD_DEVICE1:
	LD	H,0			; H := 0, DRIVER HAS NO MODES
	LD	L,UCRD_BANK		; L := BASE I/O ADDRESS
	XOR	A			; SIGNAL SUCCESS
	RET
;
UCRD_MEDIA:
	LD	A,(UCRD_MODE)
	CP	UCRD_MHD
	LD	E,MID_HD		; HARD DISK (SLICES FROM THE MBR)
	JR	Z,UCRD_MEDIA1
	LD	E,MID_RF		; 4M RAM FLOPPY
UCRD_MEDIA1:
	LD	D,0			; D:0=0 MEANS NO MEDIA CHANGE
	XOR	A			; SIGNAL SUCCESS
	RET
;
UCRD_SEEK:
	BIT	7,D			; CHECK FOR LBA FLAG
	CALL	Z,HB_CHS2LBA		; CLEAR MEANS CHS, CONVERT TO LBA
	RES	7,D			; CLEAR FLAG REGARDLESS (DOES NO HARM IF ALREADY LBA)
	LD	(UCRD_LBA+0),HL		; SAVE NEW LBA
	LD	(UCRD_LBA+2),DE
	XOR	A			; SIGNAL SUCCESS
	RET				; AND RETURN
;
; THE HBIOS DISK SUPERVISOR CALLS THE CODE AFTER "CALL HB_DSKREAD/WRITE" ONCE PER SECTOR WITH
; HL = BUFFER
;
UCRD_READ:
	CALL	HB_DSKREAD		; HOOK HBIOS DISK READ SUPERVISOR
	XOR	A			; READ
	JR	UCRD_RW			; CONTINUE TO GENERIC R/W ROUTINE
;
UCRD_WRITE:
	CALL	HB_DSKWRITE		; HOOK HBIOS DISK WRITE SUPERVISOR
	LD	A,1			; WRITE
;
UCRD_RW:
	LD	(UCRD_ISWR),A		; SAVE DIRECTION
	LD	(UCRD_DSKBUF),HL	; SAVE DISK BUFFER ADDRESS
	CALL	UCRD_PHYS		; SET UP THE PHYSICAL SECTOR, Z IF IT IS THE MBR
	JR	NZ,UCRD_RW1
	; THE SYNTHESIZED MBR
	LD	A,(UCRD_ISWR)		; WRITE?
	OR	A
	JR	NZ,UCRD_RW4		; THE MBR IS READ ONLY
	CALL	UCRD_MBR		; BUILD IT IN THE BUFFER
	JR	UCRD_RW2
UCRD_RW1:
	LD	A,(UCRD_ISWR)		; READ OR WRITE THE SECTOR
	OR	A
	JR	NZ,UCRD_RW1W
	CALL	UCRD_RDSEC
	JR	UCRD_RW2
UCRD_RW1W:
	CALL	UCRD_WRSEC
UCRD_RW2:
	; INCREMENT LBA AND BUFFER
	LD	HL,UCRD_LBA		; INCREMENT THE LBA
	CALL	INC32HL
	LD	HL,UCRD_DSKBUF+1	; BUMP DMA BY
	INC	(HL)			; ... 512 BYTES
	INC	(HL)
	LD	HL,(UCRD_DSKBUF)	; CURRENT DMA TO HL
	XOR	A			; SIGNAL SUCCESS
	RET
UCRD_RW4:
	LD	E,0			; ZERO SECTORS WRITTEN
	LD	A,ERR_READONLY		; SIGNAL ERROR
	OR	A			; SET FLAGS
	RET
;
; PHYSICAL SECTOR OF THE CURRENT LBA: UCRD_PBANK, UCRD_PADR (BANK, ADDRESS HIGH BYTE).
; IN HARD DISK MODE LBA 0 IS THE SYNTHESIZED MBR (RETURNS Z) AND PHYSICAL = LBA - 1.
; A 64K BANK HOLDS 128 SECTORS: BANK = PHYS >> 7, ADDRESS = (PHYS & $7F) * 512.
;
UCRD_PHYS:
	LD	HL,(UCRD_LBA+0)		; LBA LOW WORD (THE HIGH WORD IS 0 FOR <= 16M)
	LD	A,(UCRD_MODE)
	CP	UCRD_MHD
	JR	NZ,UCRD_PHYS1
	LD	A,H			; LBA 0?
	OR	L
	RET	Z			; MBR
	DEC	HL			; PHYSICAL = LBA - 1
UCRD_PHYS1:
	LD	A,L			; ADDRESS HIGH BYTE = (PHYS & $7F) * 2
	ADD	A,A
	LD	(UCRD_PADR),A
	ADD	HL,HL			; BANK = PHYS >> 7 = (PHYS * 2) >> 8
	LD	A,H
	LD	(UCRD_PBANK),A
	OR	$FF			; NZ: NORMAL SECTOR
	RET
;
; SET THE CARD TO THE CURRENT PHYSICAL SECTOR, LEAVE C = DATA PORT
;
UCRD_SETADR:
	LD	HL,UCRD_LBA		; SHOW ACTIVITY
	CALL	HB_DSKACT
	LD	A,(UCRD_PBANK)		; BANK
	OUT	(UCRD_BANK),A
	LD	A,(UCRD_PADR)		; ADDRESS: HIGH BYTE ON A8-A15, LOW BYTE 0
	LD	B,A
	LD	C,UCRD_ADDR
	XOR	A
	OUT	(C),A
	LD	C,UCRD_DATA		; DATA PORT FOR INIR/OTIR
	RET
;
UCRD_RDSEC:
	CALL	UCRD_SETADR		; SECTOR START
	LD	HL,(UCRD_DSKBUF)	; HL := DISK BUFFER ADDRESS
	LD	B,0			; 2 X 256 BYTES
	INIR
	INIR
	XOR	A			; SIGNAL SUCCESS
	RET
;
UCRD_WRSEC:
	CALL	UCRD_SETADR		; SECTOR START
	LD	HL,(UCRD_DSKBUF)	; HL := DISK BUFFER ADDRESS
	LD	B,0			; 2 X 256 BYTES
	OTIR
	OTIR
	XOR	A			; SIGNAL SUCCESS
	RET
;
; BUILD THE SYNTHESIZED MBR IN THE DISK BUFFER: ONE PARTITION OF TYPE $2E FROM LBA 1, SLICES *
; 16384 SECTORS LONG, SIGNATURE $55AA
;
UCRD_MBR:
	LD	HL,(UCRD_DSKBUF)	; CLEAR 512 BYTES
	LD	D,H
	LD	E,L
	INC	DE
	LD	BC,511
	LD	(HL),0
	LDIR
	LD	HL,(UCRD_DSKBUF)	; FIRST PARTITION ENTRY + 4 (TYPE)
	LD	DE,$1BE + 4
	ADD	HL,DE
	LD	(HL),$2E		; CP/M (HD1K)
	INC	HL			; LBA START (DWORD) AT +8
	INC	HL
	INC	HL
	INC	HL
	LD	(HL),1			; START = 1
	INC	HL
	INC	HL
	INC	HL
	INC	HL			; SIZE (DWORD) AT +12
	LD	A,(UCRD_SLICES)		; SLICES * 16384 = SLICES * $4000
	ADD	A,A			; HIGH BYTE OF THE LOW WORD = SLICES * $40
	ADD	A,A
	ADD	A,A
	ADD	A,A
	ADD	A,A
	ADD	A,A
	INC	HL			; +13
	LD	(HL),A			; (2 SLICES = $8000)
	LD	HL,(UCRD_DSKBUF)	; SIGNATURE
	LD	DE,$1FE
	ADD	HL,DE
	LD	(HL),$55
	INC	HL
	LD	(HL),$AA
	RET
;
; WORKING DATA
;
UCRD_BANKS	.DB	0		; IMAGE SIZE IN 64K BANKS (0 = 256)
UCRD_MODE	.DB	UCRD_MNONE	; PRESENTATION
UCRD_SLICES	.DB	0		; NUMBER OF 8M SLICES (HARD DISK MODE)
UCRD_SAVE0	.DB	0		; SAVED TEST BYTE OF BANK 0
UCRD_PBANK	.DB	0		; PHYSICAL BANK OF THE CURRENT SECTOR
UCRD_PADR	.DB	0		; PHYSICAL ADDRESS HIGH BYTE OF THE CURRENT SECTOR
UCRD_ISWR	.DB	0		; 0 = READ, 1 = WRITE
UCRD_DSKBUF	.DW	0		; DISK BUFFER
;
;--------------------------------------------------------------------------------------------------
;   HBIOS MODULE TRAILER
;--------------------------------------------------------------------------------------------------
;
END_UCRD	.EQU	$
SIZ_UCRD	.EQU	END_UCRD - ORG_UCRD
;
	MEMECHO	"UCRD occupies "
	MEMECHO	SIZ_UCRD
	MEMECHO	" bytes.\n"
