;======================================================================
;	SHARP MZ-800 KEYBOARD DRIVER
;	10 X 8 KEY MATRIX ON THE 8255 PPI ($D0-$D3)
;======================================================================
;
; THE COLUMN (0-9) IS WRITTEN TO PA0-PA3 (WITH PA4-PA7 HIGH: JOYSTICK
; STROBES OFF, CURSOR TIMER NOT RESET), THE ROW BITS ARE READ FROM PB,
; ACTIVE LOW.  THE MATRIX IS SCANNED WHENEVER THE KEYBOARD STATUS IS
; QUERIED.  A KEY IS REPORTED WHEN IT GOES DOWN.
;
; MODIFIERS: SHIFT, CTRL, ALPHA (TOGGLES CAPS LOCK).  GRAPH AND BLANK
; ARE NOT USED YET.  THE TRANSLATION TABLES ARE GENERATED BY
; mzdev/tools/mzkbdtab.py IN THE MZ-ROMWBW REPOSITORY.
;
;======================================================================
; MZK DRIVER - CONSTANTS
;======================================================================
;
MZK_PA		.EQU	$D0		; 8255 PORT A: COLUMN SELECT (OUT)
MZK_PB		.EQU	$D1		; 8255 PORT B: ROW BITS (IN, ACTIVE LOW)
MZK_CTL		.EQU	$D3		; 8255 CONTROL
MZK_MODE	.EQU	$8A		; 8255 MODE: PA OUT, PB IN, PC HI IN, PC LO OUT
MZK_COLS	.EQU	10		; MATRIX COLUMNS
;
MZK_SHFCOL	.EQU	8		; SHIFT: COLUMN 8, BIT 0
MZK_SHFBIT	.EQU	%00000001
MZK_CTLCOL	.EQU	8		; CTRL: COLUMN 8, BIT 6
MZK_CTLBIT	.EQU	%01000000
MZK_ALPCOL	.EQU	0		; ALPHA: COLUMN 0, BIT 4
MZK_ALPBIT	.EQU	%00010000
MZK_GRPBIT	.EQU	%01000000	; GRAPH: COLUMN 0, BIT 6
MZK_KEEP0	.EQU	%00101111	; COLUMN 0 WITHOUT ALPHA, GRAPH, BLANK
MZK_KEEP8	.EQU	%10111110	; COLUMN 8 WITHOUT SHIFT, CTRL
;
	DEVECHO	"MZK: IO="
	DEVECHO	MZK_PA
	DEVECHO	"\n"
;
;--------------------------------------------------------------------------------------------------
;   HBIOS MODULE HEADER
;--------------------------------------------------------------------------------------------------
;
ORG_MZK	.EQU	$
;
	.DW	SIZ_MZK			; MODULE SIZE
	.DW	MZK_INITPHASE		; ADR OF INIT PHASE HANDLER
;
; WARNING: KEYBOARD DRIVERS ARE INITIALIZED BY VDA DRIVERS
; AND SHOULD NOT BE INITIALIZED BY INITPHASE CALLS.
;
MZK_INITPHASE:
	RET				; DONE
;
;======================================================================
; MZK DRIVER - INITIALIZATION
;======================================================================
;
MZK_PREINIT:
	LD	A,MZK_MODE		; 8255 MODE, ALSO CLEARS PC0-PC3
	OUT	(MZK_CTL),A		; (PC2 = 0 MASKS THE 8253 INTERRUPT)
	LD	A,$F0			; NO COLUMN SELECTED YET
	OUT	(MZK_PA),A
	XOR	A			; SIGNAL SUCCESS
	RET
;
MZK_INIT:
	CALL	MZK_FLUSH		; NO KEY PENDING
	LD	HL,MZK_OLD		; FORGET PREVIOUS MATRIX STATE
	LD	B,MZK_COLS
	LD	A,$FF			; AS IF ALL KEYS DOWN: KEYS HELD AT
MZK_INIT1:				; STARTUP ARE NOT REPORTED
	LD	(HL),A
	INC	HL
	DJNZ	MZK_INIT1
	XOR	A			; SIGNAL SUCCESS
	RET
;
;======================================================================
; MZK DRIVER - KEYBOARD FUNCTIONS (CALLED THROUGH THE VDA TABLE)
;======================================================================
;
; KEYBOARD STATUS: A := NUMBER OF KEYS WAITING (0 OR 1), FLAGS SET
;
MZK_STAT:
	LD	A,(MZK_KEY)		; KEY ALREADY WAITING?
	OR	A
	JR	NZ,MZK_STAT1		; IF SO, REPORT IT
	CALL	MZK_SCAN		; SCAN THE MATRIX
	LD	A,(MZK_KEY)		; KEY WAITING NOW?
	OR	A
	JP	Z,CIO_IDLE		; RET VIA IDLE PROCESSING IF NO KEY
MZK_STAT1:
	LD	A,1			; ONE KEY WAITING
	OR	A			; SET FLAGS
	RET
;
; KEYBOARD READ: WAIT FOR A KEY, E := KEY CODE, C := MATRIX POSITION
; (COLUMN * 8 + BIT), D := STATE (KBD_SHIFT, KBD_CTRL, KBD_CAPSLCK)
;
MZK_READ:
	CALL	MZK_STAT		; KEY READY?
	JR	Z,MZK_READ		; NOT READY, KEEP TRYING
	LD	A,(MZK_KEY)		; KEY CODE
	LD	E,A
	LD	A,(MZK_POS)		; MATRIX POSITION
	LD	C,A
	LD	A,(MZK_STATE)		; STATE FLAGS
	LD	D,A
	XOR	A			; SIGNAL SUCCESS
	LD	(MZK_KEY),A		; KEY CONSUMED
	RET
;
; KEYBOARD FLUSH
;
MZK_FLUSH:
	XOR	A			; A = 0
	LD	(MZK_KEY),A		; NO KEY WAITING
	RET
;
;======================================================================
; MZK DRIVER - PRIVATE FUNCTIONS
;======================================================================
;
;----------------------------------------------------------------------
; SCAN THE MATRIX.  IF A KEY WENT DOWN SINCE THE LAST SCAN AND NO KEY
; IS WAITING, TRANSLATE IT INTO MZK_KEY.
;----------------------------------------------------------------------
;
MZK_SCAN:
	; READ ALL COLUMNS INTO MZK_NEW (1 = KEY DOWN)
	LD	HL,MZK_NEW		; DESTINATION
	LD	B,0			; COLUMN
MZK_SCAN1:
	LD	A,B			; SELECT COLUMN
	OR	$F0			; KEEP PA4-PA7 HIGH
	OUT	(MZK_PA),A
	IN	A,(MZK_PB)		; READ ROW BITS
	CPL				; 1 = KEY DOWN
	LD	(HL),A			; SAVE
	INC	HL
	INC	B			; NEXT COLUMN
	LD	A,B
	CP	MZK_COLS		; DONE?
	JR	NZ,MZK_SCAN1		; IF NOT, LOOP
;
	; MODIFIER STATE
	LD	C,0			; STATE ACCUMULATOR
	LD	A,(MZK_NEW + MZK_SHFCOL)
	AND	MZK_SHFBIT		; SHIFT DOWN?
	JR	Z,MZK_SCAN2
	SET	0,C			; KBD_SHIFT
MZK_SCAN2:
	LD	A,(MZK_NEW + MZK_CTLCOL)
	AND	MZK_CTLBIT		; CTRL DOWN?
	JR	Z,MZK_SCAN3
	SET	1,C			; KBD_CTRL
MZK_SCAN3:
	; ALPHA TOGGLES CAPS LOCK WHEN IT GOES DOWN
	LD	A,(MZK_OLD + MZK_ALPCOL)
	CPL				; KEYS THAT WERE UP
	LD	B,A
	LD	A,(MZK_NEW + MZK_ALPCOL)
	AND	B			; KEYS THAT WENT DOWN
	AND	MZK_ALPBIT		; ALPHA?
	LD	A,(MZK_CAPS)		; CURRENT CAPS LOCK
	JR	Z,MZK_SCAN4		; NO CHANGE
	CPL				; TOGGLE IT
	LD	(MZK_CAPS),A
MZK_SCAN4:
	OR	A			; CAPS LOCK ON?
	JR	Z,MZK_SCAN5
	SET	6,C			; KBD_CAPSLCK
MZK_SCAN5:
	LD	A,C			; SAVE STATE
	LD	(MZK_STATE),A
;
	; FIND THE FIRST KEY THAT WENT DOWN (NOT A MODIFIER)
	LD	HL,MZK_NEW		; CURRENT
	LD	DE,MZK_OLD		; PREVIOUS
	LD	C,0			; MATRIX POSITION OF COLUMN START
	LD	B,MZK_COLS		; COLUMN COUNT
MZK_SCAN6:
	LD	A,C			; MODIFIERS ARE NOT KEYS
	OR	A			; COLUMN 0?
	LD	A,MZK_KEEP0
	JR	Z,MZK_SCAN6A
	LD	A,C
	CP	MZK_SHFCOL * 8		; COLUMN 8?
	LD	A,MZK_KEEP8
	JR	Z,MZK_SCAN6A
	LD	A,$FF			; OTHER COLUMNS: ALL BITS
MZK_SCAN6A:
	PUSH	BC			; SAVE COUNTERS
	LD	B,A			; B := MASK
	LD	A,(DE)			; PREVIOUS STATE
	CPL				; KEYS THAT WERE UP
	AND	(HL)			; ... AND ARE DOWN NOW
	AND	B			; ... AND ARE NOT MODIFIERS
	POP	BC			; RESTORE COUNTERS
	JR	NZ,MZK_SCAN8		; FOUND SOMETHING
MZK_SCAN7:
	INC	HL			; NEXT COLUMN
	INC	DE
	LD	A,C
	ADD	A,8
	LD	C,A
	DJNZ	MZK_SCAN6		; LOOP
	JR	MZK_SCAN11		; NOTHING NEW
;
MZK_SCAN8:
	; A = NEW KEYS IN THIS COLUMN, C = POSITION OF BIT 0
MZK_SCAN9:
	RRA				; LOWEST BIT INTO CARRY
	JR	C,MZK_SCAN10		; FOUND THE KEY
	INC	C			; NEXT POSITION
	JR	MZK_SCAN9
MZK_SCAN10:
	LD	A,C			; MATRIX POSITION
	CALL	MZK_XLAT		; A := KEY CODE (0 = NONE)
	OR	A			; ANYTHING?
	JR	Z,MZK_SCAN11		; IF NOT, IGNORE
	LD	B,A			; SAVE CODE
	LD	A,(MZK_KEY)		; QUEUE FULL?
	OR	A
	JR	NZ,MZK_SCAN11		; IF SO, DROP THE NEW KEY
	LD	A,C			; SAVE POSITION
	LD	(MZK_POS),A
	LD	A,B			; SAVE CODE
	LD	(MZK_KEY),A
;
MZK_SCAN11:
	; CURRENT STATE BECOMES PREVIOUS STATE
	LD	HL,MZK_NEW
	LD	DE,MZK_OLD
	LD	BC,MZK_COLS
	LDIR
	RET
;
;----------------------------------------------------------------------
; TRANSLATE MATRIX POSITION A INTO A KEY CODE IN A (0 = NONE), USING
; THE MODIFIER STATE IN MZK_STATE.  BC, DE, HL PRESERVED.
;----------------------------------------------------------------------
;
MZK_XLAT:
	PUSH	HL			; SAVE REGS
	PUSH	DE
	LD	E,A			; DE := POSITION
	LD	D,0
	LD	A,(MZK_STATE)		; SHIFT?
	BIT	0,A
	LD	HL,MZK_MAPNORM		; ASSUME NORMAL
	JR	Z,MZK_XLAT1
	LD	HL,MZK_MAPSHFT		; ELSE SHIFTED
MZK_XLAT1:
	ADD	HL,DE			; POINT TO ENTRY
	LD	E,(HL)			; E := CODE
;
	; CAPS LOCK SWAPS THE CASE OF LETTERS
	BIT	6,A			; CAPS LOCK?
	JR	Z,MZK_XLAT2
	LD	A,E			; LETTER?
	OR	$20			; LOWER CASE OF IT
	CP	$61
	JR	C,MZK_XLAT2
	CP	$7B
	JR	NC,MZK_XLAT2
	LD	A,E			; SWAP CASE
	XOR	$20
	LD	E,A
;
MZK_XLAT2:
	; CTRL MAKES CONTROL CODES OF LETTERS AND [ \ ] ^ -
	LD	A,(MZK_STATE)
	BIT	1,A			; CTRL?
	JR	Z,MZK_XLAT4		; IF NOT, DONE
	LD	A,E
	OR	$20			; LETTER (EITHER CASE)?
	CP	$61
	JR	C,MZK_XLAT3
	CP	$7B
	JR	NC,MZK_XLAT3
	AND	$1F			; CONTROL CODE
	LD	E,A
	JR	MZK_XLAT4
MZK_XLAT3:
	LD	A,E
	CP	$5B			; $1B
	JR	Z,MZK_XLAT5
	CP	$5C			; $1C
	JR	Z,MZK_XLAT5
	CP	$5D			; $1D
	JR	Z,MZK_XLAT5
	CP	$5E			; $1E
	JR	Z,MZK_XLAT5
	CP	$2D			; $1F
	JR	NZ,MZK_XLAT4
	LD	E,$1F
	JR	MZK_XLAT4
MZK_XLAT5:
	AND	$1F			; CONTROL CODE
	LD	E,A
MZK_XLAT4:
	LD	A,E			; RESULT
	POP	DE			; RESTORE REGS
	POP	HL
	RET
;
;----------------------------------------------------------------------
; TRANSLATION TABLES, INDEX = COLUMN * 8 + BIT
; GENERATED BY mzdev/tools/mzkbdtab.py
;----------------------------------------------------------------------
;
MZK_MAPNORM:				; NORMAL
	.DB	$0D, $3A, $3B, $09, $00, $60, $00, $00		; COLUMN 0, BITS 0-7
	.DB	$00, $00, $00, $5D, $5B, $40, $7A, $79		; COLUMN 1, BITS 0-7
	.DB	$78, $77, $76, $75, $74, $73, $72, $71		; COLUMN 2, BITS 0-7
	.DB	$70, $6F, $6E, $6D, $6C, $6B, $6A, $69		; COLUMN 3, BITS 0-7
	.DB	$68, $67, $66, $65, $64, $63, $62, $61		; COLUMN 4, BITS 0-7
	.DB	$38, $37, $36, $35, $34, $33, $32, $31		; COLUMN 5, BITS 0-7
	.DB	$2E, $2C, $39, $30, $20, $2D, $5E, $5C		; COLUMN 6, BITS 0-7
	.DB	$2F, $3F, $F8, $F9, $F7, $F6, $08, $F0		; COLUMN 7, BITS 0-7
	.DB	$00, $00, $00, $00, $00, $00, $00, $1B		; COLUMN 8, BITS 0-7
	.DB	$00, $00, $00, $E4, $E3, $E2, $E1, $E0		; COLUMN 9, BITS 0-7
MZK_MAPSHFT:				; WITH SHIFT
	.DB	$0D, $2A, $2B, $09, $00, $60, $00, $00		; COLUMN 0, BITS 0-7
	.DB	$00, $00, $00, $7C, $7B, $60, $5A, $59		; COLUMN 1, BITS 0-7
	.DB	$58, $57, $56, $55, $54, $53, $52, $51		; COLUMN 2, BITS 0-7
	.DB	$50, $4F, $4E, $4D, $4C, $4B, $4A, $49		; COLUMN 3, BITS 0-7
	.DB	$48, $47, $46, $45, $44, $43, $42, $41		; COLUMN 4, BITS 0-7
	.DB	$28, $27, $26, $25, $24, $23, $22, $21		; COLUMN 5, BITS 0-7
	.DB	$3E, $3C, $29, $30, $20, $3D, $7E, $7D		; COLUMN 6, BITS 0-7
	.DB	$5F, $3F, $F8, $F9, $F7, $F6, $F2, $F1		; COLUMN 7, BITS 0-7
	.DB	$00, $00, $00, $00, $00, $00, $00, $1B		; COLUMN 8, BITS 0-7
	.DB	$00, $00, $00, $E9, $E8, $E7, $E6, $E5		; COLUMN 9, BITS 0-7
;
;==================================================================================================
;   MZK DRIVER - DATA
;==================================================================================================
;
MZK_KEY		.DB	0		; KEY WAITING (0 = NONE)
MZK_POS		.DB	0		; ITS MATRIX POSITION
MZK_STATE	.DB	0		; MODIFIER STATE (KBD_SHIFT, KBD_CTRL, KBD_CAPSLCK)
MZK_CAPS	.DB	0		; CAPS LOCK ($FF = ON)
MZK_NEW		.FILL	MZK_COLS,0	; MATRIX, CURRENT SCAN (1 = DOWN)
MZK_OLD		.FILL	MZK_COLS,0	; MATRIX, PREVIOUS SCAN
;
;--------------------------------------------------------------------------------------------------
;   HBIOS MODULE TRAILER
;--------------------------------------------------------------------------------------------------
;
END_MZK	.EQU	$
SIZ_MZK	.EQU	END_MZK - ORG_MZK
;
	MEMECHO	"MZK occupies "
	MEMECHO	SIZ_MZK
	MEMECHO	" bytes.\n"
