;======================================================================
;	SHARP MZ-800 KEYBOARD DRIVER
;	10 X 8 KEY MATRIX ON THE 8255 PPI ($D0-$D3)
;======================================================================
;
; THE COLUMN (0-9) IS WRITTEN TO PA0-PA3 (WITH PA4-PA7 HIGH: JOYSTICK
; STROBES OFF, CURSOR TIMER NOT RESET), THE ROW BITS ARE READ FROM PB,
; ACTIVE LOW.  WITH THE MZV VBLANK TIMER THE MATRIX IS SCANNED ON EVERY
; SYSTEM TICK (50 HZ) INTO A SMALL KEY QUEUE, WITH AUTO-REPEAT.  WITHOUT
; A TIMER IT IS SCANNED WHENEVER THE KEYBOARD STATUS IS QUERIED (NO
; AUTO-REPEAT).  A KEY IS REPORTED WHEN IT GOES DOWN.
;
; MODIFIERS: SHIFT, CTRL, ALPHA (TOGGLES CAPS LOCK).  GRAPH IS NOT USED
; YET.  AS IN THE SHARP CP/M BY J. LAMAC, BLANK RECALLS THE LINES THAT
; WERE ENTERED: THE DRIVER FOLLOWS THE CHARACTERS IT RETURNS (PRINTABLE
; ONES, BACKSPACE, DEL, ^C ^U ^X ESC CLEAR, CR ENDS THE LINE) AND KEEPS
; THE ENTERED LINES IN A HISTORY OF 256 BYTES (NEWEST FIRST, THE OLDEST
; FALL OFF, A REPEATED LINE IS KEPT ONCE).  BLANK REPLACES THE LINE BEING
; TYPED WITH THE NEXT OLDER ONE, SHIFT+BLANK WITH THE NEXT NEWER ONE (OR
; AN EMPTY LINE): THE DRIVER RETURNS BACKSPACES FOR THE CURRENT LINE AND
; THEN THE CHARACTERS OF THE RECALLED ONE, AS IF THEY WERE TYPED.  THIS
; WORKS WITH ANY OS AND COSTS NO TPA.
; THE TRANSLATION TABLES ARE GENERATED BY mzdev/tools/mzkbdtab.py IN THE
; MZ-ROMWBW REPOSITORY.
;
;======================================================================
; MZK DRIVER - CONSTANTS
;======================================================================
;
MZK_PA		.EQU	$D0		; 8255 PORT A: COLUMN SELECT (OUT)
MZK_PB		.EQU	$D1		; 8255 PORT B: ROW BITS (IN, ACTIVE LOW)
MZK_CTL		.EQU	$D3		; 8255 CONTROL
MZK_MODE	.EQU	$8A		; 8255 MODE: PA OUT, PB IN, PC HI IN, PC LO OUT
MZK_COLS	.EQU	10		; MATRIX COLUMNS
;
MZK_SHFCOL	.EQU	8		; SHIFT: COLUMN 8, BIT 0
MZK_SHFBIT	.EQU	%00000001
MZK_CTLCOL	.EQU	8		; CTRL: COLUMN 8, BIT 6
MZK_CTLBIT	.EQU	%01000000
MZK_ALPCOL	.EQU	0		; ALPHA: COLUMN 0, BIT 4
MZK_ALPBIT	.EQU	%00010000
MZK_GRPBIT	.EQU	%01000000	; GRAPH: COLUMN 0, BIT 6
MZK_KEEP0	.EQU	%10101111	; COLUMN 0 WITHOUT ALPHA, GRAPH
MZK_KEEP8	.EQU	%10111110	; COLUMN 8 WITHOUT SHIFT, CTRL
MZK_QSIZ	.EQU	8		; KEY QUEUE SIZE (POWER OF 2)
MZK_RPTDLY	.EQU	TICKFREQ / 2	; AUTO-REPEAT DELAY (TICKS)
MZK_RPTRATE	.EQU	3		; AUTO-REPEAT PERIOD (TICKS)
MZK_RECALL	.EQU	$FF		; INTERNAL CODE OF BLANK: OLDER LINE (NEVER RETURNED)
MZK_RECALLF	.EQU	$FE		; INTERNAL CODE OF SHIFT+BLANK: NEWER LINE (NEVER RETURNED)
MZK_LINMAX	.EQU	128		; LONGEST LINE REMEMBERED
					; HISTORY: 256 BYTES, 8 BIT OFFSETS (MZK_HIST)
;
	DEVECHO	"MZK: IO="
	DEVECHO	MZK_PA
	DEVECHO	"\n"
;
;--------------------------------------------------------------------------------------------------
;   HBIOS MODULE HEADER
;--------------------------------------------------------------------------------------------------
;
ORG_MZK	.EQU	$
;
	.DW	SIZ_MZK			; MODULE SIZE
	.DW	MZK_INITPHASE		; ADR OF INIT PHASE HANDLER
;
; WARNING: KEYBOARD DRIVERS ARE INITIALIZED BY VDA DRIVERS
; AND SHOULD NOT BE INITIALIZED BY INITPHASE CALLS.
;
MZK_INITPHASE:
	RET				; DONE
;
;======================================================================
; MZK DRIVER - INITIALIZATION
;======================================================================
;
MZK_PREINIT:
	LD	A,MZK_MODE		; 8255 MODE, ALSO CLEARS PC0-PC3
	OUT	(MZK_CTL),A		; (PC2 = 0 MASKS THE 8253 INTERRUPT)
	LD	A,$F0			; NO COLUMN SELECTED YET
	OUT	(MZK_PA),A
	XOR	A			; SIGNAL SUCCESS
	RET
;
MZK_INIT:
	CALL	MZK_FLUSH		; NO KEY PENDING
	LD	HL,MZK_OLD		; FORGET PREVIOUS MATRIX STATE
	LD	B,MZK_COLS
	LD	A,$FF			; AS IF ALL KEYS DOWN: KEYS HELD AT
MZK_INIT1:				; STARTUP ARE NOT REPORTED
	LD	(HL),A
	INC	HL
	DJNZ	MZK_INIT1
	LD	(MZK_RPTPOS),A		; NO KEY REPEATING ($FF)
#IF (SYSTIM == TM_MZV)
	; SCAN THE KEYBOARD ON EVERY SYSTEM TICK
	LD	HL,(VEC_TICK + 1)	; CHAIN THE PREVIOUS TICK HANDLER
	LD	(MZK_TICKNXT + 1),HL
	LD	HL,MZK_TICK		; HOOK THE TICK VECTOR
	LD	(VEC_TICK + 1),HL
#ENDIF
	XOR	A			; SIGNAL SUCCESS
	RET
;
;======================================================================
; MZK DRIVER - KEYBOARD FUNCTIONS (CALLED THROUGH THE VDA TABLE)
;======================================================================
;
; KEYBOARD STATUS: A := NUMBER OF KEYS WAITING, FLAGS SET
;
MZK_STAT:
#IF (SYSTIM != TM_MZV)
	CALL	MZK_SCAN		; NO TIMER: SCAN NOW
#ENDIF
MZK_STAT1:
	LD	A,(MZK_RPLBS)		; REPLAYING: BACKSPACES TO RETURN?
	OR	A
	JR	NZ,MZK_STAT3		; IF SO, A KEY IS READY
	LD	A,(MZK_RPLEND)		; ... OR CHARACTERS OF A RECALLED LINE?
	LD	B,A
	LD	A,(MZK_RPLPOS)
	CP	B
	JR	NZ,MZK_STAT3		; IF SO, A KEY IS READY
	LD	A,(MZK_QTAIL)		; KEYS WAITING := HEAD - TAIL
	LD	C,A
	LD	A,(MZK_QHEAD)
	SUB	C
	AND	MZK_QSIZ - 1
	JP	Z,CIO_IDLE		; RET VIA IDLE PROCESSING IF NO KEY
	LD	B,A			; B := COUNT
	LD	A,C			; OLDEST KEY A RECALL KEY?
	LD	HL,MZK_QKEY
	CALL	ADDHLA
	LD	A,(HL)
	CP	MZK_RECALLF		; ($FE OR $FF)
	LD	A,B			; COUNT
	RET	C			; IF NOT, DONE (NZ FROM CP)
	LD	E,(HL)			; E := RECALL CODE
	LD	A,C			; DROP THE RECALL KEY
	INC	A
	AND	MZK_QSIZ - 1
	LD	(MZK_QTAIL),A
	LD	A,E			; OLDER OR NEWER LINE
	CALL	MZK_HSTEP		; START ITS REPLAY (IF THERE IS ONE)
	JR	MZK_STAT1		; AND CHECK AGAIN
MZK_STAT3:
	LD	A,1			; ONE KEY READY
	OR	A			; SET FLAGS
	RET
;
; KEYBOARD READ: WAIT FOR A KEY, E := KEY CODE, C := MATRIX POSITION
; (COLUMN * 8 + BIT), D := STATE (KBD_SHIFT, KBD_CTRL, KBD_CAPSLCK)
;
MZK_READ:
	CALL	MZK_STAT		; KEY READY?
	JR	Z,MZK_READ		; NOT READY, KEEP TRYING
	LD	A,(MZK_RPLBS)		; BACKSPACES TO RETURN?
	OR	A
	JR	Z,MZK_READ0		; IF NOT, CHECK THE RECALLED LINE
	DEC	A			; ONE LESS
	LD	(MZK_RPLBS),A
	LD	E,$08			; BACKSPACE
	JR	MZK_READ0A
MZK_READ0:
	LD	A,(MZK_RPLEND)		; CHARACTERS OF A RECALLED LINE?
	LD	B,A
	LD	A,(MZK_RPLPOS)
	CP	B
	JR	Z,MZK_READ1		; IF NOT, FROM THE QUEUE
	LD	HL,MZK_HIST		; NEXT CHARACTER OF THE RECALLED LINE
	CALL	ADDHLA
	LD	E,(HL)
	LD	HL,MZK_RPLPOS
	INC	(HL)
MZK_READ0A:
	LD	C,$FF			; NO MATRIX POSITION
	JR	MZK_READ2
MZK_READ1:
	LD	A,(MZK_QTAIL)		; OLDEST KEY
	LD	HL,MZK_QKEY
	CALL	ADDHLA
	LD	E,(HL)			; E := KEY CODE
	LD	A,(MZK_QTAIL)
	LD	HL,MZK_QPOS
	CALL	ADDHLA
	LD	C,(HL)			; C := MATRIX POSITION
	LD	A,(MZK_QTAIL)		; CONSUME IT
	INC	A
	AND	MZK_QSIZ - 1
	LD	(MZK_QTAIL),A
MZK_READ2:
	LD	A,E			; FOLLOW THE LINE BEING TYPED
	CALL	MZK_TRACK
	LD	A,(MZK_STATE)		; D := STATE FLAGS
	LD	D,A
	XOR	A			; SIGNAL SUCCESS
	RET
;
; KEYBOARD FLUSH
;
MZK_FLUSH:
	LD	A,(MZK_QHEAD)		; DROP ALL WAITING KEYS
	LD	(MZK_QTAIL),A
	XOR	A			; STOP A REPLAY
	LD	(MZK_RPLBS),A
	LD	(MZK_RPLPOS),A
	LD	(MZK_RPLEND),A
	RET				; SIGNAL SUCCESS (A = 0)
;
#IF (SYSTIM == TM_MZV)
;
; SYSTEM TICK HOOK
;
MZK_TICK:
	CALL	MZK_SCAN		; SCAN, QUEUE NEW AND REPEATED KEYS
MZK_TICKNXT:
	JP	0			; PREVIOUS TICK HANDLER (PATCHED)
#ENDIF
;
;======================================================================
; MZK DRIVER - PRIVATE FUNCTIONS
;======================================================================
;
;----------------------------------------------------------------------
; SCAN THE MATRIX.  A KEY THAT WENT DOWN SINCE THE LAST SCAN IS
; TRANSLATED AND QUEUED.  WITH THE TIMER, A KEY HELD DOWN IS REPEATED.
;----------------------------------------------------------------------
;
MZK_SCAN:
	; READ ALL COLUMNS INTO MZK_NEW (1 = KEY DOWN)
	LD	HL,MZK_NEW		; DESTINATION
	LD	B,0			; COLUMN
MZK_SCAN1:
	LD	A,B			; SELECT COLUMN
	OR	$F0			; KEEP PA4-PA7 HIGH
	OUT	(MZK_PA),A
	IN	A,(MZK_PB)		; READ ROW BITS
	CPL				; 1 = KEY DOWN
	LD	(HL),A			; SAVE
	INC	HL
	INC	B			; NEXT COLUMN
	LD	A,B
	CP	MZK_COLS		; DONE?
	JR	NZ,MZK_SCAN1		; IF NOT, LOOP
;
	; MODIFIER STATE
	LD	C,0			; STATE ACCUMULATOR
	LD	A,(MZK_NEW + MZK_SHFCOL)
	AND	MZK_SHFBIT		; SHIFT DOWN?
	JR	Z,MZK_SCAN2
	SET	0,C			; KBD_SHIFT
MZK_SCAN2:
	LD	A,(MZK_NEW + MZK_CTLCOL)
	AND	MZK_CTLBIT		; CTRL DOWN?
	JR	Z,MZK_SCAN3
	SET	1,C			; KBD_CTRL
MZK_SCAN3:
	; ALPHA TOGGLES CAPS LOCK WHEN IT GOES DOWN
	LD	A,(MZK_OLD + MZK_ALPCOL)
	CPL				; KEYS THAT WERE UP
	LD	B,A
	LD	A,(MZK_NEW + MZK_ALPCOL)
	AND	B			; KEYS THAT WENT DOWN
	AND	MZK_ALPBIT		; ALPHA?
	LD	A,(MZK_CAPS)		; CURRENT CAPS LOCK
	JR	Z,MZK_SCAN4		; NO CHANGE
	CPL				; TOGGLE IT
	LD	(MZK_CAPS),A
MZK_SCAN4:
	OR	A			; CAPS LOCK ON?
	JR	Z,MZK_SCAN5
	SET	6,C			; KBD_CAPSLCK
MZK_SCAN5:
	LD	A,C			; SAVE STATE
	LD	(MZK_STATE),A
;
	; FIND THE FIRST KEY THAT WENT DOWN (NOT A MODIFIER)
	LD	HL,MZK_NEW		; CURRENT
	LD	DE,MZK_OLD		; PREVIOUS
	LD	C,0			; MATRIX POSITION OF COLUMN START
	LD	B,MZK_COLS		; COLUMN COUNT
MZK_SCAN6:
	LD	A,C			; MODIFIERS ARE NOT KEYS
	OR	A			; COLUMN 0?
	LD	A,MZK_KEEP0
	JR	Z,MZK_SCAN6A
	LD	A,C
	CP	MZK_SHFCOL * 8		; COLUMN 8?
	LD	A,MZK_KEEP8
	JR	Z,MZK_SCAN6A
	LD	A,$FF			; OTHER COLUMNS: ALL BITS
MZK_SCAN6A:
	PUSH	BC			; SAVE COUNTERS
	LD	B,A			; B := MASK
	LD	A,(DE)			; PREVIOUS STATE
	CPL				; KEYS THAT WERE UP
	AND	(HL)			; ... AND ARE DOWN NOW
	AND	B			; ... AND ARE NOT MODIFIERS
	POP	BC			; RESTORE COUNTERS
	JR	NZ,MZK_SCAN8		; FOUND SOMETHING
MZK_SCAN7:
	INC	HL			; NEXT COLUMN
	INC	DE
	LD	A,C
	ADD	A,8
	LD	C,A
	DJNZ	MZK_SCAN6		; LOOP
	JR	MZK_SCANR		; NOTHING NEW, CHECK AUTO-REPEAT
;
MZK_SCAN8:
	; A = NEW KEYS IN THIS COLUMN, C = POSITION OF BIT 0
MZK_SCAN9:
	RRA				; LOWEST BIT INTO CARRY
	JR	C,MZK_SCAN10		; FOUND THE KEY
	INC	C			; NEXT POSITION
	JR	MZK_SCAN9
MZK_SCAN10:
	LD	A,C			; NEW KEY, ALSO THE REPEAT CANDIDATE
	LD	(MZK_RPTPOS),A
	LD	A,MZK_RPTDLY		; FIRST REPEAT AFTER THE DELAY
	LD	(MZK_RPTCNT),A
	LD	A,C			; TRANSLATE AND QUEUE IT
	CALL	MZK_PUTKEY
	JR	MZK_SCAN11		; DONE
;
MZK_SCANR:
#IF (SYSTIM == TM_MZV)
	; NO NEW KEY: REPEAT THE KEY THAT IS STILL HELD DOWN
	LD	A,(MZK_RPTPOS)		; REPEAT CANDIDATE
	CP	$FF			; NONE?
	JR	Z,MZK_SCAN11		; IF SO, DONE
	LD	C,A			; C := MATRIX POSITION
	RRCA				; COLUMN := POSITION / 8
	RRCA
	RRCA
	AND	$1F
	LD	HL,MZK_NEW		; HL := COLUMN BYTE
	CALL	ADDHLA
	LD	A,C			; BIT := POSITION AND 7
	AND	7
	LD	B,A
	LD	A,1			; A := BIT MASK
	JR	Z,MZK_SCANR2
MZK_SCANR1:
	ADD	A,A
	DJNZ	MZK_SCANR1
MZK_SCANR2:
	AND	(HL)			; STILL DOWN?
	JR	NZ,MZK_SCANR3		; IF SO, COUNT
	LD	A,$FF			; RELEASED: STOP REPEATING
	LD	(MZK_RPTPOS),A
	JR	MZK_SCAN11
MZK_SCANR3:
	LD	HL,MZK_RPTCNT		; COUNT DOWN
	DEC	(HL)
	JR	NZ,MZK_SCAN11		; NOT YET
	LD	(HL),MZK_RPTRATE	; NEXT REPEAT AFTER THE PERIOD
	LD	A,C			; QUEUE THE KEY AGAIN
	CALL	MZK_PUTKEY
#ENDIF
;
MZK_SCAN11:
	; CURRENT STATE BECOMES PREVIOUS STATE
	LD	HL,MZK_NEW
	LD	DE,MZK_OLD
	LD	BC,MZK_COLS
	LDIR
	RET
;
;----------------------------------------------------------------------
; FOLLOW THE LINE BEING TYPED (CHARACTER A, AS RETURNED TO THE CALLER).
; CR PUTS A NON-EMPTY LINE INTO THE HISTORY.  BC, DE, HL PRESERVED.
;----------------------------------------------------------------------
;
MZK_TRACK:
	PUSH	BC			; SAVE REGS
	PUSH	DE
	PUSH	HL
	LD	C,A			; C := CHARACTER
	CP	$0D			; CR?
	JR	NZ,MZK_TRACK1
	LD	A,(MZK_LINLEN)		; EMPTY LINE?
	OR	A
	CALL	NZ,MZK_HADD		; IF NOT, INTO THE HISTORY
	JR	MZK_TRACKCLR		; NEW EMPTY LINE
MZK_TRACK1:
	CP	$08			; BACKSPACE
	JR	Z,MZK_TRACKBS
	CP	$7F			; DEL (RUBOUT)
	JR	Z,MZK_TRACKBS
	CP	$03			; ^C
	JR	Z,MZK_TRACKCLR
	CP	$15			; ^U
	JR	Z,MZK_TRACKCLR
	CP	$18			; ^X
	JR	Z,MZK_TRACKCLR
	CP	$1B			; ESC
	JR	Z,MZK_TRACKCLR
	CP	$20			; OTHER CONTROL CODES: IGNORE
	JR	C,MZK_TRACK9
	CP	$7F			; SPECIAL KEYS: IGNORE
	JR	NC,MZK_TRACK9
	LD	A,(MZK_LINLEN)		; ROOM LEFT?
	CP	MZK_LINMAX
	JR	NC,MZK_TRACK9		; IF NOT, IGNORE
	LD	B,A			; B := LENGTH
	LD	HL,MZK_LINE		; STORE THE CHARACTER
	CALL	ADDHLA
	LD	(HL),C
	LD	A,B			; LENGTH + 1
	INC	A
	LD	(MZK_LINLEN),A
	JR	MZK_TRACK9
MZK_TRACKBS:
	LD	A,(MZK_LINLEN)		; REMOVE THE LAST CHARACTER
	OR	A
	JR	Z,MZK_TRACK9
	DEC	A
	LD	(MZK_LINLEN),A
	JR	MZK_TRACK9
MZK_TRACKCLR:
	XOR	A			; EMPTY LINE
	LD	(MZK_LINLEN),A
	DEC	A			; NO HISTORY LINE SHOWN ($FF)
	LD	(MZK_HIDX),A
MZK_TRACK9:
	POP	HL			; RESTORE REGS
	POP	DE
	POP	BC
	RET
;
;----------------------------------------------------------------------
; PUT THE LINE BEING TYPED (MZK_LINE, LENGTH A, 1-MZK_LINMAX) INTO THE
; HISTORY.  THE HISTORY HOLDS THE LINES NEWEST FIRST, EACH ENDED BY A
; ZERO; THE REST OF THE BUFFER IS ZERO.  THE OLD LINES MOVE UP BY THE
; LENGTH + 1, WHAT DOES NOT FIT FALLS OFF (MZK_HFIND IGNORES A LINE CUT
; OFF THAT WAY).  A LINE THE SAME AS THE NEWEST ONE IS NOT ADDED AGAIN.
; AF, BC, DE, HL USED.
;----------------------------------------------------------------------
;
MZK_HADD:
	LD	B,A			; COMPARE WITH THE NEWEST LINE
	LD	HL,MZK_HIST
	LD	DE,MZK_LINE
MZK_HADD1:
	LD	A,(DE)
	CP	(HL)
	JR	NZ,MZK_HADD2		; DIFFERENT
	INC	HL
	INC	DE
	DJNZ	MZK_HADD1
	LD	A,(HL)			; SAME CHARACTERS: SAME LENGTH TOO?
	OR	A
	RET	Z			; IF SO, ALREADY THE NEWEST LINE
MZK_HADD2:
	LD	A,(MZK_LINLEN)		; C := LENGTH + 1 (LINE + ZERO)
	INC	A
	LD	C,A
	LD	B,0
	LD	HL,MZK_HIST + 255	; MOVE THE HISTORY UP BY C BYTES
	LD	D,H			; DE := LAST BYTE
	LD	E,L
	OR	A
	SBC	HL,BC			; HL := LAST BYTE - C
	PUSH	BC			; SAVE LENGTH + 1
	LD	A,C			; BC := 256 - C BYTES TO MOVE
	NEG
	LD	C,A
	LDDR
	POP	BC			; BC := LENGTH + 1
	DEC	C			; BC := LENGTH
	LD	HL,MZK_LINE		; THE LINE TO THE FRONT
	LD	DE,MZK_HIST
	LDIR
	XOR	A			; AND ITS ZERO
	LD	(DE),A
	RET
;
;----------------------------------------------------------------------
; FIND HISTORY LINE A (0 = NEWEST).  E := OFFSET OF ITS FIRST CHARACTER,
; D := OFFSET OF ITS ZERO.  CF SET IF THERE IS NO SUCH LINE (PAST THE
; LAST ONE, OR CUT OFF AT THE END OF THE BUFFER).  A, BC, HL PRESERVED.
;----------------------------------------------------------------------
;
MZK_HFIND:
	PUSH	AF			; SAVE REGS
	PUSH	BC
	PUSH	HL
	LD	B,A			; B := LINES TO GO + 1
	INC	B
	LD	E,0			; E := START OF THE LINE
MZK_HFIND1:
	LD	HL,MZK_HIST		; HL := ITS FIRST CHARACTER
	LD	A,E
	CALL	ADDHLA
	LD	A,(HL)			; ZERO: NO MORE LINES
	OR	A
	JR	Z,MZK_HFIND9
	LD	D,E			; D := OFFSET BEING LOOKED AT
MZK_HFIND2:
	INC	D			; NEXT CHARACTER
	JR	Z,MZK_HFIND9		; PAST THE BUFFER: LINE CUT OFF
	INC	HL
	LD	A,(HL)			; END OF THE LINE?
	OR	A
	JR	NZ,MZK_HFIND2
	DEC	B			; THE LINE WANTED?
	JR	Z,MZK_HFIND8
	LD	E,D			; NEXT LINE STARTS AFTER THE ZERO
	INC	E
	JR	NZ,MZK_HFIND1		; IF STILL IN THE BUFFER
	JR	MZK_HFIND9
MZK_HFIND8:
	POP	HL			; FOUND
	POP	BC
	POP	AF
	OR	A			; CF := 0
	RET
MZK_HFIND9:
	POP	HL			; NOT FOUND
	POP	BC
	POP	AF
	SCF				; CF := 1
	RET
;
;----------------------------------------------------------------------
; BLANK (A = MZK_RECALL) OR SHIFT+BLANK (A = MZK_RECALLF): REPLACE THE
; LINE BEING TYPED WITH THE NEXT OLDER OR NEWER HISTORY LINE.  SETS UP
; THE REPLAY: BACKSPACES FOR THE CURRENT LINE, THEN THE RECALLED LINE.
; NOTHING HAPPENS PAST THE OLDEST LINE.  PAST THE NEWEST ONE THE LINE IS
; ONLY ERASED.  AF, DE USED.
;----------------------------------------------------------------------
;
MZK_HSTEP:
	CP	MZK_RECALL		; OLDER?
	LD	A,(MZK_HIDX)		; LINE SHOWN NOW ($FF = NONE)
	JR	NZ,MZK_HSTEP2		; IF NOT, NEWER
	INC	A			; NEXT OLDER ($FF + 1 = NEWEST)
	CALL	MZK_HFIND		; IS THERE ONE?
	RET	C			; IF NOT, NOTHING HAPPENS
	JR	MZK_HSTEP4
MZK_HSTEP2:
	CP	$FF			; NO LINE SHOWN?
	RET	Z			; THEN NOTHING NEWER
	DEC	A			; NEXT NEWER
	CP	$FF			; PAST THE NEWEST?
	JR	Z,MZK_HSTEP3		; THEN AN EMPTY LINE
	CALL	MZK_HFIND		; E, D := THE LINE
	RET	C			; (ALWAYS THERE)
	JR	MZK_HSTEP4
MZK_HSTEP3:
	LD	DE,0			; EMPTY: NO CHARACTERS
MZK_HSTEP4:
	LD	(MZK_HIDX),A		; LINE SHOWN
	LD	A,E			; ITS CHARACTERS
	LD	(MZK_RPLPOS),A
	LD	A,D
	LD	(MZK_RPLEND),A
	LD	A,(MZK_LINLEN)		; BUT FIRST ERASE THE CURRENT LINE
	LD	(MZK_RPLBS),A
	RET
;
;----------------------------------------------------------------------
; TRANSLATE MATRIX POSITION A AND QUEUE THE KEY CODE (IF ANY AND IF
; THE QUEUE IS NOT FULL)
;----------------------------------------------------------------------
;
MZK_PUTKEY:
	LD	C,A			; SAVE POSITION
	CALL	MZK_XLAT		; A := KEY CODE
	OR	A			; ANYTHING?
	RET	Z			; IF NOT, DONE
	LD	E,A			; SAVE CODE
	LD	A,(MZK_QHEAD)		; B := HEAD
	LD	B,A
	INC	A			; D := NEXT HEAD
	AND	MZK_QSIZ - 1
	LD	D,A
	LD	A,(MZK_QTAIL)		; QUEUE FULL?
	CP	D
	RET	Z			; IF SO, DROP THE KEY
	LD	HL,MZK_QKEY		; STORE CODE
	LD	A,B
	CALL	ADDHLA
	LD	(HL),E
	LD	HL,MZK_QPOS		; STORE POSITION
	LD	A,B
	CALL	ADDHLA
	LD	(HL),C
	LD	A,D			; PUBLISH IT
	LD	(MZK_QHEAD),A
	RET
;
;----------------------------------------------------------------------
; TRANSLATE MATRIX POSITION A INTO A KEY CODE IN A (0 = NONE), USING
; THE MODIFIER STATE IN MZK_STATE.  BC, DE, HL PRESERVED.
;----------------------------------------------------------------------
;
MZK_XLAT:
	PUSH	HL			; SAVE REGS
	PUSH	DE
	LD	E,A			; DE := POSITION
	LD	D,0
	LD	A,(MZK_STATE)		; SHIFT?
	BIT	0,A
	LD	HL,MZK_MAPNORM		; ASSUME NORMAL
	JR	Z,MZK_XLAT1
	LD	HL,MZK_MAPSHFT		; ELSE SHIFTED
MZK_XLAT1:
	ADD	HL,DE			; POINT TO ENTRY
	LD	E,(HL)			; E := CODE
;
	; CAPS LOCK SWAPS THE CASE OF LETTERS
	BIT	6,A			; CAPS LOCK?
	JR	Z,MZK_XLAT2
	LD	A,E			; LETTER?
	OR	$20			; LOWER CASE OF IT
	CP	$61
	JR	C,MZK_XLAT2
	CP	$7B
	JR	NC,MZK_XLAT2
	LD	A,E			; SWAP CASE
	XOR	$20
	LD	E,A
;
MZK_XLAT2:
	; CTRL MAKES CONTROL CODES OF LETTERS AND [ \ ] ^ -
	LD	A,(MZK_STATE)
	BIT	1,A			; CTRL?
	JR	Z,MZK_XLAT4		; IF NOT, DONE
	LD	A,E
	OR	$20			; LETTER (EITHER CASE)?
	CP	$61
	JR	C,MZK_XLAT3
	CP	$7B
	JR	NC,MZK_XLAT3
	AND	$1F			; CONTROL CODE
	LD	E,A
	JR	MZK_XLAT4
MZK_XLAT3:
	LD	A,E
	CP	$5B			; $1B
	JR	Z,MZK_XLAT5
	CP	$5C			; $1C
	JR	Z,MZK_XLAT5
	CP	$5D			; $1D
	JR	Z,MZK_XLAT5
	CP	$5E			; $1E
	JR	Z,MZK_XLAT5
	CP	$2D			; $1F
	JR	NZ,MZK_XLAT4
	LD	E,$1F
	JR	MZK_XLAT4
MZK_XLAT5:
	AND	$1F			; CONTROL CODE
	LD	E,A
MZK_XLAT4:
	LD	A,E			; RESULT
	POP	DE			; RESTORE REGS
	POP	HL
	RET
;
