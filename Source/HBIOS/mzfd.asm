;==================================================================================================
;   SHARP MZ-800 FLOPPY DISK DRIVER (WD279X / MB8876 / WD177X ON THE SHARP FLOPPY INTERFACE)
;==================================================================================================
;
; PORTS OF THE SHARP FLOPPY INTERFACE (MZ-1E05, MZ-1E19 AND COMPATIBLES):
;
;   $D8	R: STATUS, W: COMMAND	\
;   $D9	TRACK REGISTER		 | CONTROLLER REGISTERS, THE DATA BUS IS INVERTED,
;   $DA	SECTOR REGISTER		 | SO THE DRIVER COMPLEMENTS EVERY VALUE
;   $DB	DATA REGISTER		/
;   $DC	W: BIT 7 MOTOR ON, BIT 2 DRIVE SELECT ENABLE, BITS 1-0 DRIVE
;   $DD	W: BIT 0 SIDE
;   $DE	W: BIT 0 HIGH DENSITY (HD MODIFICATION), KEPT AT DOUBLE DENSITY
;   $DF	W: BIT 0 DRQ INTERRUPT ENABLE (HD MODIFICATION), KEPT OFF
;
; THE DATA IS TRANSFERRED BY POLLING WITH INTERRUPTS DISABLED DURING A SECTOR: ABOUT 87 T-STATES
; PER BYTE, DOUBLE DENSITY BRINGS A BYTE EVERY 32 US = 113 T-STATES AT 3.55 MHZ.  WHILE WAITING
; FOR THE SECTOR TO COME, INTERRUPTS ARE LET IN BETWEEN THE STATUS POLLS.
;
; THE DATA IS STORED TRUE ON THE DISK (EVERY BYTE IS COMPLEMENTED ON ITS WAY), AS LAMAC'S CP/M
; FOR THE MZ-800 STORES IT, SO THE DATA AREA CAN BE READ ON A PC.  ONLY THE MZ-800 IPL BOOT TRACK
; (CYLINDER 0, SIDE 1, 16 X 256 BYTES) IS STORED INVERTED, IT LIES IN THE RESERVED TRACKS.
;
; THE STATUS BITS ARE CHECKED AS ALL CONTROLLERS USED ON THE INTERFACE REPORT THEM: NOT READY
; (BIT 7) IS NOT TRUSTED, THE WD1772 REPORTS ITS MOTOR THERE.  A COMMAND THAT ENDS WITHOUT ALL
; THE DATA IS AN ERROR.  READ/WRITE SECTOR ENABLE THE SIDE COMPARE WITH THE SIDE IN BIT 3, AS
; LAMAC'S CP/M 4.1 DOES ($82/$8A, $A2/$AA).
;
; MEDIA (LOGICAL CP/M TRACK = CYLINDER * 2 + SIDE, 9 SECTORS OF 512 BYTES NUMBERED FROM 1):
;   720K, 80 CYLINDERS: MID_FD720, ALSO THE 720K FORMAT OF LAMAC'S CP/M 4.1 (SAME DPB)
;   360K, 40 CYLINDERS: MID_FD360, ALSO LAMAC'S 360K: ITS DIRECTORY USES 2 OF THE 4 BLOCKS THAT
;	DPB_FD360 RESERVES FOR THE DIRECTORY, SO BOTH SYSTEMS CAN USE EACH OTHER'S DISKS.
;
; MEDIA DISCOVERY READS AN ID FIELD ON CYLINDER 2.  THE DRIVE TYPE GIVES THE FORMAT.  IN A 5.25"
; 80 TRACK DRIVE (FDT_5HD) A 40 TRACK DISK SHOWS CYLINDER 1 THERE AND IS USED WITH DOUBLE STEPS.
;
; THE MOTOR IS SWITCHED OFF MZFDMOTO SECONDS AFTER THE LAST ACCESS (FROM THE SYSTEM TICK).
;
MZFD_STS	.EQU	$D8		; R: STATUS, W: COMMAND
MZFD_TRK	.EQU	$D9		; TRACK REGISTER
MZFD_SEC	.EQU	$DA		; SECTOR REGISTER
MZFD_DAT	.EQU	$DB		; DATA REGISTER
MZFD_MOT	.EQU	$DC		; MOTOR AND DRIVE SELECT
MZFD_SIDE	.EQU	$DD		; SIDE
MZFD_DENS	.EQU	$DE		; DENSITY (HD MODIFICATION)
MZFD_INTEN	.EQU	$DF		; DRQ INTERRUPT ENABLE (HD MODIFICATION)
;
; CONTROLLER COMMANDS (TRUE VALUES)
;
MZFD_CRESTORE	.EQU	$08 | MZFDSTEP	; RESTORE, HEAD LOAD, NO VERIFY
MZFD_CSEEK	.EQU	$18 | MZFDSTEP	; SEEK, HEAD LOAD, NO VERIFY
MZFD_CREAD	.EQU	$82		; READ SECTOR, SIDE COMPARE (SIDE IN BIT 3)
MZFD_CWRITE	.EQU	$A2		; WRITE SECTOR, SIDE COMPARE (SIDE IN BIT 3)
MZFD_CRDADR	.EQU	$C0		; READ ADDRESS
MZFD_CFINT	.EQU	$D0		; FORCE INTERRUPT, NO INTRQ
;
MZFD_TRIES	.EQU	5		; ATTEMPTS PER SECTOR
MZFD_SPINDLY	.EQU	MZFDSPIN * 125 / 2	; SPIN UP TIME IN 16 US UNITS (VDELAY)
MZFD_SETLDLY	.EQU	MZFDSETL * 125 / 2	; HEAD SETTLE TIME IN 16 US UNITS
MZFD_MOTTICKS	.EQU	MZFDMOTO * TICKFREQ	; MOTOR OFF DELAY IN TICKS
;
#IF (MZFD_MOTTICKS > 255)
	.ECHO	"*** MZFDMOTO IS TOO LONG ***\n"
	!!!!!
#ENDIF
;
	DEVECHO	"MZFD: IO="
	DEVECHO	MZFD_STS
	DEVECHO	", UNITS="
	DEVECHO	MZFDCNT
	DEVECHO	"\n"
;
;--------------------------------------------------------------------------------------------------
;   HBIOS MODULE HEADER
;--------------------------------------------------------------------------------------------------
;
ORG_MZFD	.EQU	$
;
	.DW	SIZ_MZFD		; MODULE SIZE
	.DW	MZFD_INITPHASE		; ADR OF INIT PHASE HANDLER
;
MZFD_INITPHASE:
	; INIT PHASE HANDLER, A=PHASE
	CP	HB_PHASE_INIT		; INIT PHASE?
	JP	Z,MZFD_INIT		; DO INIT
	RET				; DONE
;
; PER UNIT CONFIG, IY POINTS TO IT IN THE DISK FUNCTIONS
;
MZFD_DEV	.EQU	0		; DEVICE NUMBER = DRIVE SELECT 0-3 (BYTE)
MZFD_STAT	.EQU	1		; LAST STATUS (BYTE)
MZFD_MEDTYP	.EQU	2		; MEDIA TYPE FDM..., $FF = NONE/UNKNOWN (BYTE)
MZFD_CURTRK	.EQU	3		; PHYSICAL CYLINDER UNDER THE HEAD, $FF = UNKNOWN (BYTE)
MZFD_HST	.EQU	4		; HOST POSITION, CCSH (DSKY FORMAT):
MZFD_HSTTRK	.EQU	MZFD_HST + 0	;   CYLINDER (WORD)
MZFD_HSTSEC	.EQU	MZFD_HST + 2	;   SECTOR FROM 0 (BYTE)
MZFD_HSTHD	.EQU	MZFD_HST + 3	;   HEAD (BYTE)
MZFD_TYPE	.EQU	8		; DRIVE TYPE FDT_... (BYTE)
MZFD_DSTEP	.EQU	9		; 1 = DOUBLE STEPPING (BYTE)
MZFD_CFGSIZ	.EQU	10		; SIZE OF AN ENTRY
;
MZFD_CFGTBL:
	.DB	0, 0, $FF, $FF		; UNIT 0
	.DW	0
	.DB	0, 0, MZFD0TYPE, 0
#IF (MZFDCNT >= 2)
	.DB	1, 0, $FF, $FF		; UNIT 1
	.DW	0
	.DB	0, 0, MZFD1TYPE, 0
#ENDIF
#IF (MZFDCNT >= 3)
	.DB	2, 0, $FF, $FF		; UNIT 2
	.DW	0
	.DB	0, 0, MZFD2TYPE, 0
#ENDIF
#IF (MZFDCNT >= 4)
	.DB	3, 0, $FF, $FF		; UNIT 3
	.DW	0
	.DB	0, 0, MZFD3TYPE, 0
#ENDIF
;
#IF (($ - MZFD_CFGTBL) != (MZFDCNT * MZFD_CFGSIZ))
	.ECHO	"*** INVALID MZFD CONFIG TABLE ***\n"
	!!!!!
#ENDIF
;
; MEDIA TABLE, INDEXED BY FDM...: CYLINDERS, HEADS, SECTORS PER TRACK, MEDIA ID
;
MZFD_MEDTBL:
	.DB	80, 2, 9, MID_FD720	; FDM720
	.DB	80, 2, 18, MID_FD144	; FDM144 (HIGH DENSITY, NOT SUPPORTED YET)
	.DB	40, 2, 9, MID_FD360	; FDM360
	.DB	80, 2, 15, MID_FD120	; FDM120 (HIGH DENSITY, NOT SUPPORTED YET)
;
; DEVICE ATTRIBUTES BY DRIVE TYPE (AS FD.ASM)
;
MZFD_DEVATTR:
	.DB	%11000000		; DRIVE TYPE NONE
	.DB	%11010101		; DRIVE TYPE 3.5" DD
	.DB	%11010110		; DRIVE TYPE 3.5" HD
	.DB	%11001101		; DRIVE TYPE 5.25" DD
	.DB	%11001110		; DRIVE TYPE 5.25" HD
	.DB	%11000101		; DRIVE TYPE 8"
;
;--------------------------------------------------------------------------------------------------
;   INITIALIZATION
;--------------------------------------------------------------------------------------------------
;
MZFD_INIT:
	CALL	NEWLINE			; FORMATTING
	PRTS("MZFD: IO=0x$")
	LD	A,MZFD_STS
	CALL	PRTHEXBYTE
	CALL	MZFD_DETECT		; CONTROLLER THERE?
	JR	Z,MZFD_INIT1
	PRTS(" NOT PRESENT$")
	OR	$FF			; SIGNAL FAILURE
	RET
;
MZFD_INIT1:
	PRTS(" UNITS=$")
	LD	A,MZFDCNT + '0'
	CALL	COUT
;
	; KNOWN STATE: NO DRQ INTERRUPT, DOUBLE DENSITY, MOTOR OFF, NO COMMAND RUNNING
	XOR	A
	OUT	(MZFD_INTEN),A
	OUT	(MZFD_DENS),A
	OUT	(MZFD_MOT),A
	LD	A,MZFD_CFINT
	CALL	MZFD_CMDOUT
;
	; ADD THE UNITS TO THE DISK UNIT TABLE
	LD	B,MZFDCNT		; LOOP CONTROL
	LD	IY,MZFD_CFGTBL		; START OF CFG TABLE
MZFD_INIT2:
	PUSH	BC			; SAVE LOOP CONTROL
	LD	BC,MZFD_FNTBL		; BC := FUNC TABLE ADR
	PUSH	IY			; CFG ENTRY POINTER
	POP	DE			; COPY TO DE
	CALL	DIO_ADDENT		; ADD ENTRY
	LD	BC,MZFD_CFGSIZ		; SIZE OF CFG ENTRY
	ADD	IY,BC			; BUMP IY TO NEXT ENTRY
	POP	BC			; RESTORE BC
	DJNZ	MZFD_INIT2		; LOOP AS NEEDED
;
#IF (SYSTIM != TM_NONE)
	; MOTOR OFF TIMER ON THE SYSTEM TICK
	LD	HL,(VEC_TICK + 1)	; CHAIN THE PREVIOUS TICK HANDLER
	LD	(MZFD_TICKNXT + 1),HL
	LD	HL,MZFD_TICK		; HOOK THE TICK VECTOR
	LD	(VEC_TICK + 1),HL
#ENDIF
	XOR	A			; INIT SUCCEEDED
	RET
;
; CONTROLLER PRESENCE: THE TRACK REGISTER MUST HOLD WHAT IS WRITTEN (NO BUS READS $FF)
;
MZFD_DETECT:
	LD	A,$A5
	OUT	(MZFD_TRK),A
	CALL	MZFD_DLY
	IN	A,(MZFD_TRK)
	CP	$A5
	RET	NZ
	LD	A,$5A
	OUT	(MZFD_TRK),A
	CALL	MZFD_DLY
	IN	A,(MZFD_TRK)
	CP	$5A
	RET
;
#IF (SYSTIM != TM_NONE)
;
; SYSTEM TICK: SWITCH THE MOTOR OFF WHEN THE TIMER RUNS OUT
;
MZFD_TICK:
	LD	A,(MZFD_MOTTMR)		; TIMER RUNNING?
	OR	A
	JR	Z,MZFD_TICKNXT
	DEC	A
	LD	(MZFD_MOTTMR),A
	JR	NZ,MZFD_TICKNXT
	OUT	(MZFD_MOT),A		; A = 0: MOTOR OFF, NO DRIVE SELECTED
	LD	(MZFD_MOTON),A
MZFD_TICKNXT:
	JP	0			; PREVIOUS TICK HANDLER (PATCHED)
#ENDIF
;
;--------------------------------------------------------------------------------------------------
;   DISK FUNCTIONS
;--------------------------------------------------------------------------------------------------
;
MZFD_FNTBL:
	.DW	MZFD_STATUS
	.DW	MZFD_RESET
	.DW	MZFD_SEEK
	.DW	MZFD_READ
	.DW	MZFD_WRITE
	.DW	MZFD_VERIFY
	.DW	MZFD_FORMAT
	.DW	MZFD_DEVICE
	.DW	MZFD_MEDIA
	.DW	MZFD_DEFMED
	.DW	MZFD_CAP
	.DW	MZFD_GEOM
#IF (($ - MZFD_FNTBL) != (DIO_FNCNT * 2))
	.ECHO	"*** INVALID MZFD FUNCTION TABLE ***\n"
	!!!!!
#ENDIF
;
MZFD_VERIFY:
MZFD_FORMAT:
MZFD_DEFMED:
	SYSCHKERR(ERR_NOTIMPL)		; INVALID SUB-FUNCTION
	RET
;
MZFD_STATUS:
	LD	A,(IY+MZFD_STAT)	; LAST STATUS
	OR	A
	RET
;
MZFD_RESET:
	LD	(IY+MZFD_STAT),0	; CLEAR THE STATUS
	LD	(IY+MZFD_CURTRK),$FF	; RECALIBRATE BEFORE THE NEXT ACCESS
	XOR	A
	RET
;
MZFD_DEVICE:
	LD	D,DIODEV_FD		; D := DEVICE TYPE
	LD	E,(IY+MZFD_DEV)		; E := PHYSICAL DEVICE NUMBER
	LD	A,(IY+MZFD_TYPE)	; DRIVE TYPE
	LD	HL,MZFD_DEVATTR		; DEVICE ATTR TABLE
	CALL	ADDHLA			; POINT TO ENTRY
	LD	C,(HL)			; C := ATTRIBUTES
	LD	H,0			; H := MODE (NONE)
	LD	L,MZFD_STS		; L := BASE I/O ADDRESS
	XOR	A			; SIGNAL SUCCESS
	RET
;
; MEDIA: E = 0 REPORTS THE KNOWN MEDIA, ELSE THE MEDIA IS DISCOVERED.  E := MEDIA ID.
;
MZFD_MEDIA:
	LD	A,E			; DISCOVER?
	OR	A
	CALL	NZ,MZFD_PROBE		; YES
	LD	A,(IY+MZFD_MEDTYP)
	CP	$FF			; ANY MEDIA?
	JR	Z,MZFD_NOMED
	CALL	MZFD_MEDENT		; HL := MEDIA TABLE ENTRY
	INC	HL
	INC	HL
	INC	HL
	LD	E,(HL)			; E := MEDIA ID
	LD	D,0
	XOR	A			; SIGNAL SUCCESS
	RET
;
MZFD_NOMED:
	LD	DE,0			; E := MID_NONE
	LD	HL,0
	LD	A,ERR_NOMEDIA		; NO MEDIA
	OR	A
	RET
;
MZFD_CAP:
	; DE:HL := NUMBER OF SECTORS, BC := 512
	CALL	MZFD_GEOM		; HL := CYLINDERS, D := HEADS, E := SECTORS
	RET	NZ
	PUSH	HL			; SAVE CYLINDERS
	LD	H,D			; HEADS
	RES	7,H			; NO LBA FLAG
	CALL	MULT8			; HL := SECTORS PER CYLINDER
	POP	DE			; E := CYLINDERS
	LD	H,L
	CALL	MULT8			; HL := TOTAL SECTORS
	LD	DE,0
	LD	BC,512
	XOR	A
	RET
;
MZFD_GEOM:
	; HL := CYLINDERS, D := HEADS (BIT 7 = LBA CAPABLE), E := SECTORS PER TRACK
	LD	A,(IY+MZFD_MEDTYP)
	CP	$FF			; ANY MEDIA?
	JR	Z,MZFD_NOMED
	CALL	MZFD_MEDENT		; HL := MEDIA TABLE ENTRY
	LD	A,(HL)			; CYLINDERS
	INC	HL
	LD	D,(HL)			; HEADS
	SET	7,D			; LBA CAPABLE (THE SEEK CONVERTS)
	INC	HL
	LD	E,(HL)			; SECTORS PER TRACK
	LD	L,A
	LD	H,0
	XOR	A
	RET
;
; SEEK: DE:HL IS CHS (D = HEAD, E = SECTOR FROM 0, HL = CYLINDER) OR LBA (BIT 7 OF D)
;
MZFD_SEEK:
	BIT	7,D			; LBA?
	JR	Z,MZFD_SEEK9		; NO, SAVE THE CHS AS IT IS
	; LBA (16 BITS IS ENOUGH FOR A FLOPPY) TO CHS
	PUSH	HL
	CALL	MZFD_GEOM		; E := SECTORS, D := HEADS
	POP	HL
	RET	NZ
	RES	7,D
	LD	(MZFD_CURGEOM),DE	; MZFD_CURSPT, MZFD_CURHDS
	LD	A,(MZFD_CURSPT)
	LD	D,0
	LD	E,A
	CALL	DIV16			; BC := TRACK, HL := SECTOR
	PUSH	HL			; SAVE SECTOR
	PUSH	BC
	POP	HL			; HL := TRACK
	LD	A,(MZFD_CURHDS)
	LD	D,0
	LD	E,A
	CALL	DIV16			; BC := CYLINDER, HL := HEAD
	PUSH	HL			; SAVE HEAD
	PUSH	BC
	POP	HL			; HL := CYLINDER
	POP	BC
	LD	D,C			; D := HEAD
	POP	BC
	LD	E,C			; E := SECTOR
MZFD_SEEK9:
	PUSH	HL			; SAVE CYLINDER
	LD	A,MZFD_HST		; HL := ADR OF THE HOST POSITION
	CALL	LDHLIYA
	EX	(SP),HL			; CYLINDER BACK, ADR TO (SP)
	POP	BC			; BC := ADR
	CALL	ST32			; SAVE DE:HL THERE
	XOR	A
	RET
;
; READ / WRITE: THE HBIOS DISK SUPERVISOR CALLS THE CODE AFTER "CALL HB_DSKREAD/WRITE" ONCE PER
; SECTOR WITH HL = BUFFER
;
MZFD_READ:
	CALL	HB_DSKREAD		; HOOK HBIOS DISK READ SUPERVISOR
	LD	A,MZFD_CREAD
	JR	MZFD_RW
;
MZFD_WRITE:
	CALL	HB_DSKWRITE		; HOOK HBIOS DISK WRITE SUPERVISOR
	LD	A,MZFD_CWRITE
;
MZFD_RW:
	LD	(MZFD_OPCMD),A		; SAVE THE COMMAND
	LD	(MZFD_DSKBUF),HL	; SAVE THE BUFFER ADDRESS
	LD	A,(IY+MZFD_MEDTYP)
	CP	$FF			; MEDIA KNOWN?
	JP	Z,MZFD_NOMED
	LD	A,4			; SHOW ACTIVITY
	CALL	LDHLIYA
	CALL	HB_DSKACTCHS
	CALL	MZFD_RUN		; THE SECTOR, WITH RETRIES
	CALL	MZFD_DONE		; START THE MOTOR OFF TIMER
	LD	(IY+MZFD_STAT),A	; SAVE THE STATUS
	OR	A
	RET	NZ			; ERROR
	CALL	MZFD_NEXT		; NEXT SECTOR
	XOR	A
	RET
;
;--------------------------------------------------------------------------------------------------
;   PRIVATE FUNCTIONS
;--------------------------------------------------------------------------------------------------
;
; READ OR WRITE THE SECTOR AT THE HOST POSITION (COMMAND IN MZFD_OPCMD, BUFFER IN MZFD_DSKBUF).
; RETURNS A = 0 OR AN HBIOS ERROR CODE.
;
MZFD_RUN:
	CALL	MZFD_SELECT		; MOTOR ON, DRIVE SELECTED
	LD	B,MZFD_TRIES
MZFD_RUN1:
	PUSH	BC
	CALL	MZFD_GOTRK		; HEAD TO THE CYLINDER
	JR	NZ,MZFD_RUN2
	LD	A,(IY+MZFD_HSTHD)	; SIDE
	OUT	(MZFD_SIDE),A
	LD	A,(IY+MZFD_HSTSEC)	; SECTOR NUMBER, FROM 1 ON THE DISK
	INC	A
	CPL
	OUT	(MZFD_SEC),A
	LD	A,(IY+MZFD_HSTHD)	; THE SIDE TO COMPARE GOES TO BIT 3
	AND	1
	RLCA
	RLCA
	RLCA
	LD	HL,MZFD_OPCMD
	OR	(HL)			; A := COMMAND
	LD	HL,(MZFD_DSKBUF)
	LD	DE,512
	CALL	MZFD_XFER		; Z IF OK, ELSE A := ERROR BITS
MZFD_RUN2:
	POP	BC
	RET	Z			; DONE (A = 0)
	LD	(MZFD_LASTST),A
	BIT	6,A			; WRITE PROTECTED?
	JR	NZ,MZFD_RUN4
	LD	A,B			; FROM THE THIRD ATTEMPT ON, RECALIBRATE FIRST
	CP	MZFD_TRIES
	JR	Z,MZFD_RUN3
	LD	(IY+MZFD_CURTRK),$FF
MZFD_RUN3:
	DJNZ	MZFD_RUN1
#IF (MZFDTRACE >= 1)
	CALL	MZFD_PRTERR
#ENDIF
	LD	A,ERR_IO		; GIVE UP
	OR	A
	RET
MZFD_RUN4:
	LD	A,ERR_READONLY
	OR	A
	RET
;
; MEDIA DISCOVERY: READ AN ID FIELD ON CYLINDER 2, SIDE 0 (THE DATA AREA OF EVERY FORMAT).
; SETS THE MEDIA TYPE, $FF IF NONE.
;
MZFD_PROBE:
	LD	(IY+MZFD_MEDTYP),$FF	; NONE UNTIL FOUND
	LD	(IY+MZFD_DSTEP),0
	LD	(IY+MZFD_CURTRK),$FF	; RECALIBRATE FIRST
	CALL	MZFD_SELECT
	LD	B,2			; TWO ATTEMPTS
MZFD_PROBE1:
	PUSH	BC
	LD	(IY+MZFD_HSTTRK),2	; CYLINDER 2, SIDE 0
	LD	(IY+MZFD_HSTTRK+1),0
	LD	(IY+MZFD_HSTHD),0
	CALL	MZFD_GOTRK
	JR	NZ,MZFD_PROBE2
	XOR	A
	OUT	(MZFD_SIDE),A
	LD	A,MZFD_CRDADR
	LD	HL,MZFD_IDBUF
	LD	DE,6
	CALL	MZFD_XFER		; Z IF AN ID WAS READ
MZFD_PROBE2:
	POP	BC
	JR	Z,MZFD_PROBE3
	LD	(IY+MZFD_CURTRK),$FF
	DJNZ	MZFD_PROBE1
	JR	MZFD_DONE		; NO MEDIA
;
MZFD_PROBE3:
	LD	A,(IY+MZFD_TYPE)
	LD	C,FDM360
	CP	FDT_5DD			; 5.25" 40 TRACKS: 360K
	JR	Z,MZFD_PROBE4
	LD	C,FDM720		; OTHERWISE 720K ...
	CP	FDT_5HD
	JR	NZ,MZFD_PROBE4
	LD	A,(MZFD_IDBUF)		; ... BUT IN A 5.25" 80 TRACK DRIVE ID CYLINDER 1
	CP	1			; AT CYLINDER 2 IS A 40 TRACK DISK
	JR	NZ,MZFD_PROBE4
	LD	C,FDM360
	LD	(IY+MZFD_DSTEP),1	; DOUBLE STEPPING
MZFD_PROBE4:
	LD	(IY+MZFD_MEDTYP),C
	; FALL THROUGH
;
; END OF AN ACCESS: START THE MOTOR OFF TIMER (AF PRESERVED)
;
MZFD_DONE:
	PUSH	AF
	LD	A,MZFD_MOTTICKS
	LD	(MZFD_MOTTMR),A
	POP	AF
	RET
;
; MOTOR ON AND DRIVE SELECTED, WAIT FOR THE SPIN UP IF THE MOTOR WAS OFF
;
MZFD_SELECT:
	XOR	A			; NO MOTOR OFF WHILE WORKING
	LD	(MZFD_MOTTMR),A
	OUT	(MZFD_DENS),A		; DOUBLE DENSITY
	LD	A,(IY+MZFD_DEV)		; DRIVE
	AND	3
	OR	$84			; MOTOR ON, SELECT ENABLE
	OUT	(MZFD_MOT),A
	LD	A,(MZFD_MOTON)		; RUNNING ALREADY?
	OR	A
	RET	NZ
	INC	A
	LD	(MZFD_MOTON),A
	LD	DE,MZFD_SPINDLY		; WAIT FOR THE SPIN UP
	JP	VDELAY
;
; HEAD TO THE HOST CYLINDER (RECALIBRATE IF THE POSITION IS UNKNOWN).  LEAVES THE TRACK REGISTER
; AT THE CYLINDER NUMBER OF THE IDS.  RETURNS Z IF OK, ELSE NZ AND A = ERROR BITS.
;
MZFD_GOTRK:
	LD	A,(IY+MZFD_CURTRK)
	INC	A			; $FF: UNKNOWN?
	JR	NZ,MZFD_GOTRK1
	CALL	MZFD_RECAL
	RET	NZ
MZFD_GOTRK1:
	LD	A,(IY+MZFD_CURTRK)	; TRACK REGISTER := WHERE THE HEAD IS
	CPL
	OUT	(MZFD_TRK),A
	LD	A,(IY+MZFD_HSTTRK)	; PHYSICAL TARGET CYLINDER
	BIT	0,(IY+MZFD_DSTEP)
	JR	Z,MZFD_GOTRK2
	ADD	A,A			; DOUBLE STEPPING
MZFD_GOTRK2:
	CP	(IY+MZFD_CURTRK)
	JR	Z,MZFD_GOTRK3		; ALREADY THERE
	LD	C,A			; C := TARGET
	LD	(IY+MZFD_CURTRK),$FF	; UNKNOWN UNTIL THE SEEK IS DONE
	CPL
	OUT	(MZFD_DAT),A		; DATA REGISTER := TARGET
	LD	A,MZFD_CSEEK
	CALL	MZFD_TYPE1		; CY ON TIMEOUT, BC KEPT
	JR	C,MZFD_GOTRK9
	LD	(IY+MZFD_CURTRK),C
	LD	DE,MZFD_SETLDLY		; HEAD SETTLE
	CALL	VDELAY
MZFD_GOTRK3:
	LD	A,(IY+MZFD_HSTTRK)	; TRACK REGISTER := CYLINDER IN THE IDS
	CPL
	OUT	(MZFD_TRK),A
	XOR	A
	RET
MZFD_GOTRK9:
	LD	A,$10			; SEEK ERROR
	OR	A
	RET
;
; RECALIBRATE: RESTORE TO CYLINDER 0.  RETURNS Z IF OK, ELSE NZ AND A = ERROR BITS.
;
MZFD_RECAL:
	LD	A,MZFD_CRESTORE
	CALL	MZFD_TYPE1		; A := STATUS
	JR	C,MZFD_GOTRK9		; TIMEOUT
	AND	$04			; TRACK 0?
	XOR	$04
	JR	NZ,MZFD_GOTRK9
	LD	(IY+MZFD_CURTRK),A	; A = 0: AT CYLINDER 0
	RET
;
; TYPE I COMMAND IN A (TRUE VALUE): ISSUE AND WAIT FOR THE END.  A := STATUS (TRUE), CY ON TIMEOUT
; (ABOUT 7 S).  BC, DE AND HL KEPT.
;
MZFD_TYPE1:
	PUSH	BC
	PUSH	DE
	CALL	MZFD_CMDOUT
	CALL	MZFD_DLY		; STATUS IS VALID AFTER ABOUT 30 US
	LD	A,8
	CALL	MZFD_WAIT
	POP	DE
	POP	BC
	RET
;
; WAIT UNTIL THE CONTROLLER IS NOT BUSY, A = TIMEOUT IN UNITS OF ABOUT 0.9 S.  A := STATUS (TRUE),
; CY ON TIMEOUT (THE COMMAND IS THEN STOPPED).  USES BC.
;
MZFD_WAIT:
	LD	(MZFD_TOHI),A
	LD	BC,0
MZFD_WAIT1:
	IN	A,(MZFD_STS)		; 48 T-STATES PER LOOP
	RRCA				; CY := NOT BUSY
	JR	C,MZFD_WAIT2
	DEC	BC
	LD	A,B
	OR	C
	JR	NZ,MZFD_WAIT1
	LD	A,(MZFD_TOHI)
	DEC	A
	LD	(MZFD_TOHI),A
	JR	NZ,MZFD_WAIT1
	LD	A,MZFD_CFINT		; TIMEOUT: STOP THE COMMAND
	CALL	MZFD_CMDOUT
	LD	A,$10			; AS RECORD NOT FOUND / SEEK ERROR
	SCF
	RET
MZFD_WAIT2:
	IN	A,(MZFD_STS)		; STATUS
	CPL
	OR	A			; CLEAR CY
	RET
;
; TRANSFER ONE SECTOR OR ID FIELD WITH THE COMMAND IN A (TRUE VALUE): READ SECTOR, WRITE SECTOR
; OR READ ADDRESS.  HL = BUFFER, DE = NUMBER OF BYTES.  RETURNS Z IF ALL THE BYTES WENT WITHOUT AN
; ERROR, ELSE NZ AND A = ERROR BITS OF THE STATUS (RECORD NOT FOUND IF THE COMMAND ENDED EARLY).
;
MZFD_XFER:
	LD	(MZFD_XCMD),A
#IF (INTMODE > 0)
	LD	A,(INTSENAB)		; INTERRUPTS IN USE: LET THEM IN WHILE WAITING
#ELSE
	XOR	A
#ENDIF
	LD	(MZFD_XIEN),A
	PUSH	DE
	LD	A,(MZFD_XCMD)
	DI
	CALL	MZFD_CMDOUT		; ISSUE THE COMMAND
	CALL	MZFD_DLY		; STATUS IS VALID AFTER ABOUT 30 US
	POP	DE
	LD	BC,0			; TIMEOUT 2 X 65536 POLLS (ABOUT 3.7 S)
	LD	A,2
	LD	(MZFD_TOHI),A
MZFD_XFER1:
	IN	A,(MZFD_STS)		; STATUS, INVERTED: ACTIVE BITS READ 0
	BIT	1,A			; DRQ?
	JR	Z,MZFD_XFER3		; THE FIRST BYTE: GO ON WITH INTERRUPTS OFF
	RRCA				; CY := NOT BUSY
	JR	C,MZFD_XFER7		; ENDED WITHOUT DATA
	LD	A,(MZFD_XIEN)		; INTERRUPT WINDOW
	OR	A
	JR	Z,MZFD_XFER2
	EI
	NOP
	DI
MZFD_XFER2:
	DEC	BC
	LD	A,B
	OR	C
	JR	NZ,MZFD_XFER1
	LD	A,(MZFD_TOHI)
	DEC	A
	LD	(MZFD_TOHI),A
	JR	NZ,MZFD_XFER1
	CALL	MZFD_IEN		; TIMEOUT (NO DISK?)
	LD	A,MZFD_CFINT		; STOP THE COMMAND
	CALL	MZFD_CMDOUT
	LD	A,$10			; AS RECORD NOT FOUND
	OR	A
	RET
;
MZFD_XFER3:
	LD	A,(MZFD_XCMD)
	AND	$E0
	CP	$A0			; WRITE SECTOR?
	JR	Z,MZFD_XWR
;
MZFD_XRD:
	; READ: 87 T-STATES PER BYTE
	IN	A,(MZFD_DAT)		; 11
	CPL				; 4
	LD	(HL),A			; 7
	INC	HL			; 6
	DEC	DE			; 6
	LD	A,D			; 4
	OR	E			; 4
	JR	Z,MZFD_XFER6		; 7	ALL BYTES
MZFD_XRD1:
	IN	A,(MZFD_STS)		; 11
	RRCA				; 4	CY := NOT BUSY
	JR	C,MZFD_XFER7		; 7	ENDED EARLY
	RRCA				; 4	CY := NO DRQ
	JR	NC,MZFD_XRD		; 12
	JR	MZFD_XRD1
;
MZFD_XWR:
	; WRITE: 90 T-STATES PER BYTE
	LD	A,(HL)			; 7
	CPL				; 4
	OUT	(MZFD_DAT),A		; 11
	INC	HL			; 6
	DEC	DE			; 6
	LD	A,D			; 4
	OR	E			; 4
	JR	Z,MZFD_XFER6		; 7	ALL BYTES
MZFD_XWR1:
	IN	A,(MZFD_STS)		; 11
	RRCA				; 4	CY := NOT BUSY
	JR	C,MZFD_XFER7		; 7	ENDED EARLY
	RRCA				; 4	CY := NO DRQ
	JR	NC,MZFD_XWR		; 12
	JR	MZFD_XWR1
;
MZFD_XFER6:
	; ALL BYTES: INTERRUPTS AGAIN, WAIT FOR THE END OF THE COMMAND (CRC)
	CALL	MZFD_IEN
	LD	A,1
	CALL	MZFD_WAIT		; A := STATUS
	JR	MZFD_XFER8
;
MZFD_XFER7:
	; THE COMMAND ENDED BEFORE ALL THE BYTES
	CALL	MZFD_IEN
	IN	A,(MZFD_STS)		; STATUS
	CPL
;
MZFD_XFER8:
	; A = FINAL STATUS
	LD	(MZFD_XSTS),A
	LD	B,A
	LD	C,$1C			; READ: RECORD NOT FOUND, CRC, LOST DATA
	LD	A,(MZFD_XCMD)
	AND	$E0
	CP	$A0			; WRITE SECTOR?
	JR	NZ,MZFD_XFER8A
	LD	C,$7C			; ALSO WRITE PROTECT, WRITE FAULT
MZFD_XFER8A:
	LD	A,B
	AND	C			; ERROR BITS
	RET	NZ
	LD	A,D			; ALL THE BYTES?
	OR	E
	RET	Z			; YES, OK
	LD	A,$10			; NO: AS RECORD NOT FOUND
	OR	A
	RET
;
; INTERRUPTS BACK ON IF THEY ARE IN USE (AF KEPT)
;
MZFD_IEN:
	PUSH	AF
	LD	A,(MZFD_XIEN)
	OR	A
	JR	Z,MZFD_IEN1
	POP	AF
	EI
	RET
MZFD_IEN1:
	POP	AF
	RET
;
; COMMAND IN A (TRUE VALUE) TO THE CONTROLLER
;
MZFD_CMDOUT:
	CPL
	OUT	(MZFD_STS),A
	RET
;
; DELAY ABOUT 110 US (A AND DE DESTROYED)
;
MZFD_DLY:
	LD	DE,7
	JP	VDELAY
;
; NEXT SECTOR OF THE HOST POSITION
;
MZFD_NEXT:
	CALL	MZFD_MEDENT		; HL := MEDIA TABLE ENTRY
	INC	HL
	LD	B,(HL)			; B := HEADS
	INC	HL
	LD	A,(HL)			; A := SECTORS PER TRACK
	INC	(IY+MZFD_HSTSEC)
	CP	(IY+MZFD_HSTSEC)
	RET	NZ
	LD	(IY+MZFD_HSTSEC),0
	INC	(IY+MZFD_HSTHD)
	LD	A,B
	CP	(IY+MZFD_HSTHD)
	RET	NZ
	LD	(IY+MZFD_HSTHD),0
	INC	(IY+MZFD_HSTTRK)
	RET
;
; HL := MEDIA TABLE ENTRY OF THE UNIT'S MEDIA
;
MZFD_MEDENT:
	LD	A,(IY+MZFD_MEDTYP)
	ADD	A,A			; 4 BYTES PER ENTRY
	ADD	A,A
	LD	HL,MZFD_MEDTBL
	JP	ADDHLA
;
#IF (MZFDTRACE >= 1)
;
; PRINT THE FAILED SECTOR AND THE LAST STATUS
;
MZFD_PRTERR:
	CALL	NEWLINE
	PRTS("MZFD$")
	LD	A,(IY+MZFD_DEV)
	CALL	PRTDECB
	PRTS(": ERR ST=$")
	LD	A,(MZFD_LASTST)
	CALL	PRTHEXBYTE
	PRTS(" C=$")
	LD	A,(IY+MZFD_HSTTRK)
	CALL	PRTDECB
	PRTS(" H=$")
	LD	A,(IY+MZFD_HSTHD)
	CALL	PRTDECB
	PRTS(" S=$")
	LD	A,(IY+MZFD_HSTSEC)
	INC	A
	JP	PRTDECB
#ENDIF
;
; WORKING DATA
;
MZFD_MOTON	.DB	0		; MOTOR RUNNING
MZFD_MOTTMR	.DB	0		; MOTOR OFF TIMER (TICKS), 0 = STOPPED
MZFD_OPCMD	.DB	0		; READ OR WRITE COMMAND OF THE CURRENT REQUEST
MZFD_DSKBUF	.DW	0		; BUFFER OF THE CURRENT REQUEST
MZFD_XCMD	.DB	0		; COMMAND OF THE CURRENT TRANSFER
MZFD_XIEN	.DB	0		; INTERRUPTS IN USE DURING THE TRANSFER
MZFD_XSTS	.DB	0		; FINAL STATUS OF THE LAST TRANSFER
MZFD_LASTST	.DB	0		; ERROR BITS OF THE LAST FAILED ATTEMPT
MZFD_TOHI	.DB	0		; TIMEOUT, HIGH COUNTER
MZFD_CURSPT	.DB	0		; SECTORS PER TRACK (LBA CONVERSION)
MZFD_CURHDS	.DB	0		; HEADS (LBA CONVERSION)
MZFD_CURGEOM	.EQU	MZFD_CURSPT
MZFD_IDBUF	.FILL	6,0		; ID FIELD FROM READ ADDRESS: C, H, R, N, CRC
;
;--------------------------------------------------------------------------------------------------
;   HBIOS MODULE TRAILER
;--------------------------------------------------------------------------------------------------
;
END_MZFD	.EQU	$
SIZ_MZFD	.EQU	END_MZFD - ORG_MZFD
;
	MEMECHO	"MZFD occupies "
	MEMECHO	SIZ_MZFD
	MEMECHO	" bytes.\n"
