;==================================================================================================
; UNICARD RTC DRIVER (SHARP MZ-700/800/1500 UNICARD AND COMPATIBLE CARDS)
;==================================================================================================
;
; THE UNICARD REPOSITORY API (PORTS $50/$51) HAS CLOCK COMMANDS:
;   $62 RTCGETD: 3 BYTES OUT: DAY, MONTH, YEAR - 1980 (BINARY)
;   $63 RTCGETT: 3 BYTES OUT: HOURS, MINUTES, SECONDS (BINARY)
;   $60 RTCSETD: 3 BYTES IN:  DAY, MONTH, YEAR - 1980
;   $61 RTCSETT: 3 BYTES IN:  HOURS, MINUTES, SECONDS
; EVERY PORT ACCESS HOLDS THE CPU IN WAIT UNTIL THE CARD IS DONE, SO NO
; STATUS POLLING IS NEEDED.  WITHOUT A CARD THE PORTS READ $FF.
;
UCRTC_CMD	.EQU	$50		; REPOSITORY COMMAND / STATUS
UCRTC_DATA	.EQU	$51		; REPOSITORY DATA
UCRTC_STSR	.EQU	$03		; RESET STATUS POINTER
UCRTC_SETD	.EQU	$60
UCRTC_SETT	.EQU	$61
UCRTC_GETD	.EQU	$62
UCRTC_GETT	.EQU	$63
UCRTC_BUFSIZ	.EQU	6		; YYMMDDHHMMSS
;
	DEVECHO	"UCRTC: IO="
	DEVECHO	UCRTC_CMD
	DEVECHO	"\n"
;
;--------------------------------------------------------------------------------------------------
;   HBIOS MODULE HEADER
;--------------------------------------------------------------------------------------------------
;
ORG_UCRTC	.EQU	$
;
	.DW	SIZ_UCRTC		; MODULE SIZE
	.DW	UCRTC_INITPHASE		; ADR OF INIT PHASE HANDLER
;
UCRTC_INITPHASE:
	; INIT PHASE HANDLER, A=PHASE
	CP	HB_PHASE_INIT		; INIT PHASE?
	JP	Z,UCRTC_INIT		; DO INIT
	RET				; DONE
;
; RTC DEVICE INITIALIZATION ENTRY
;
UCRTC_INIT:
	LD	A,(RTC_DISPACT)		; RTC DISPATCHER ALREADY SET?
	OR	A			; SET FLAGS
	RET	NZ			; IF ALREADY ACTIVE, ABORT
;
	CALL	NEWLINE			; FORMATTING
	PRTS("UCRTC: IO=0x$")
	LD	A,UCRTC_CMD
	CALL	PRTHEXBYTE
;
	; A CARD ANSWERS STATUS BYTE 0 WITH SOMETHING ELSE THAN $FF
	LD	A,UCRTC_STSR		; RESET STATUS POINTER
	OUT	(UCRTC_CMD),A
	IN	A,(UCRTC_CMD)		; STATUS BYTE 0
	INC	A			; $FF?
	JR	NZ,UCRTC_INIT1		; IF NOT, CARD PRESENT
	PRTS(" NOT PRESENT$")
	OR	$FF			; SIGNAL FAILURE
	RET
;
UCRTC_INIT1:
	CALL	PC_SPACE		; DISPLAY CURRENT TIME
	CALL	UCRTC_GETTIM0
	LD	HL,UCRTC_BUF
	CALL	PRTDT
;
	LD	BC,UCRTC_DISPATCH	; REGISTER AS THE RTC
	CALL	RTC_SETDISP
	XOR	A			; SIGNAL SUCCESS
	RET
;
; RTC DEVICE FUNCTION DISPATCH ENTRY
;   A: RESULT (OUT), 0=OK, Z=OK, NZ=ERR
;   B: FUNCTION (IN)
;
UCRTC_DISPATCH:
	LD	A,B		; GET REQUESTED FUNCTION
	AND	$0F		; ISOLATE SUB-FUNCTION
	JP	Z,UCRTC_GETTIM	; GET TIME
	DEC	A
	JP	Z,UCRTC_SETTIM	; SET TIME
	DEC	A
	JP	Z,UCRTC_GETBYT	; GET NVRAM BYTE VALUE
	DEC	A
	JP	Z,UCRTC_SETBYT	; SET NVRAM BYTE VALUE
	DEC	A
	JP	Z,UCRTC_GETBLK	; GET NVRAM DATA BLOCK VALUES
	DEC	A
	JP	Z,UCRTC_SETBLK	; SET NVRAM DATA BLOCK VALUES
	DEC	A
	JP	Z,UCRTC_GETALM	; GET ALARM
	DEC	A
	JP	Z,UCRTC_SETALM	; SET ALARM
	DEC	A
	JP	Z,UCRTC_DEVICE	; REPORT RTC DEVICE INFO
	SYSCHKERR(ERR_NOFUNC)
	RET
;
; THE CARD HAS NO NVRAM AND NO ALARM
;
UCRTC_GETBYT:
UCRTC_SETBYT:
UCRTC_GETBLK:
UCRTC_SETBLK:
UCRTC_GETALM:
UCRTC_SETALM:
	SYSCHKERR(ERR_NOTIMPL)
	RET
;
; RTC GET TIME
;   A: RESULT (OUT), 0=OK, Z=OK, NZ=ERR
;   HL: DATE/TIME BUFFER (OUT)
; BUFFER FORMAT IS BCD: YYMMDDHHMMSS, 24 HOUR TIME
;
UCRTC_GETTIM:
	PUSH	HL			; SAVE PTR TO CALLERS BUFFER
	CALL	UCRTC_GETTIM0		; GET TIME TO WORK BUFFER
	; NOW COPY TO REAL DESTINATION (INTERBANK SAFE)
	LD	A,BID_BIOS		; COPY FROM BIOS BANK
	LD	(HB_SRCBNK),A		; SET IT
	LD	A,(HB_INVBNK)		; COPY TO CURRENT USER BANK
	LD	(HB_DSTBNK),A		; SET IT
	LD	HL,UCRTC_BUF		; SOURCE ADR
	POP	DE			; DEST ADR
	LD	BC,UCRTC_BUFSIZ		; LENGTH
	CALL	HB_BNKCPY		; COPY THE CLOCK DATA
	XOR	A			; SIGNAL SUCCESS
	RET				; AND RETURN
;
; READ THE CARD CLOCK INTO UCRTC_BUF (BCD).  THE TIME IS READ BEFORE AND
; AFTER THE DATE; IF THE HOUR WRAPPED IN BETWEEN (MIDNIGHT), READ AGAIN.
;
UCRTC_GETTIM0:
	CALL	UCRTC_RDTIME		; TIME
	LD	A,(UCRTC_HH)
	PUSH	AF			; SAVE HOURS
	LD	A,UCRTC_GETD		; DATE
	OUT	(UCRTC_CMD),A
	IN	A,(UCRTC_DATA)		; DAY
	CALL	BYTE2BCD
	LD	(UCRTC_DT),A
	IN	A,(UCRTC_DATA)		; MONTH
	CALL	BYTE2BCD
	LD	(UCRTC_MO),A
	IN	A,(UCRTC_DATA)		; YEAR - 1980
	ADD	A,80			; TWO DIGIT YEAR (1980-2079)
	CP	100
	JR	C,UCRTC_GETTIM1
	SUB	100
UCRTC_GETTIM1:
	CALL	BYTE2BCD
	LD	(UCRTC_YR),A
	CALL	UCRTC_RDTIME		; TIME AGAIN
	POP	AF			; FIRST HOURS
	LD	B,A
	LD	A,(UCRTC_HH)		; STILL THE SAME HOUR?
	CP	B
	RET	Z			; IF SO, DATE AND TIME MATCH
	JR	UCRTC_GETTIM0		; ELSE READ AGAIN
;
UCRTC_RDTIME:
	LD	A,UCRTC_GETT		; TIME
	OUT	(UCRTC_CMD),A
	IN	A,(UCRTC_DATA)		; HOURS
	CALL	BYTE2BCD
	LD	(UCRTC_HH),A
	IN	A,(UCRTC_DATA)		; MINUTES
	CALL	BYTE2BCD
	LD	(UCRTC_MM),A
	IN	A,(UCRTC_DATA)		; SECONDS
	CALL	BYTE2BCD
	LD	(UCRTC_SS),A
	RET
;
; RTC SET TIME
;   A: RESULT (OUT), 0=OK, Z=OK, NZ=ERR
;   HL: DATE/TIME BUFFER (IN)
; BUFFER FORMAT IS BCD: YYMMDDHHMMSS, 24 HOUR TIME, YEARS 00-79 ARE 2000-2079
;
UCRTC_SETTIM:
	; COPY TO TEMP BUF
	LD	A,(HB_INVBNK)		; COPY FROM CURRENT USER BANK
	LD	(HB_SRCBNK),A		; SET IT
	LD	A,BID_BIOS		; COPY TO BIOS BANK
	LD	(HB_DSTBNK),A		; SET IT
	LD	DE,UCRTC_BUF		; DEST ADR
	LD	BC,UCRTC_BUFSIZ		; LENGTH
	CALL	HB_BNKCPY		; COPY THE CLOCK DATA
;
	LD	A,UCRTC_SETD		; DATE
	OUT	(UCRTC_CMD),A
	LD	A,(UCRTC_DT)		; DAY
	CALL	BCD2BYTE
	OUT	(UCRTC_DATA),A
	LD	A,(UCRTC_MO)		; MONTH
	CALL	BCD2BYTE
	OUT	(UCRTC_DATA),A
	LD	A,(UCRTC_YR)		; YEAR
	CALL	BCD2BYTE
	CP	80			; 80-99 ARE 1980-1999
	JR	NC,UCRTC_SETTIM1
	ADD	A,100			; 00-79 ARE 2000-2079
UCRTC_SETTIM1:
	SUB	80			; YEAR - 1980
	OUT	(UCRTC_DATA),A
;
	LD	A,UCRTC_SETT		; TIME
	OUT	(UCRTC_CMD),A
	LD	A,(UCRTC_HH)		; HOURS
	CALL	BCD2BYTE
	OUT	(UCRTC_DATA),A
	LD	A,(UCRTC_MM)		; MINUTES
	CALL	BCD2BYTE
	OUT	(UCRTC_DATA),A
	LD	A,(UCRTC_SS)		; SECONDS
	CALL	BCD2BYTE
	OUT	(UCRTC_DATA),A
	XOR	A			; SIGNAL SUCCESS
	RET				; AND RETURN
;
; REPORT RTC DEVICE INFO
;
UCRTC_DEVICE:
	LD	D,RTCDEV_UC		; D := DEVICE TYPE
	LD	E,0			; E := PHYSICAL DEVICE NUMBER
	LD	H,0			; H := 0, DRIVER HAS NO MODES
	LD	L,UCRTC_CMD		; L := BASE I/O ADDRESS
	XOR	A			; SIGNAL SUCCESS
	RET
;
; WORKING VARIABLES
;
UCRTC_BUF:	; ALL IN BCD!!!
UCRTC_YR	.DB	0
UCRTC_MO	.DB	0
UCRTC_DT	.DB	0
UCRTC_HH	.DB	0
UCRTC_MM	.DB	0
UCRTC_SS	.DB	0
;
;--------------------------------------------------------------------------------------------------
;   HBIOS MODULE TRAILER
;--------------------------------------------------------------------------------------------------
;
END_UCRTC	.EQU	$
SIZ_UCRTC	.EQU	END_UCRTC - ORG_UCRTC
;
	MEMECHO	"UCRTC occupies "
	MEMECHO	SIZ_UCRTC
	MEMECHO	" bytes.\n"
