;======================================================================
;	COMMON PART OF THE ROMWBW LOADERS FOR THE SHARP MZ-800
;======================================================================
;
; INCLUDED BY THE LOADERS (MZFLDR.ASM, MZIPL.ASM) IN THEIR MAIN PART,
; WHICH RUNS AT MAIN_LOC ($C000-$CFFF, STACK INCLUDED) IN MZ-700 MODE.
;
; MEMEXT (PORT $E7, PAGE OF THE CPU ADDRESS SPACE IN A12-A15, BANK AS
; DATA): PEHU HAS 8K BANKS (AN ODD PAGE FOLLOWS THE EVEN ONE), LUFTNER
; HAS 4K BANKS.  ROMWBW BANK $80+N IS MEMEXT RAM AT N * 32K FOR BOTH.
;
; THE LOADER DEFINES MAIN_LOC AND STR_STOP.
;
;----------------------------------------------------------------------
; MEMEXT DETECTION ON CPU PAGE 4 ($4000) WITH BANKS $20 AND $22.  THEIR
; FIRST BYTES ARE RESTORED.  RETURNS A = 0 PEHU, 1 LUFTNER, $FF NONE.
; PAGES 4 AND 5 ARE LEFT IDENTITY MAPPED.
;----------------------------------------------------------------------
;
MX_DETECT:
	LD	HL,$4000		; TEST ADDRESS
	LD	BC,$4000 | MX_PORT	; PAGE 4
	LD	A,$20			; BANK X
	OUT	(C),A
	LD	D,(HL)			; SAVE ORIGINAL BYTE
	LD	(HL),$AA		; MARKER X
	LD	A,$22			; BANK Y
	OUT	(C),A
	LD	E,(HL)			; SAVE ORIGINAL BYTE
	LD	(HL),$55		; MARKER Y
	LD	A,$20			; BACK TO BANK X
	OUT	(C),A
	LD	A,(HL)
	CP	$AA			; DISTINCT BANKS?
	LD	A,$FF			; NO MEMEXT
	RET	NZ			; (NOTHING TO RESTORE, SAME RAM)
	LD	B,$50			; PAGE 5, ODD PAGE OF THE PAIR
	LD	A,$22			; BANK Y
	OUT	(C),A
	LD	A,(HL)			; PEHU MAPS THE PAIR, LUFTNER PAGE 5 ONLY
	SUB	$55			; ZERO IF PEHU
	JR	Z,MX_DET1
	LD	A,1			; LUFTNER
MX_DET1:
	PUSH	AF			; SAVE TYPE
	LD	B,$40			; RESTORE THE ORIGINAL BYTES
	LD	A,$22
	OUT	(C),A
	LD	(HL),E
	LD	A,$20
	OUT	(C),A
	LD	(HL),D
	POP	AF			; TYPE
	PUSH	AF
	OR	A			; IDENTITY MAP FOR PAGES 4 AND 5
	LD	A,2			; PEHU: 8K BANK 2 AT $4000-$5FFF
	JR	Z,MX_DET2
	LD	A,4			; LUFTNER: 4K BANKS 4 AND 5
	OUT	(C),A
	LD	B,$50
	INC	A
MX_DET2:
	OUT	(C),A
	POP	AF			; TYPE
	RET
;
;----------------------------------------------------------------------
; DETECT MEMEXT AND REPORT IT, STOP WITHOUT IT.  THEN MOVE TO THE
; COMMON BANK (MX_TOCOM).
;----------------------------------------------------------------------
;
MX_SETUP:
	CALL	MX_DETECT		; A := 0 PEHU, 1 LUFTNER, $FF NONE
	LD	(MX_TYPE),A
	INC	A			; NONE?
	JR	NZ,MX_SETUP1
	LD	HL,STR_NOMX
	JP	FAIL
MX_SETUP1:
	LD	HL,STR_PEHU		; REPORT TYPE
	LD	A,(MX_TYPE)
	OR	A
	JR	Z,MX_SETUP2
	LD	HL,STR_LUFT
MX_SETUP2:
	CALL	PRTLN
	JP	MX_TOCOM		; NOW RUN FROM THE COMMON BANK
;
;----------------------------------------------------------------------
; MAP 32K MEMEXT BANK A (0-15) AT $0000-$7FFF.  BC, DE, HL DESTROYED.
;----------------------------------------------------------------------
;
MX_LOWER:
	LD	BC,$0000 | MX_PORT	; FIRST PAGE
	LD	E,A			; SAVE BANK
	LD	A,(MX_TYPE)
	OR	A			; PEHU?
	LD	A,E
	JR	NZ,MX_LOWER1
	RLCA				; PEHU: FIRST 8K BANK = BANK * 4
	RLCA
	LD	DE,$2004		; PAGE STEP $20, 4 WINDOWS
	JR	MX_LOWER2
MX_LOWER1:
	RLCA				; LUFTNER: FIRST 4K BANK = BANK * 8
	RLCA
	RLCA
	LD	DE,$1008		; PAGE STEP $10, 8 WINDOWS
MX_LOWER2:
	OUT	(C),A			; MAP ONE WINDOW
	INC	A			; NEXT BANK
	LD	L,A
	LD	A,B			; NEXT PAGE
	ADD	A,D
	LD	B,A
	LD	A,L
	DEC	E
	JR	NZ,MX_LOWER2
	RET
;
;----------------------------------------------------------------------
; MOVE THIS CODE (AND ITS STACK, $C000-$CFFF) INTO THE COMMON BANK AND
; MAP THE COMMON BANK AT $8000-$FFFF.  THE COPY GOES THROUGH A WINDOW AT
; $4000 SHOWING THE PART OF THE COMMON BANK THAT WILL APPEAR AT $C000.
; WHEN $8000-$FFFF IS SWITCHED, THE SAME BYTES ARE ALREADY THERE.
;----------------------------------------------------------------------
;
MX_TOCOM:
	LD	BC,$4000 | MX_PORT	; WINDOW: PAGE 4
	LD	A,(MX_TYPE)
	OR	A
	LD	A,COM_BANK * 4 + 2	; PEHU: 8K BANK FOR $C000-$DFFF
	JR	Z,MX_TOCOM1
	LD	A,COM_BANK * 8 + 4	; LUFTNER: 4K BANK FOR $C000-$CFFF
MX_TOCOM1:
	OUT	(C),A
	LD	HL,MAIN_LOC		; COPY $C000-$CFFF, STACK INCLUDED
	LD	DE,$4000
	LD	BC,$1000
	LDIR
	; SWITCH $8000-$FFFF TO THE COMMON BANK.  NO STACK USE FROM THE COPY
	; UNTIL HERE: A CALL WOULD PUSH ITS RETURN ADDRESS INTO THE OLD BANK.
	LD	BC,$8000 | MX_PORT	; FIRST UPPER PAGE
	LD	A,(MX_TYPE)
	OR	A
	LD	A,COM_BANK * 4		; PEHU: FIRST 8K BANK
	LD	DE,$2004		; PAGE STEP $20, 4 WINDOWS
	JR	Z,MX_TOCOM3
	LD	A,COM_BANK * 8		; LUFTNER: FIRST 4K BANK
	LD	DE,$1008		; PAGE STEP $10, 8 WINDOWS
MX_TOCOM3:
	OUT	(C),A			; MAP ONE WINDOW
	INC	A			; NEXT BANK
	LD	L,A
	LD	A,B			; NEXT PAGE
	ADD	A,D
	LD	B,A
	LD	A,L
	DEC	E
	JR	NZ,MX_TOCOM3
	LD	BC,$4000 | MX_PORT	; WINDOW BACK TO IDENTITY
	LD	A,(MX_TYPE)
	OR	A
	LD	A,2			; PEHU: 8K BANK 2
	JR	Z,MX_TOCOM2
	LD	A,4			; LUFTNER: 4K BANK 4
MX_TOCOM2:
	OUT	(C),A
	RET
;
;----------------------------------------------------------------------
; START HBIOS: BANK $80 LOW, MZ-800 MODE, RAM EVERYWHERE, JUMP TO 0
;----------------------------------------------------------------------
;
HB_GO:
	XOR	A
	CALL	MX_LOWER
	LD	A,$04			; MZ-800 MODE, 640X200
	OUT	(GDG_DMD),A
	OUT	($E0),A			; RAM AT $0000-$1FFF
	OUT	($E1),A			; RAM AT $E000-$FFFF
	IN	A,($E1)			; CG-ROM AND VRAM OUT
	JP	0			; HBIOS
;
FAIL:
	; PRINT MESSAGE HL AND STOP
	CALL	PRTLN
	LD	HL,STR_STOP
	CALL	PRTLN
	DI
	HALT
;
;----------------------------------------------------------------------
; TEXT OUTPUT ON THE MZ-700 MODE SCREEN
;----------------------------------------------------------------------
;
CLS:
	LD	HL,TXT_VRAM		; CHARACTERS: BLANK
	LD	DE,TXT_VRAM + 1
	LD	BC,TXT_COLS * TXT_ROWS - 1
	LD	(HL),0
	LDIR
	LD	HL,TXT_ATTR		; ATTRIBUTES: WHITE ON BLUE
	LD	DE,TXT_ATTR + 1
	LD	BC,TXT_COLS * TXT_ROWS - 1
	LD	(HL),$71
	LDIR
	LD	HL,TXT_VRAM		; CURSOR HOME
	LD	(CURSOR),HL
	LD	(LINE),HL
	RET
;
PRTLN:
	CALL	PRT			; PRINT HL, THEN NEW LINE
NEWLINE:
	LD	HL,(LINE)		; NEXT LINE
	LD	DE,TXT_COLS
	ADD	HL,DE
	LD	(LINE),HL
	LD	(CURSOR),HL
	RET
;
PRT:
	LD	A,(HL)			; PRINT ZERO TERMINATED STRING HL
	INC	HL
	OR	A
	RET	Z
	PUSH	HL
	CALL	PUTC
	POP	HL
	JR	PRT
;
PRTHEX:
	; PRINT A AS TWO HEX DIGITS
	PUSH	AF
	RRCA
	RRCA
	RRCA
	RRCA
	CALL	PRTHEX1
	POP	AF
PRTHEX1:
	AND	$0F
	ADD	A,'0'
	CP	'9' + 1
	JR	C,PUTC
	ADD	A,'A' - '9' - 1
	; FALL THROUGH
;
PUTC:
	; ASCII CHARACTER A AT THE CURSOR (UPPER CASE, DIGITS, SOME SIGNS)
	PUSH	DE
	PUSH	HL
	CALL	DISPCODE
	LD	HL,(CURSOR)
	LD	(HL),A
	INC	HL
	LD	(CURSOR),HL
	POP	HL
	POP	DE
	RET
;
DISPCODE:
	; ASCII A -> MZ DISPLAY CODE A
	CP	'A'
	JR	C,DISPCODE1
	CP	'Z' + 1
	JR	NC,DISPCODE1
	SUB	$40			; A-Z = $01-$1A
	RET
DISPCODE1:
	CP	'0'
	JR	C,DISPCODE2
	CP	'9' + 1
	JR	NC,DISPCODE2
	SUB	$10			; 0-9 = $20-$29
	RET
DISPCODE2:
	LD	HL,DISPTBL		; OTHER SIGNS FROM A TABLE
	LD	E,A
DISPCODE3:
	LD	A,(HL)
	OR	A			; END OF TABLE: BLANK
	RET	Z
	INC	HL
	CP	E
	LD	A,(HL)
	INC	HL
	RET	Z
	JR	DISPCODE3
;
DISPTBL:	; ASCII, DISPLAY CODE
	.DB	'.', $2E, ':', $4F, ',', $2F, '-', $2A, '/', $2D, '(', $68
	.DB	')', $69, '!', $61, '?', $49, '=', $2B, '_', $2A
	.DB	0
;
STR_PEHU	.DB	"MEMEXT: PEHU 512K", 0
STR_LUFT	.DB	"MEMEXT: LUFTNER 512K", 0
STR_NOMX	.DB	"ERROR: NO MEMEXT (PEHU OR LUFTNER 512K)", 0
STR_STOP	.DB	"STOPPED.", 0
;
MX_TYPE		.DB	0		; 0 = PEHU, 1 = LUFTNER
CURSOR		.DW	0		; TEXT CURSOR
LINE		.DW	0		; START OF THE CURRENT LINE
