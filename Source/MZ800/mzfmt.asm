;======================================================================
;	MZFMT: FORMAT A FLOPPY ON THE SHARP MZ-800 (ROMWBW)
;======================================================================
;
; USAGE:  MZFMT D: [/360] [/PC]
;
; FORMATS THE FLOPPY IN DRIVE D: THROUGH HBIOS (DIODEFMED, DIOFORMAT OF
; THE MZ-800 FLOPPY DRIVER MZFD.ASM): 720K (80 CYLINDERS), OR 360K WITH
; /360 (40 CYLINDERS, THE DEFAULT IN 5.25" DOUBLE DENSITY DRIVES), 9
; SECTORS OF 512 BYTES FILLED WITH $E5 (AN EMPTY DIRECTORY).
;
; BY DEFAULT THE DISK GETS THE MZ LAYOUT OF LAMAC'S CP/M: CYLINDER 0,
; SIDE 1 IS THE IPL BOOT TRACK OF 16 SECTORS OF 256 BYTES, READY FOR
; MZSYS.  /PC LEAVES IT OUT (THE LAYOUT OF ROMWBW FD720/FD360, ALSO READ
; BY PCS).  THE DATA AREA IS THE SAME IN BOTH.
;
;======================================================================
;
BDOS		.EQU	$0005
FCB1		.EQU	$005C		; DRIVE OF THE FIRST ARGUMENT
CMDTAIL		.EQU	$0080		; COMMAND TAIL (LENGTH, TEXT)
;
BF_DIOFORMAT	.EQU	$16		; HBIOS: FORMAT TRACK
BF_DIODEVICE	.EQU	$17		; HBIOS: DEVICE INFO
BF_DIODEFMED	.EQU	$19		; HBIOS: DEFINE MEDIA
DIODEV_FD	.EQU	$01		; FLOPPY DEVICE TYPE
MID_FD720	.EQU	5
MID_FD360	.EQU	7
MZFD_IO		.EQU	$D8		; I/O BASE OF THE MZ-800 FLOPPY DRIVER
;
	.ORG	$0100
;
F_START:
	LD	(F_SAVSP),SP
	LD	SP,F_STACK
	LD	DE,F_STRBANNER
	CALL	F_PRTSTR
;
	; ROMWBW HBIOS AND CBIOS?
	LD	HL,($FFFC)		; HB_IDENT: ADDRESS OF THE IDENT BLOCK
	LD	A,(HL)			; 'W', ~'W'
	CP	'W'
	JP	NZ,F_ERRWBW
	INC	HL
	LD	A,(HL)
	CP	~'W'
	JP	NZ,F_ERRWBW
	LD	HL,($40)		; CBIOS STAMP IN PAGE ZERO: 'W', ~'W'
	LD	A,L
	CP	'W'
	JP	NZ,F_ERRWBW
	LD	A,H
	CP	~'W'
	JP	NZ,F_ERRWBW
;
	; DRIVE AND OPTIONS
	LD	A,(FCB1)		; 1-16, 0 = NONE
	OR	A
	JP	Z,F_USAGE
	DEC	A
	LD	(F_DRIVE),A
	ADD	A,'A'
	LD	(F_STRDRV),A
	CALL	F_OPTIONS
;
	; HBIOS UNIT OF THE DRIVE FROM THE CBIOS DRIVE MAP
	LD	HL,($44)		; CBX: CBIOS EXTENSION DATA
	INC	HL			; DRIVE MAP ADDRESS AT +2
	INC	HL
	LD	A,(HL)
	INC	HL
	LD	H,(HL)
	LD	L,A
	DEC	HL			; THE NUMBER OF DRIVES IS JUST BEFORE THE MAP
	LD	A,(F_DRIVE)
	CP	(HL)
	JP	NC,F_ERRSEL
	INC	HL
	ADD	A,A			; 4 BYTES PER DRIVE: UNIT, SLICE, DPH
	ADD	A,A
	LD	E,A
	LD	D,0
	ADD	HL,DE
	LD	A,(HL)			; UNIT
	CP	$FF			; UNASSIGNED?
	JP	Z,F_ERRSEL
	LD	(F_UNIT),A
;
	; AN MZ-800 FLOPPY?
	LD	C,A
	LD	B,BF_DIODEVICE
	RST	08
	OR	A
	JP	NZ,F_ERRDEV
	LD	A,D
	CP	DIODEV_FD
	JP	NZ,F_ERRDEV
	LD	A,L
	CP	MZFD_IO
	JP	NZ,F_ERRDEV
	LD	A,C			; ATTRIBUTES: FORM FACTOR (BITS 4-3) AND DENSITY (1-0)
	AND	%00011011
	CP	%00001001		; 5.25" DD: 360K BY DEFAULT
	JR	NZ,F_START1
	LD	A,1
	LD	(F_O360),A
F_START1:
;
	; CONFIRM
	LD	DE,F_STRFMT1
	CALL	F_PRTSTR
	LD	DE,F_STR720
	LD	A,(F_O360)
	OR	A
	JR	Z,F_START2
	LD	DE,F_STR360
F_START2:
	CALL	F_PRTSTR
	LD	DE,F_STRMZ
	LD	A,(F_OPC)
	OR	A
	JR	Z,F_START3
	LD	DE,F_STRPC
F_START3:
	CALL	F_PRTSTR
	LD	C,1			; CONSOLE INPUT
	CALL	BDOS
	AND	$DF			; UPPER CASE
	CP	'Y'
	JP	NZ,F_ABORT
	LD	DE,F_STRCRLF
	CALL	F_PRTSTR
;
	; MEDIA
	LD	E,MID_FD720
	LD	A,80
	LD	(F_NCYL),A
	LD	A,(F_O360)
	OR	A
	JR	Z,F_START4
	LD	E,MID_FD360
	LD	A,40
	LD	(F_NCYL),A
F_START4:
	LD	A,(F_OPC)		; MZ LAYOUT: BIT 7
	OR	A
	JR	NZ,F_START5
	SET	7,E
F_START5:
	LD	A,(F_UNIT)
	LD	C,A
	LD	B,BF_DIODEFMED
	RST	08
	OR	A
	JP	NZ,F_ERRDEV
;
	; ALL TRACKS
	XOR	A
	LD	(F_CYL),A
F_LOOP:
	LD	DE,F_STRCYL		; PROGRESS
	CALL	F_PRTSTR
	LD	A,(F_CYL)
	CALL	F_PRTDEC
	XOR	A			; SIDE 0, THEN 1
	CALL	F_TRACK
	JP	NZ,F_ERRFMT
	LD	A,1
	CALL	F_TRACK
	JP	NZ,F_ERRFMT
	LD	HL,F_CYL
	INC	(HL)
	LD	A,(F_NCYL)
	CP	(HL)
	JR	NZ,F_LOOP
;
	LD	C,13			; BDOS DISK RESET
	CALL	BDOS
	LD	DE,F_STRDONE
	CALL	F_PRTSTR
	JR	F_EXIT
;
F_ERRWBW:
	LD	DE,F_STRWBW
	JR	F_ERR
F_ERRSEL:
	LD	DE,F_STRSEL
	JR	F_ERR
F_ERRDEV:
	LD	DE,F_STRDEV
	JR	F_ERR
F_ERRFMT:
	CP	-10			; ERR_READONLY
	LD	DE,F_STRWP
	JR	Z,F_ERR
	LD	DE,F_STRERR
	JR	F_ERR
F_ABORT:
	LD	DE,F_STRABORT
	JR	F_ERR
F_USAGE:
	LD	DE,F_STRUSAGE
F_ERR:
	CALL	F_PRTSTR
	LD	C,13			; BDOS DISK RESET
	CALL	BDOS
F_EXIT:
	LD	SP,(F_SAVSP)
	RET
;
; FORMAT THE TRACK OF F_CYL ON SIDE A.  Z IF OK, ELSE A = HBIOS ERROR.
;
F_TRACK:
	LD	D,A			; HEAD
	LD	E,$E5			; FILL
	LD	A,(F_CYL)
	LD	L,A
	LD	H,0
	LD	A,(F_UNIT)
	LD	C,A
	LD	B,BF_DIOFORMAT
	RST	08
	OR	A
	RET
;
; OPTIONS IN THE COMMAND TAIL: /360, /PC
;
F_OPTIONS:
	LD	HL,CMDTAIL
	LD	B,(HL)			; LENGTH
	INC	B
F_OPT1:
	INC	HL
	DEC	B
	RET	Z
	LD	A,(HL)
	CP	'/'
	JR	NZ,F_OPT1
	INC	HL
	DEC	B
	RET	Z
	LD	A,(HL)
	CP	'3'
	JR	NZ,F_OPT2
	LD	A,1
	LD	(F_O360),A
	JR	F_OPT1
F_OPT2:
	CP	'P'
	JR	NZ,F_OPT1
	LD	A,1
	LD	(F_OPC),A
	JR	F_OPT1
;
; PRINT A (0-255) IN DECIMAL
;
F_PRTDEC:
	LD	C,'0' - 1		; HUNDREDS AND TENS ONLY WHEN NEEDED
	LD	B,100
	CALL	F_DIGIT
	LD	B,10
	CALL	F_DIGIT
	ADD	A,'0'
	JR	F_PUTC
F_DIGIT:
	LD	D,'0' - 1
F_DIGIT1:
	INC	D
	SUB	B
	JR	NC,F_DIGIT1
	ADD	A,B
	PUSH	AF
	LD	A,D
	CP	'0'			; LEADING ZERO?
	JR	NZ,F_DIGIT2
	LD	A,C
	CP	'0' - 1
	JR	Z,F_DIGIT3		; YES, SKIP IT
F_DIGIT2:
	LD	C,'0'			; FROM NOW ON PRINT ZEROS
	LD	A,D
	CALL	F_PUTC
F_DIGIT3:
	POP	AF
	RET
;
F_PUTC:
	PUSH	AF
	PUSH	BC
	PUSH	DE
	LD	E,A
	LD	C,2
	CALL	BDOS
	POP	DE
	POP	BC
	POP	AF
	RET
;
F_PRTSTR:
	LD	C,9
	JP	BDOS
;
F_STRBANNER	.TEXT	"MZFMT: FLOPPY FORMAT FOR THE SHARP MZ-800 (ROMWBW)\r\n$"
F_STRUSAGE	.TEXT	"USAGE: MZFMT D: [/360] [/PC]\r\n"
		.TEXT	"Formats the floppy in D: as 720K (80 cylinders) or with /360 as 360K\r\n"
		.TEXT	"(40 cylinders, the default in 5.25\" DD drives), 9 x 512 bytes per track.\r\n"
		.TEXT	"The disk gets the MZ layout of Lamac's CP/M (IPL boot track for MZSYS),\r\n"
		.TEXT	"/PC leaves the boot track out.\r\n$"
F_STRWBW	.TEXT	"ERROR: NOT ROMWBW\r\n$"
F_STRSEL	.TEXT	"ERROR: NO SUCH DRIVE\r\n$"
F_STRDEV	.TEXT	"ERROR: NOT AN MZ-800 FLOPPY DRIVE\r\n$"
F_STRWP		.TEXT	"\r\nERROR: WRITE PROTECTED\r\n$"
F_STRERR	.TEXT	"\r\nERROR: FORMAT FAILED\r\n$"
F_STRABORT	.TEXT	"\r\nAborted.\r\n$"
F_STRFMT1	.TEXT	"Format drive "
F_STRDRV	.TEXT	"A: as $"
F_STR720	.TEXT	"720K$"
F_STR360	.TEXT	"360K$"
F_STRMZ		.TEXT	", MZ layout? ALL DATA WILL BE LOST (Y/N) $"
F_STRPC		.TEXT	", PC layout? ALL DATA WILL BE LOST (Y/N) $"
F_STRCRLF	.TEXT	"\r\n$"
F_STRCYL	.TEXT	"\rCylinder $"
F_STRDONE	.TEXT	"\r\nDone.\r\n$"
;
F_DRIVE		.DB	0
F_UNIT		.DB	0
F_O360		.DB	0		; /360
F_OPC		.DB	0		; /PC
F_NCYL		.DB	0
F_CYL		.DB	0
F_SAVSP		.DW	0
		.FILL	64, 0
F_STACK		.EQU	$
;
	.END
