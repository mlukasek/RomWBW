;======================================================================
;	ROMWBW FLOPPY BOOT (IPL) FOR THE SHARP MZ-800
;======================================================================
;
; THE OUTPUT (MZ800-IPL.BIN, 4096 BYTES) IS THE MZ-800 IPL BOOT TRACK:
; CYLINDER 0, SIDE 1, 16 SECTORS OF 256 BYTES.  SECTOR 1 IS THE IPLPRO
; HEADER, SECTORS 2-16 HOLD THE LOADER.  THE MZ-800 BUS INVERTS THE
; FLOPPY DATA AND THE ROM READS WITHOUT COMPLEMENTING, SO THE TRACK IS
; STORED COMPLEMENTED ON THE DISK.  THROUGH THE ROMWBW FLOPPY DRIVER
; (MZFD.ASM) IT IS RESERVED TRACK 3 OF A DISK IN THE MZ LAYOUT, READ AND
; WRITTEN AS IT IS IN MEMORY (MZSYS.COM WRITES IT THERE).
;
; THE MONITOR ROM READS THE HEADER TO $CF00, THEN THE LOADER (SIZE AT
; +$14) FROM LOGICAL SECTOR 1 (+$1E) TO $1200 (+$16) AND JUMPS TO $1200
; (+$18).  THE LOADER:
;
;  1. DETECTS MEMEXT (PEHU OR LUFTNER, 512K), STOPS WITHOUT IT, AND
;     MOVES TO THE COMMON BANK (AS THE UNICARD LOADER, MZCOMMON.ASM).
;  2. READS THE CP/M DIRECTORY OF THE DISK IN DRIVE 0 (720K OR 360K, THE
;     DATA AREA OF ROMWBW FD720/FD360 AND OF LAMAC'S CP/M) AND LOADS THE
;     FILE NAMED IN THE PARAMETERS (USER 0, ROMWBW.ROM) INTO BANKS $80,
;     $81, ...: MZ800_STD.ROM FILLS THE RAM DISK TOO, MZ800_STD.UPD
;     (128K) IS QUICKER TO LOAD AND LEAVES THE RAM DISK EMPTY.
;  3. STARTS HBIOS.
;
; THE PARAMETERS FOLLOW THE JUMP AT $1200 (MZSYS.COM AND MZDSK.PY SET
; THEM): "RWB", FORMAT (0 = 720K, 1 = 360K), DOUBLE STEPPING (0/1),
; FILE NAME (11 BYTES AS IN A CP/M DIRECTORY ENTRY).
;
; THE FLOPPY IS READ BY POLLING WITH INTERRUPTS DISABLED, AS IN MZFD.ASM.
;
;======================================================================
;
MX_PORT		.EQU	$E7		; MEMEXT PAGE MAPPING PORT
GDG_DMD		.EQU	$CE		; GDG DISPLAY MODE
;
FD_STS		.EQU	$D8		; R: STATUS, W: COMMAND (INVERTED)
FD_TRK		.EQU	$D9		; TRACK REGISTER (INVERTED)
FD_SEC		.EQU	$DA		; SECTOR REGISTER (INVERTED)
FD_DAT		.EQU	$DB		; DATA REGISTER (INVERTED)
FD_MOT		.EQU	$DC		; MOTOR / DRIVE SELECT
FD_SIDE		.EQU	$DD		; SIDE
FD_DENS		.EQU	$DE		; DENSITY (HD MODIFICATION)
FD_INTEN	.EQU	$DF		; DRQ INTERRUPT ENABLE (HD MODIFICATION)
;
TXT_VRAM	.EQU	$D000		; MZ-700 MODE TEXT SCREEN
TXT_ATTR	.EQU	$D800		; ... AND ITS ATTRIBUTES
TXT_COLS	.EQU	40
TXT_ROWS	.EQU	25
;
COM_BANK	.EQU	15		; BID_COM ($8F) AS 32K MEMEXT BANK
MAX_BANKS	.EQU	12		; LOAD AT MOST BANKS $80-$8B
;
MAIN_LOC	.EQU	$C000		; MAIN PART RUNS HERE (4K, COPIED WITH STACK)
DIRBUF		.EQU	$8000		; DIRECTORY (4K), IN THE COMMON BANK
;
SPT		.EQU	9		; 512 BYTE SECTORS PER TRACK
DATA_LS		.EQU	4 * SPT		; FIRST SECTOR OF THE DATA AREA (4 RESERVED TRACKS)
DIR_SECS	.EQU	8		; 128 DIRECTORY ENTRIES
TRIES		.EQU	5		; ATTEMPTS PER SECTOR
;
;======================================================================
; IPLPRO HEADER (SECTOR 1 OF THE BOOT TRACK, READ TO $CF00)
;======================================================================
;
	.ORG	$CF00
;
IPL_HDR:
	.DB	$03, "IPLPRO"		; MASTER FLAG
	.DB	"ROMWBW", $0D		; NAME (SHOWN BY THE ROM)
	.FILL	(IPL_HDR + $14) - $, 0
	.DW	LDR_END - LDR_START	; +$14 SIZE
	.DW	LDR_START		; +$16 LOAD ADDRESS
	.DW	LDR_START		; +$18 EXECUTION ADDRESS
	.FILL	4, 0
	.DW	1			; +$1E FIRST LOGICAL SECTOR (256 BYTES)
	.FILL	(IPL_HDR + 256) - $, 0
;
;======================================================================
; STUB AT $1200: PARAMETERS, KNOWN MEMORY MAP, MAIN PART TO $C000
;======================================================================
;
	.ORG	$1200
;
LDR_START:
	JR	LDR_INIT
;
PAR_SIG		.DB	"RWB"		; PARAMETERS
PAR_FMT		.DB	0		; 0 = 720K, 1 = 360K
PAR_DSTEP	.DB	0		; 1 = DOUBLE STEPPING
PAR_NAME	.DB	"ROMWBW  ROM"	; FILE (USER 0)
PAR_LEN		.EQU	$ - PAR_FMT
;
LDR_INIT:
	DI
	LD	SP,LDR_START		; TEMPORARY STACK BELOW US
	LD	A,$08			; MZ-700 MODE (TEXT SCREEN, 700 MEMORY MAP)
	OUT	(GDG_DMD),A
	OUT	($E4),A			; POWER-ON MAP: RAM AT $1000-$CFFF
	LD	HL,MAIN_IMG		; COPY THE MAIN PART
	LD	DE,MAIN_LOC
	LD	BC,MAIN_END - MAIN_LOC
	LDIR
	JP	MAIN			; AND RUN IT
;
MAIN_IMG	.EQU	$
;
;======================================================================
; MAIN PART, RUNS AT $C000-$CFFF (STACK INCLUDED)
;======================================================================
;
	.ORG	MAIN_LOC
;
MAIN:
	LD	SP,MAIN_STACK		; STACK INSIDE THE COPIED AREA
	LD	HL,PAR_FMT		; KEEP THE PARAMETERS
	LD	DE,FMT
	LD	BC,PAR_LEN
	LDIR
	CALL	CLS			; CLEAR THE SCREEN
	LD	HL,STR_TITLE
	CALL	PRTLN
	CALL	MX_SETUP		; MEMEXT, THEN RUN FROM THE COMMON BANK
;
	; FLOPPY: MOTOR ON, RECALIBRATE, READ THE DIRECTORY
	CALL	FD_START
	LD	HL,DIRBUF
	LD	DE,DATA_LS
	LD	B,DIR_SECS
MAIN1:
	PUSH	BC
	PUSH	DE
	CALL	FD_READ			; HL := HL + 512
	POP	DE
	INC	DE
	POP	BC
	DJNZ	MAIN1
;
	; THE FILE, EXTENT BY EXTENT
	XOR	A
	LD	(EXTN),A
	CALL	FINDEXT			; FIRST EXTENT THERE?
	JR	Z,MAIN2
	LD	HL,STR_NOFILE
	JP	FAIL
MAIN2:
	LD	HL,STR_LOAD
	CALL	PRT
	OUT	($E0),A			; RAM AT $0000-$0FFF
	XOR	A			; FIRST BANK
	LD	(BANK),A
	CALL	MX_LOWER
	LD	HL,0
	LD	(DEST),HL
MAIN3:
	CALL	FINDEXT			; HL := ENTRY OF EXTENT EXTN
	JR	NZ,MAIN9		; NO MORE
	LD	DE,16			; BLOCK POINTERS
	ADD	HL,DE
	LD	B,8			; 720K: 8 WORDS
	LD	A,(FMT)
	OR	A
	JR	Z,MAIN4
	LD	B,16			; 360K: 16 BYTES
MAIN4:
	PUSH	BC
	LD	E,(HL)			; DE := BLOCK
	INC	HL
	LD	D,0
	LD	A,(FMT)
	OR	A
	JR	NZ,MAIN5
	LD	D,(HL)
	INC	HL
MAIN5:
	PUSH	HL
	LD	A,D			; NO BLOCK: END OF THE ENTRY
	OR	E
	CALL	NZ,LOADBLK		; CY IF THE BANKS ARE FULL
	POP	HL
	POP	BC
	JR	C,MAIN9
	DJNZ	MAIN4
	LD	HL,EXTN			; NEXT EXTENT
	INC	(HL)
	JR	MAIN3
;
MAIN9:
	LD	A,'.'			; LAST BANK
	CALL	PUTC
	XOR	A			; MOTOR OFF
	OUT	(FD_MOT),A
	JP	HB_GO			; START HBIOS
;
;----------------------------------------------------------------------
; FIND THE DIRECTORY ENTRY OF EXTENT EXTN OF THE FILE (USER 0).
; Z AND HL = ENTRY IF FOUND.  AN ENTRY HOLDS 1 (720K) OR 2 (360K)
; LOGICAL EXTENTS, ITS NUMBER IS (S2 * 32 + EX) >> EXM.
;----------------------------------------------------------------------
;
FINDEXT:
	LD	HL,DIRBUF
	LD	B,DIR_SECS * 16		; ENTRIES
FINDEXT1:
	PUSH	BC
	PUSH	HL
	LD	A,(HL)			; USER 0?
	OR	A
	JR	NZ,FINDEXT3
	INC	HL			; NAME, ATTRIBUTE BITS MASKED
	LD	DE,NAME
	LD	B,11
FINDEXT2:
	LD	A,(DE)
	LD	C,A
	LD	A,(HL)
	AND	$7F
	CP	C
	JR	NZ,FINDEXT3
	INC	HL
	INC	DE
	DJNZ	FINDEXT2
	LD	C,(HL)			; C := EX
	INC	HL
	INC	HL
	LD	A,(HL)			; S2 * 32 + EX
	RRCA
	RRCA
	RRCA
	AND	$E0
	ADD	A,C
	LD	C,A
	LD	A,(FMT)			; 360K: EXM = 1
	OR	A
	JR	Z,FINDEXT2A
	SRL	C
FINDEXT2A:
	LD	A,(EXTN)
	CP	C
	JR	Z,FINDEXT4		; FOUND
FINDEXT3:
	POP	HL			; NEXT ENTRY
	LD	DE,32
	ADD	HL,DE
	POP	BC
	DJNZ	FINDEXT1
	OR	$FF			; NOT FOUND
	RET
FINDEXT4:
	POP	HL			; ENTRY
	POP	BC
	XOR	A
	RET
;
;----------------------------------------------------------------------
; LOAD BLOCK DE (2K = 4 SECTORS) TO DEST, SWITCHING TO THE NEXT BANK
; WHEN THE CURRENT ONE IS FULL.  CY IF ALL BANKS ARE FULL.
;----------------------------------------------------------------------
;
LOADBLK:
	LD	HL,(DEST)		; BANK FULL?
	BIT	7,H
	JR	Z,LOADBLK1
	PUSH	DE
	LD	A,'.'			; PROGRESS
	CALL	PUTC
	LD	HL,BANK			; NEXT BANK
	INC	(HL)
	LD	A,(HL)
	CP	MAX_BANKS
	SCF
	JR	Z,LOADBLK9		; NO MORE BANKS
	CALL	MX_LOWER
	LD	HL,0
	LD	(DEST),HL
	POP	DE
LOADBLK1:
	EX	DE,HL			; LOGICAL SECTOR := DATA_LS + 4 * BLOCK
	ADD	HL,HL
	ADD	HL,HL
	LD	DE,DATA_LS
	ADD	HL,DE
	EX	DE,HL
	LD	HL,(DEST)
	LD	B,4
LOADBLK2:
	PUSH	BC
	PUSH	DE
	CALL	FD_READ			; HL := HL + 512
	POP	DE
	INC	DE
	POP	BC
	DJNZ	LOADBLK2
	LD	(DEST),HL
	OR	A			; NC: OK
	RET
LOADBLK9:
	POP	DE
	RET
;
;----------------------------------------------------------------------
; FLOPPY: MOTOR ON, DRIVE 0, RECALIBRATE
;----------------------------------------------------------------------
;
FD_START:
	XOR	A
	OUT	(FD_INTEN),A		; NO DRQ INTERRUPT, DOUBLE DENSITY
	OUT	(FD_DENS),A
	LD	A,$84			; MOTOR ON, DRIVE 0
	OUT	(FD_MOT),A
	LD	DE,500			; SPIN UP
	CALL	DELAY
	LD	A,$D0			; FORCE INTERRUPT
	CALL	FD_CMD
	; FALL THROUGH
;
FD_RESTORE:
	LD	A,$08			; RESTORE, HEAD LOAD, 6 MS STEPS
	CALL	FD_CMD
	CALL	FD_WAIT			; A := STATUS
	AND	$04			; TRACK 0?
	JR	NZ,FD_RESTORE1
	LD	HL,STR_NOTRK0
	JP	FAIL
FD_RESTORE1:
	XOR	A
	LD	(CURCYL),A
	RET
;
;----------------------------------------------------------------------
; READ LOGICAL SECTOR DE (512 BYTES, 9 PER TRACK, TRACK = CYLINDER * 2
; + SIDE) TO HL.  RETURNS HL := HL + 512, STOPS ON AN ERROR.
;----------------------------------------------------------------------
;
FD_READ:
	LD	(BUF),HL
	EX	DE,HL			; TRACK := SECTOR / 9
	LD	C,0
FD_READ1:
	LD	DE,SPT
	OR	A
	SBC	HL,DE
	JR	C,FD_READ2
	INC	C
	JR	FD_READ1
FD_READ2:
	ADD	HL,DE			; SECTOR (0-8)
	LD	A,L
	INC	A
	LD	(SECT),A		; SECTOR NUMBER ON THE DISK (1-9)
	LD	A,C
	AND	1
	LD	(HEAD),A
	LD	A,C
	SRL	A
	LD	(CYL),A
	LD	B,TRIES
FD_READ3:
	PUSH	BC
	LD	A,(CYL)			; PHYSICAL CYLINDER
	LD	C,A
	LD	A,(DSTEP)
	OR	A
	JR	Z,FD_READ4
	SLA	C
FD_READ4:
	CALL	FD_SEEK
	LD	A,(CYL)			; TRACK REGISTER := CYLINDER IN THE IDS
	CPL
	OUT	(FD_TRK),A
	LD	A,(HEAD)
	OUT	(FD_SIDE),A
	LD	A,(SECT)
	CPL
	OUT	(FD_SEC),A
	LD	A,(HEAD)		; READ SECTOR, SIDE COMPARE
	RLCA
	RLCA
	RLCA
	OR	$82
	CALL	FD_CMD
	LD	HL,(BUF)
	CALL	FD_XRD			; Z IF OK, A := STATUS
	POP	BC
	RET	Z			; HL := BUFFER + 512
	LD	(STATUS),A
	LD	A,B			; FROM THE THIRD ATTEMPT ON, RECALIBRATE
	CP	TRIES
	JR	Z,FD_READ5
	PUSH	BC
	CALL	FD_RESTORE
	POP	BC
FD_READ5:
	DJNZ	FD_READ3
	LD	HL,STR_DISKERR		; GIVE UP
	CALL	PRT
	LD	A,(CYL)
	CALL	PRTHEX
	LD	A,'/'
	CALL	PUTC
	LD	A,(HEAD)
	CALL	PRTHEX
	LD	A,'/'
	CALL	PUTC
	LD	A,(SECT)
	CALL	PRTHEX
	LD	A,' '
	CALL	PUTC
	LD	A,(STATUS)
	CALL	PRTHEX
	LD	HL,STR_EMPTY
	JP	FAIL
;
; SEEK TO PHYSICAL CYLINDER C
;
FD_SEEK:
	LD	A,(CURCYL)
	CP	C
	RET	Z
	CPL				; TRACK REGISTER := WHERE THE HEAD IS
	OUT	(FD_TRK),A
	LD	A,C			; DATA REGISTER := TARGET
	CPL
	OUT	(FD_DAT),A
	LD	A,$18			; SEEK, HEAD LOAD, 6 MS STEPS
	CALL	FD_CMD
	CALL	FD_WAIT
	LD	A,C
	LD	(CURCYL),A
	LD	DE,15			; HEAD SETTLE
	JP	DELAY
;
; READ THE SECTOR DATA OF THE COMMAND JUST ISSUED (512 BYTES TO HL).
; Z IF OK, ELSE A := ERROR BITS OF THE STATUS.
;
FD_XRD:
	LD	DE,512
	LD	BC,0			; TIMEOUT FOR THE FIRST BYTE, 3 X 65536 POLLS
	LD	A,3
	LD	(TOHI),A
FD_XRD1:
	IN	A,(FD_STS)		; STATUS, INVERTED: ACTIVE BITS READ 0
	BIT	1,A			; DRQ?
	JR	Z,FD_XRD3
	RRCA				; CY := NOT BUSY
	JR	C,FD_XRD8		; ENDED WITHOUT DATA
	DEC	BC
	LD	A,B
	OR	C
	JR	NZ,FD_XRD1
	LD	A,(TOHI)
	DEC	A
	LD	(TOHI),A
	JR	NZ,FD_XRD1
	LD	A,$D0			; TIMEOUT: STOP
	CALL	FD_CMD
	LD	A,$10			; AS RECORD NOT FOUND
	OR	A
	RET
FD_XRD3:
	IN	A,(FD_DAT)		; 87 T-STATES PER BYTE
	CPL
	LD	(HL),A
	INC	HL
	DEC	DE
	LD	A,D
	OR	E
	JR	Z,FD_XRD6		; ALL BYTES
FD_XRD4:
	IN	A,(FD_STS)
	RRCA				; CY := NOT BUSY
	JR	C,FD_XRD8		; ENDED EARLY
	RRCA				; CY := NO DRQ
	JR	NC,FD_XRD3
	JR	FD_XRD4
FD_XRD6:
	CALL	FD_WAIT			; END OF THE COMMAND (CRC)
	JR	FD_XRD9
FD_XRD8:
	IN	A,(FD_STS)
	CPL
FD_XRD9:
	AND	$1C			; RECORD NOT FOUND, CRC, LOST DATA
	RET	NZ
	LD	A,D			; ALL BYTES?
	OR	E
	RET	Z
	LD	A,$10			; ENDED EARLY
	RET
;
; COMMAND A (TRUE VALUE) TO THE CONTROLLER, WAIT UNTIL THE STATUS IS VALID
;
FD_CMD:
	CPL
	OUT	(FD_STS),A
	LD	A,40			; ABOUT 150 US
FD_CMD1:
	DEC	A
	JR	NZ,FD_CMD1
	RET
;
; WAIT UNTIL NOT BUSY (ABOUT 2 S AT MOST), A := STATUS (TRUE VALUE)
;
FD_WAIT:
	PUSH	BC
	LD	BC,0
	LD	A,3
	LD	(TOHI),A
FD_WAIT1:
	IN	A,(FD_STS)
	RRCA				; CY := NOT BUSY
	JR	C,FD_WAIT2
	DEC	BC
	LD	A,B
	OR	C
	JR	NZ,FD_WAIT1
	LD	A,(TOHI)
	DEC	A
	LD	(TOHI),A
	JR	NZ,FD_WAIT1
	LD	A,$D0			; TIMEOUT: STOP
	CALL	FD_CMD
FD_WAIT2:
	IN	A,(FD_STS)
	CPL
	POP	BC
	RET
;
; DELAY DE MILLISECONDS (ROUGHLY, 3.55 MHZ)
;
DELAY:
	LD	B,0
DELAY1:
	DJNZ	DELAY1			; 256 X 13 T
	DEC	DE
	LD	A,D
	OR	E
	JR	NZ,DELAY
	RET
;
#INCLUDE "mzcommon.asm"
;
;----------------------------------------------------------------------
; STRINGS AND DATA
;----------------------------------------------------------------------
;
STR_TITLE	.DB	"ROMWBW FLOPPY LOADER FOR SHARP MZ-800", 0
STR_NOFILE	.DB	"ERROR: IMAGE FILE NOT ON THE DISK", 0
STR_NOTRK0	.DB	"ERROR: NO TRACK 0", 0
STR_DISKERR	.DB	"DISK ERROR C/H/S ST ", 0
STR_LOAD	.DB	"LOADING ", 0
STR_EMPTY	.DB	0
;
FMT		.DB	0		; PARAMETERS (COPY)
DSTEP		.DB	0
NAME		.FILL	11, ' '
;
EXTN		.DB	0		; EXTENT BEING LOADED
BANK		.DB	0		; CURRENT BANK
DEST		.DW	0		; LOAD ADDRESS IN THE BANK
BUF		.DW	0		; SECTOR BUFFER
CYL		.DB	0		; SECTOR: CYLINDER, HEAD, NUMBER ON THE DISK
HEAD		.DB	0
SECT		.DB	0
CURCYL		.DB	0		; PHYSICAL CYLINDER UNDER THE HEAD
STATUS		.DB	0		; STATUS OF THE LAST FAILED ATTEMPT
TOHI		.DB	0		; TIMEOUT, HIGH COUNTER
;
MAIN_END	.EQU	$
;
#IF (MAIN_END > (MAIN_LOC + $0F00))	; TASM: NO OPERATOR PRECEDENCE
	.ECHO	"*** ERROR: LOADER MAIN PART TOO BIG!!!\n"
	!!!
#ENDIF
;
MAIN_STACK	.EQU	MAIN_LOC + $1000	; STACK AT THE TOP OF $C000-$CFFF
;
	.ORG	MAIN_IMG + (MAIN_END - MAIN_LOC)
LDR_END		.EQU	$
;
#IF ((LDR_END - LDR_START) > (15 * 256))
	.ECHO	"*** ERROR: LOADER DOES NOT FIT THE BOOT TRACK!!!\n"
	!!!
#ENDIF
;
	.FILL	(LDR_START + (15 * 256)) - $, 0	; REST OF THE BOOT TRACK
;
	.END
