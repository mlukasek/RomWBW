;======================================================================
;	UC: FILES OF THE UNICARD SD CARD FROM CP/M (SHARP MZ-800, ROMWBW)
;======================================================================
;
; USAGE:	UC DIR [PATH]		LIST A DIRECTORY OF THE SD CARD
;		UC CD PATH		CHANGE THE CURRENT SD DIRECTORY
;		UC GET SDFILE [D:FILE]	COPY A FILE FROM THE SD CARD
;		UC PUT D:FILE [SDFILE]	COPY A FILE TO THE SD CARD
;		UC MOUNT IMAGE		IMAGE FILE FOR THE UNICARD RAM DISK
;					(RESTART AFTERWARDS)
;
; THE UNICARD REPOSITORY (PORTS $50 COMMAND/STATUS, $51 DATA) GIVES
; ACCESS TO THE FAT FILE SYSTEM OF THE SD CARD.  A COMMAND IS WRITTEN TO
; $50, ITS PARAMETERS TO $51 (STRINGS END WITH $0D).  THE STATUS IS READ
; FROM $50 AFTER COMMAND $03 (BYTE 0: BIT 0 BUSY, 1 OUTPUT, 2 READDIR,
; 3 READ_FILE, 4 WRITE_FILE, 5 EOF, 7 ERROR).  AN OPEN FILE IS READ AND
; WRITTEN BYTE BY BYTE ON $51, THE CARD HOLDS THE CPU IN WAIT, SO
; INIR/OTIR WORK.  NO SEEK (BROKEN IN FIRMWARE 0.26).
;
; GET STORES THE EXACT SIZE ROUNDED UP TO 128 BYTE RECORDS (THE LAST ONE
; FILLED WITH ^Z), PUT STORES WHOLE RECORDS.
;
;======================================================================
;
BDOS		.EQU	$0005
CMDTAIL		.EQU	$0080
;
UC_CMD		.EQU	$50		; COMMAND / STATUS
UC_DATA		.EQU	$51		; DATA
;
C_STSR		.EQU	$03		; STATUS POINTER TO THE START
C_ASCII		.EQU	$01		; I/O TRANSLATOR: ASCII
C_STORNO	.EQU	$04		; CANCEL THE CURRENT COMMAND
C_MOUNT		.EQU	$10		; IMAGE FOR A DRIVE (4 = RAM DISK)
C_CHDIR		.EQU	$21		; CHANGE DIRECTORY
C_GETCWD	.EQU	$22		; CURRENT DIRECTORY
C_FILELIST	.EQU	$42		; DIRECTORY AS TEXT
C_OPEN		.EQU	$50		; OPEN FILE (MODE, NAME)
C_CLOSE		.EQU	$54		; CLOSE FILE
C_SIZE		.EQU	$56		; FILE SIZE (DWORD)
;
S_READDIR	.EQU	2		; STATUS BITS
S_READ		.EQU	3
S_WRITE		.EQU	4
S_ERROR		.EQU	7
;
	.ORG	$0100
;
START:
	LD	(SAVSP),SP
	LD	SP,STACK
	CALL	TOKENS			; SPLIT THE COMMAND TAIL
	LD	A,(NTOK)
	OR	A
	JP	Z,USAGE
	; UNICARD THERE?
	LD	A,C_STORNO
	OUT	(UC_CMD),A
	CALL	STATUS
	CP	$FF			; NO CARD READS $FF
	JP	Z,ERRCARD
	LD	A,C_ASCII		; NAMES WITHOUT SHARP ASCII TRANSLATION
	OUT	(UC_CMD),A
	; SUBCOMMAND
	LD	HL,TOK1
	LD	DE,STRDIR
	CALL	STRCMP
	JP	Z,DODIR
	LD	DE,STRCD
	CALL	STRCMP
	JP	Z,DOCD
	LD	DE,STRGET
	CALL	STRCMP
	JP	Z,DOGET
	LD	DE,STRPUT
	CALL	STRCMP
	JP	Z,DOPUT
	LD	DE,STRMOUNT
	CALL	STRCMP
	JP	Z,DOMOUNT
	JP	USAGE
;
;----------------------------------------------------------------------
; UC DIR [PATH]
;----------------------------------------------------------------------
;
DODIR:
	LD	A,C_GETCWD		; SHOW THE CURRENT DIRECTORY FIRST
	OUT	(UC_CMD),A
	CALL	RDSTRPRT
	CALL	CRLF
	LD	A,(TOK2)		; NO PATH: THE CURRENT DIRECTORY (AN EMPTY ONE IS THE ROOT)
	OR	A
	JR	NZ,DODIR0
	LD	A,'.'
	LD	(TOK2),A
	XOR	A
	LD	(TOK2 + 1),A
DODIR0:
	LD	A,C_FILELIST
	OUT	(UC_CMD),A
	LD	HL,TOK2			; PATH
	CALL	SENDSTR
	CALL	STATUS
	BIT	S_ERROR,A
	JP	NZ,ERRSD
DODIR1:
	CALL	STATUS			; MORE ENTRIES?
	BIT	S_READDIR,A
	JP	Z,EXIT
	CALL	RDSTR			; NAME (DIRECTORIES END WITH /)
	LD	HL,STRBUF
	CALL	PRTSTR0
	LD	A,(STRLEN)		; PAD TO 24 COLUMNS
	LD	B,A
	LD	A,24
	SUB	B
	JR	C,DODIR2
	JR	Z,DODIR2
	LD	B,A
DODIR1A:
	LD	A,' '
	CALL	PUTC
	DJNZ	DODIR1A
DODIR2:
	CALL	RDSTR			; SIZE
	LD	HL,STRBUF
	CALL	PRTSTR0
	CALL	CRLF
	JR	DODIR1
;
;----------------------------------------------------------------------
; UC CD PATH
;----------------------------------------------------------------------
;
DOCD:
	LD	A,(NTOK)
	CP	2
	JP	C,USAGE
	LD	A,C_CHDIR
	OUT	(UC_CMD),A
	LD	HL,TOK2
	CALL	SENDSTR
	CALL	STATUS
	BIT	S_ERROR,A
	JP	NZ,ERRSD
	XOR	A			; SHOW IT (THE NEW CURRENT DIRECTORY)
	LD	(TOK2),A
	JP	DODIR
;
;----------------------------------------------------------------------
; UC MOUNT IMAGE
;----------------------------------------------------------------------
;
DOMOUNT:
	LD	A,(NTOK)
	CP	2
	JP	C,USAGE
	LD	A,C_MOUNT
	OUT	(UC_CMD),A
	LD	A,4			; THE RAM DISK
	OUT	(UC_DATA),A
	LD	HL,TOK2
	CALL	SENDSTR
	CALL	STATUS
	BIT	S_ERROR,A
	JP	NZ,ERRSD
	LD	DE,STRMOUNTED
	CALL	PRTSTR
	JP	EXIT
;
;----------------------------------------------------------------------
; UC GET SDFILE [D:FILE]
;----------------------------------------------------------------------
;
DOGET:
	LD	A,(NTOK)
	CP	2
	JP	C,USAGE
	; CP/M FILE: THE THIRD ARGUMENT OR THE NAME OF THE SD FILE
	LD	HL,TOK3
	LD	A,(NTOK)
	CP	3
	JR	NC,DOGET1
	LD	HL,TOK2			; THE NAME AFTER THE LAST / OF THE SD PATH
	LD	D,H
	LD	E,L
DOGET0:
	LD	A,(HL)
	INC	HL
	OR	A
	JR	Z,DOGET0B
	CP	'/'
	JR	NZ,DOGET0
	LD	D,H
	LD	E,L
	JR	DOGET0
DOGET0B:
	EX	DE,HL
DOGET1:
	CALL	MKFCB			; FCB FROM THE NAME AT HL
	JP	NZ,ERRNAME
	; OPEN ON THE CARD
	LD	A,C_OPEN
	OUT	(UC_CMD),A
	LD	A,$01			; READ
	OUT	(UC_DATA),A
	LD	HL,TOK2
	CALL	SENDSTR
	CALL	STATUS
	AND	$88			; ERROR, READ_FILE
	CP	$08
	JP	NZ,ERRSD
	LD	A,C_SIZE		; SIZE (DWORD, LOW BYTE FIRST)
	OUT	(UC_CMD),A
	LD	HL,SIZE
	LD	BC,4 * 256 + UC_DATA
	INIR
	; CP/M FILE
	LD	C,19			; DELETE AN OLD ONE
	LD	DE,FCB
	CALL	BDOS
	LD	C,22			; MAKE
	LD	DE,FCB
	CALL	BDOS
	INC	A
	JP	Z,ERRFULL
	LD	C,26			; DMA
	LD	DE,RECBUF
	CALL	BDOS
DOGET2:
	LD	HL,(SIZE)		; ANYTHING LEFT?
	LD	A,H
	OR	L
	LD	HL,(SIZE + 2)
	OR	H
	OR	L
	JR	Z,DOGET9
	; B := MIN(128, SIZE)
	LD	B,128
	LD	HL,(SIZE + 2)
	LD	A,H
	OR	L
	JR	NZ,DOGET3
	LD	HL,(SIZE)
	LD	A,H
	OR	A
	JR	NZ,DOGET3
	LD	A,L
	CP	128
	JR	NC,DOGET3
	LD	B,L
DOGET3:
	LD	A,B			; SIZE := SIZE - B
	LD	(COUNT),A
	LD	HL,(SIZE)
	LD	E,B
	LD	D,0
	OR	A
	SBC	HL,DE
	LD	(SIZE),HL
	JR	NC,DOGET4
	LD	HL,(SIZE + 2)
	DEC	HL
	LD	(SIZE + 2),HL
DOGET4:
	LD	HL,RECBUF		; FILL WITH ^Z, THEN READ
	LD	D,H
	LD	E,L
	INC	DE
	LD	(HL),$1A
	LD	BC,127
	LDIR
	LD	HL,RECBUF
	LD	A,(COUNT)
	LD	B,A
	LD	C,UC_DATA
	INIR
	LD	C,21			; WRITE THE RECORD
	LD	DE,FCB
	CALL	BDOS
	OR	A
	JR	NZ,DOGET8
	LD	A,'.'			; PROGRESS PER 8 RECORDS
	LD	HL,RECNT
	INC	(HL)
	LD	A,(HL)
	AND	7
	LD	A,'.'
	CALL	Z,PUTC
	JR	DOGET2
DOGET8:
	CALL	SDCLOSE
	JP	ERRFULL
DOGET9:
	CALL	SDCLOSE
	LD	C,16			; CLOSE THE CP/M FILE
	LD	DE,FCB
	CALL	BDOS
	LD	DE,STRDONE
	CALL	PRTSTR
	JP	EXIT
;
;----------------------------------------------------------------------
; UC PUT D:FILE [SDFILE]
;----------------------------------------------------------------------
;
DOPUT:
	LD	A,(NTOK)
	CP	2
	JP	C,USAGE
	LD	HL,TOK2
	CALL	MKFCB
	JP	NZ,ERRNAME
	LD	C,15			; OPEN THE CP/M FILE
	LD	DE,FCB
	CALL	BDOS
	INC	A
	JP	Z,ERRNOFILE
	; SD NAME: THE THIRD ARGUMENT OR NAME.EXT OF THE FCB
	LD	A,(NTOK)
	CP	3
	JR	NC,DOPUT1
	CALL	FCBNAME			; TOK3 := NAME.EXT
DOPUT1:
	LD	A,C_OPEN
	OUT	(UC_CMD),A
	LD	A,$0A			; WRITE, CREATE ALWAYS
	OUT	(UC_DATA),A
	LD	HL,TOK3
	CALL	SENDSTR
	CALL	STATUS
	AND	$90			; ERROR, WRITE_FILE
	CP	$10
	JP	NZ,ERRSD
	LD	C,26			; DMA
	LD	DE,RECBUF
	CALL	BDOS
DOPUT2:
	LD	C,20			; READ A RECORD
	LD	DE,FCB
	CALL	BDOS
	OR	A
	JR	NZ,DOPUT9		; END OF THE FILE
	LD	HL,RECBUF
	LD	BC,128 * 256 + UC_DATA
	OTIR
	LD	HL,RECNT		; PROGRESS PER 8 RECORDS
	INC	(HL)
	LD	A,(HL)
	AND	7
	LD	A,'.'
	CALL	Z,PUTC
	JR	DOPUT2
DOPUT9:
	CALL	SDCLOSE
	CALL	STATUS
	BIT	S_ERROR,A
	JP	NZ,ERRSD
	LD	DE,STRDONE
	CALL	PRTSTR
	JP	EXIT
;
;----------------------------------------------------------------------
; HELPERS
;----------------------------------------------------------------------
;
; STATUS BYTE 0 IN A
;
STATUS:
	LD	A,C_STSR
	OUT	(UC_CMD),A
	IN	A,(UC_CMD)
	RET
;
SDCLOSE:
	LD	A,C_CLOSE
	OUT	(UC_CMD),A
	RET
;
; STRING HL (ZERO TERMINATED) AS A PARAMETER, THEN $0D
;
SENDSTR:
	LD	A,(HL)
	INC	HL
	OR	A
	JR	Z,SENDSTR1
	OUT	(UC_DATA),A
	JR	SENDSTR
SENDSTR1:
	LD	A,$0D
	OUT	(UC_DATA),A
	RET
;
; READ A STRING UP TO $0D FROM THE DATA PORT TO STRBUF (ZERO TERMINATED,
; LENGTH IN STRLEN, AT MOST 63 CHARACTERS KEPT)
;
RDSTR:
	LD	HL,STRBUF
	LD	B,0
RDSTR1:
	IN	A,(UC_DATA)
	CP	$0D
	JR	Z,RDSTR2
	LD	C,A
	LD	A,B
	CP	63
	JR	NC,RDSTR1
	LD	(HL),C
	INC	HL
	INC	B
	JR	RDSTR1
RDSTR2:
	LD	(HL),0
	LD	A,B
	LD	(STRLEN),A
	RET
;
; COMMAND OUTPUT AS A STRING TO THE CONSOLE (WHILE THERE IS OUTPUT)
;
RDSTRPRT:
	CALL	STATUS
	BIT	1,A			; OUTPUT?
	RET	Z
	IN	A,(UC_DATA)
	CP	$0D
	RET	Z
	OR	A
	RET	Z
	CALL	PUTC
	JR	RDSTRPRT
;
; SPLIT THE COMMAND TAIL INTO TOK1..TOK3 (ZERO TERMINATED, UPPER CASE BY
; THE CCP), NTOK := NUMBER OF TOKENS
;
TOKENS:
	XOR	A
	LD	(NTOK),A
	LD	(TOK1),A
	LD	(TOK2),A
	LD	(TOK3),A
	LD	HL,CMDTAIL
	LD	B,(HL)			; LENGTH
	INC	HL
	LD	DE,TOK1
	CALL	TOKEN
	RET	Z
	LD	DE,TOK2
	CALL	TOKEN
	RET	Z
	LD	DE,TOK3
	; FALL THROUGH
;
; NEXT TOKEN OF THE TAIL (HL, B CHARACTERS LEFT) TO DE.  Z IF NONE.
;
TOKEN:
	LD	A,B			; SKIP SPACES
	OR	A
	RET	Z
	LD	A,(HL)
	CP	' '
	JR	NZ,TOKEN1
	INC	HL
	DEC	B
	JR	TOKEN
TOKEN1:
	PUSH	HL
	LD	HL,NTOK
	INC	(HL)
	POP	HL
	LD	C,63			; AT MOST 63 CHARACTERS
TOKEN2:
	LD	A,(HL)
	CP	' '
	JR	Z,TOKEN3
	LD	(DE),A
	INC	DE
	INC	HL
	DEC	C
	JR	Z,TOKEN3
	DJNZ	TOKEN2
TOKEN3:
	XOR	A
	LD	(DE),A
	INC	A			; NZ
	RET
;
; COMPARE STRINGS HL, DE (ZERO TERMINATED).  Z IF EQUAL.  HL KEPT.
;
STRCMP:
	PUSH	HL
STRCMP1:
	LD	A,(DE)
	CP	(HL)
	JR	NZ,STRCMP2
	OR	A
	JR	Z,STRCMP2
	INC	HL
	INC	DE
	JR	STRCMP1
STRCMP2:
	POP	HL
	RET
;
; FCB FROM "D:NAME.EXT" AT HL.  NZ IF THE NAME IS BAD.
;
MKFCB:
	PUSH	HL
	LD	HL,FCB			; CLEAR THE FCB, BLANK NAME
	LD	B,36
MKFCB0:
	LD	(HL),0
	INC	HL
	DJNZ	MKFCB0
	LD	HL,FCB + 1
	LD	B,11
MKFCB0A:
	LD	(HL),' '
	INC	HL
	DJNZ	MKFCB0A
	POP	HL
	INC	HL			; DRIVE?
	LD	A,(HL)
	DEC	HL
	CP	':'
	JR	NZ,MKFCB1
	LD	A,(HL)
	SUB	'A' - 1
	LD	(FCB),A
	INC	HL
	INC	HL
MKFCB1:
	LD	DE,FCB + 1		; NAME, UP TO 8
	LD	B,8
	CALL	MKFCBPART
	LD	A,(HL)
	CP	'.'
	JR	NZ,MKFCB2
	INC	HL
	LD	DE,FCB + 9		; EXTENSION, UP TO 3
	LD	B,3
	CALL	MKFCBPART
MKFCB2:
	LD	A,(FCB + 1)		; A NAME?
	CP	' '
	JR	Z,MKFCB3
	XOR	A			; Z: OK
	RET
MKFCB3:
	OR	$FF			; NZ: NO NAME
	RET
;
MKFCBPART:
	LD	A,(HL)
	OR	A
	RET	Z
	CP	'.'
	RET	Z
	CP	'a'			; UPPER CASE
	JR	C,MKFCBPART1
	CP	'z' + 1
	JR	NC,MKFCBPART1
	SUB	$20
MKFCBPART1:
	INC	HL
	DEC	B
	INC	B
	JR	Z,MKFCBPART		; FULL: SKIP THE REST
	LD	(DE),A
	INC	DE
	DEC	B
	JR	MKFCBPART
;
; TOK3 := "NAME.EXT" FROM THE FCB
;
FCBNAME:
	LD	HL,FCB + 1
	LD	DE,TOK3
	LD	B,8
FCBNAME1:
	LD	A,(HL)
	CP	' '
	JR	Z,FCBNAME2
	LD	(DE),A
	INC	DE
FCBNAME2:
	INC	HL
	DJNZ	FCBNAME1
	LD	A,(FCB + 9)
	CP	' '
	JR	Z,FCBNAME4
	LD	A,'.'
	LD	(DE),A
	INC	DE
	LD	B,3
FCBNAME3:
	LD	A,(HL)
	CP	' '
	JR	Z,FCBNAME3A
	LD	(DE),A
	INC	DE
FCBNAME3A:
	INC	HL
	DJNZ	FCBNAME3
FCBNAME4:
	XOR	A
	LD	(DE),A
	RET
;
; CONSOLE
;
PUTC:
	PUSH	AF
	PUSH	BC
	PUSH	DE
	PUSH	HL
	LD	E,A
	LD	C,2
	CALL	BDOS
	POP	HL
	POP	DE
	POP	BC
	POP	AF
	RET
;
CRLF:
	LD	A,13
	CALL	PUTC
	LD	A,10
	JP	PUTC
;
PRTSTR0:				; ZERO TERMINATED STRING HL
	LD	A,(HL)
	OR	A
	RET	Z
	CALL	PUTC
	INC	HL
	JR	PRTSTR0
;
PRTSTR:					; $ TERMINATED STRING DE
	LD	C,9
	JP	BDOS
;
ERRCARD:
	LD	DE,STRERRCARD
	JR	ERR
ERRSD:
	CALL	SDCLOSE
	LD	DE,STRERRSD
	JR	ERR
ERRNAME:
	LD	DE,STRERRNAME
	JR	ERR
ERRNOFILE:
	LD	DE,STRERRNOFILE
	JR	ERR
ERRFULL:
	LD	DE,STRERRFULL
	JR	ERR
USAGE:
	LD	DE,STRUSAGE
ERR:
	CALL	PRTSTR
EXIT:
	LD	SP,(SAVSP)
	RET
;
STRDIR		.DB	"DIR", 0
STRCD		.DB	"CD", 0
STRGET		.DB	"GET", 0
STRPUT		.DB	"PUT", 0
STRMOUNT	.DB	"MOUNT", 0
;
STRUSAGE	.TEXT	"UC: UNICARD SD CARD FILES (SHARP MZ-800, ROMWBW)\r\n"
		.TEXT	"  UC DIR [PATH]            list a directory of the SD card\r\n"
		.TEXT	"  UC CD PATH               change the current SD directory\r\n"
		.TEXT	"  UC GET SDFILE [D:FILE]   copy a file from the SD card\r\n"
		.TEXT	"  UC PUT D:FILE [SDFILE]   copy a file to the SD card\r\n"
		.TEXT	"  UC MOUNT IMAGE           image file of the Unicard RAM disk (restart then)\r\n$"
STRERRCARD	.TEXT	"ERROR: NO UNICARD\r\n$"
STRERRSD	.TEXT	"\r\nERROR: SD CARD (NO SUCH FILE OR DIRECTORY?)\r\n$"
STRERRNAME	.TEXT	"ERROR: BAD CP/M FILE NAME\r\n$"
STRERRNOFILE	.TEXT	"ERROR: NO SUCH CP/M FILE\r\n$"
STRERRFULL	.TEXT	"\r\nERROR: CP/M DISK OR DIRECTORY FULL\r\n$"
STRDONE		.TEXT	" done.\r\n$"
STRMOUNTED	.TEXT	"Mounted. Restart the system to use the new RAM disk image.\r\n$"
;
SAVSP		.DW	0
NTOK		.DB	0
STRLEN		.DB	0
COUNT		.DB	0
RECNT		.DB	0
SIZE		.DW	0, 0
TOK1		.FILL	64, 0
TOK2		.FILL	64, 0
TOK3		.FILL	64, 0
STRBUF		.FILL	64, 0
FCB		.FILL	36, 0
RECBUF		.FILL	128, 0
		.FILL	64, 0
STACK		.EQU	$
;
	.END
