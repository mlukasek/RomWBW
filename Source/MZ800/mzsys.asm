;======================================================================
;	MZSYS: MAKE A FLOPPY BOOTABLE ON THE SHARP MZ-800 (ROMWBW)
;======================================================================
;
; USAGE:  MZSYS D: [FILENAME.EXT]
;
; WRITES THE ROMWBW IPL LOADER (MZIPL.ASM, INCLUDED HERE) TO THE MZ-800
; BOOT TRACK OF THE DISK IN DRIVE D:.  AT POWER ON THE MZ-800 ROM STARTS
; IT FROM DRIVE 0 AND IT LOADS FILENAME.EXT (DEFAULT ROMWBW.ROM, USER 0)
; FROM THE DISK AS THE ROMWBW IMAGE.  THE DISK NEEDS ALSO:
;   - THE IMAGE: PIP D:ROMWBW.ROM=...MZ800_STD.ROM (OR THE QUICKER TO
;     LOAD .UPD, WHICH LEAVES THE RAM DISK EMPTY);
;   - FOR THE DISK BOOT OF THE BOOT LOADER (OPTIONAL): SYSCOPY D:=ZSYS.SYS.
;
; THE DISK MUST BE IN ONE OF LAMAC'S FORMATS (720K, 360K, HD 1.44M OR 1.2M)
; IN THE MZ LAYOUT, WITH THE IPL
; BOOT TRACK OF 256 BYTE SECTORS (AS LAMAC'S CP/M FORMATS IT).  THE ROMWBW
; FLOPPY DRIVER (MZFD.ASM) SHOWS THAT TRACK AS RESERVED TRACK 3 WITH 8
; SECTORS OF 512 BYTES, SO A READ OF ITS 9TH SECTOR FAILS: THAT IS THE
; TEST FOR THE LAYOUT.  CP/M 2.2 (ZSDOS) ONLY, DIRECT BIOS CALLS.
;
;======================================================================
;
BDOS		.EQU	$0005
FCB1		.EQU	$005C		; DRIVE, NAME OF THE FIRST ARGUMENT
FCB2		.EQU	$006C		; ... OF THE SECOND
;
S_TRK		.EQU	3		; CP/M TRACK OF THE BOOT TRACK
S_RECS		.EQU	32		; 4096 BYTES IN 128 BYTE RECORDS
;
	.ORG	$0100
;
S_START:
	LD	(S_SAVSP),SP
	LD	SP,S_STACK
	LD	DE,S_STRBANNER
	CALL	S_PRTSTR
;
	; ROMWBW HBIOS?
	LD	HL,($FFFC)		; HB_IDENT: ADDRESS OF THE IDENT BLOCK
	LD	A,(HL)			; 'W', ~'W'
	CP	'W'
	JP	NZ,S_ERRWBW
	INC	HL
	LD	A,(HL)
	CP	~'W'
	JP	NZ,S_ERRWBW
	; CP/M 2.2?
	LD	C,12			; BDOS VERSION
	CALL	BDOS
	LD	A,L
	CP	$30
	JP	NC,S_ERRVER
;
	; DRIVE
	LD	A,(FCB1)		; 1-16, 0 = NONE
	OR	A
	JP	Z,S_USAGE
	DEC	A
	LD	(S_DRIVE),A
	ADD	A,'A'
	LD	(S_STRDRV),A
	; FILE NAME
	LD	A,(FCB2 + 1)
	CP	' '
	JR	Z,S_START1
	LD	HL,FCB2 + 1
	LD	DE,S_IPL + 256 + PAR_NAME - LDR_START	; NAME PARAMETER
	LD	BC,11
	LDIR
S_START1:
;
	; SELECT, FORMAT FROM THE DPB
	LD	A,(S_DRIVE)
	LD	C,A
	LD	E,0			; FIRST SELECT
	LD	A,9			; SELDSK
	CALL	S_BIOS
	LD	A,H
	OR	L
	JP	Z,S_ERRSEL
	LD	DE,10			; DPB
	ADD	HL,DE
	LD	A,(HL)
	INC	HL
	LD	H,(HL)
	LD	L,A
	LD	E,(HL)			; E := SPT (THE HIGH BYTE MUST BE 0)
	INC	HL
	LD	A,(HL)
	OR	A
	JP	NZ,S_ERRFMT
	INC	HL
	LD	D,(HL)			; D := BSH
	INC	HL			; DSM AT +5
	INC	HL
	INC	HL
	LD	C,(HL)
	INC	HL
	LD	B,(HL)			; BC := DSM
	LD	A,E
	CP	36			; 9 X 512: 720K OR 360K, 2K BLOCKS
	JR	Z,S_START1A
	LD	A,D			; HD OF LAMAC'S CP/M: 4K BLOCKS
	CP	5
	JP	NZ,S_ERRFMT
	LD	A,E
	CP	72			; 18 X 512: 1.44M
	LD	A,2
	JR	Z,S_START2
	LD	A,E
	CP	60			; 15 X 512: 1.2M
	LD	A,3
	JR	Z,S_START2
	JP	S_ERRFMT
S_START1A:
	LD	A,D
	CP	4
	JP	NZ,S_ERRFMT
	LD	HL,350			; 720K
	OR	A
	SBC	HL,BC
	LD	A,0
	JR	Z,S_START2
	LD	HL,170			; 360K
	OR	A
	SBC	HL,BC
	LD	A,1
	JP	NZ,S_ERRFMT
S_START2:
	LD	(S_IPL + 256 + PAR_FMT - LDR_START),A	; FORMAT PARAMETER
;
	; MZ LAYOUT: TRACK 3 HAS ITS FIRST SECTOR BUT NOT A 9TH
	LD	BC,0
	CALL	S_READ
	JP	NZ,S_ERRLAY
	LD	BC,S_RECS
	CALL	S_READ
	JP	Z,S_ERRLAY
;
	; WRITE THE LOADER
	LD	DE,S_STRWRITE
	CALL	S_PRTSTR
	LD	HL,S_IPL
	LD	(S_DMA),HL
	LD	BC,0
S_WRITE1:
	PUSH	BC
	LD	HL,(S_DMA)
	LD	DE,128
	PUSH	HL
	ADD	HL,DE
	LD	(S_DMA),HL
	POP	HL
	LD	A,C
	CP	S_RECS - 1		; LAST RECORD: NO CACHING
	LD	E,2
	JR	NZ,S_WRITE2
	LD	E,1
S_WRITE2:
	CALL	S_RW			; WRITE RECORD C FROM HL, TYPE E
	POP	BC
	JP	NZ,S_ERRIO
	INC	C
	LD	A,C
	CP	S_RECS
	JR	NZ,S_WRITE1
;
	LD	C,13			; BDOS DISK RESET (AFTER DIRECT BIOS CALLS)
	CALL	BDOS
	LD	DE,S_STRDONE
	CALL	S_PRTSTR
	JR	S_EXIT
;
S_ERRWBW:
	LD	DE,S_STRWBW
	JR	S_ERR
S_ERRVER:
	LD	DE,S_STRVER
	JR	S_ERR
S_ERRSEL:
	LD	DE,S_STRSEL
	JR	S_ERR
S_ERRFMT:
	LD	DE,S_STRFMT
	JR	S_ERR
S_ERRLAY:
	LD	DE,S_STRLAY
	JR	S_ERR
S_ERRIO:
	LD	DE,S_STRIO
	JR	S_ERR
S_USAGE:
	LD	DE,S_STRUSAGE
S_ERR:
	CALL	S_PRTSTR
	LD	C,13			; BDOS DISK RESET
	CALL	BDOS
S_EXIT:
	LD	SP,(S_SAVSP)
	RET
;
; READ RECORD BC OF THE BOOT TRACK TO THE BUFFER.  Z IF OK.
;
S_READ:
	LD	HL,S_BUF
	LD	A,13			; READ
	JR	S_RW1
;
; WRITE RECORD C OF THE BOOT TRACK FROM HL, WRITE TYPE E.  Z IF OK.
;
S_RW:
	LD	B,0
	LD	A,E
	LD	(S_WTYPE),A
	LD	A,14			; WRITE
S_RW1:
	LD	(S_FUNC),A
	PUSH	HL
	PUSH	BC
	LD	A,(S_DRIVE)		; SELECT (NOT THE FIRST TIME)
	LD	C,A
	LD	E,1
	LD	A,9
	CALL	S_BIOS
	LD	BC,S_TRK		; TRACK
	LD	A,10
	CALL	S_BIOS
	POP	BC			; SECTOR (RECORD)
	LD	A,11
	CALL	S_BIOS
	POP	BC			; DMA
	LD	A,12
	CALL	S_BIOS
	LD	A,(S_WTYPE)		; WRITE TYPE (IGNORED BY READ)
	LD	C,A
	LD	A,(S_FUNC)
	CALL	S_BIOS
	OR	A
	RET
;
; BIOS FUNCTION A (0 = BOOT, 1 = WBOOT, ...), ARGUMENTS IN BC AND DE
;
S_BIOS:
	PUSH	DE
	LD	HL,($0001)		; WBOOT ENTRY = BIOS BASE + 3
	DEC	HL
	DEC	HL
	DEC	HL
	LD	E,A
	LD	D,0
	ADD	HL,DE
	ADD	HL,DE
	ADD	HL,DE
	POP	DE
	JP	(HL)
;
S_PRTSTR:
	LD	C,9
	JP	BDOS
;
S_STRBANNER	.TEXT	"MZSYS: ROMWBW BOOT FLOPPY FOR THE SHARP MZ-800\r\n$"
S_STRUSAGE	.TEXT	"USAGE: MZSYS D: [FILENAME.EXT]\r\n"
		.TEXT	"Writes the IPL loader to the boot track of the floppy in D:. The\r\n"
		.TEXT	"loader boots the RomWBW image FILENAME.EXT (default ROMWBW.ROM) from\r\n"
		.TEXT	"that disk. 720K, 360K, 1.44M or 1.2M floppy in the MZ layout (formatted\r\n"
		.TEXT	"by Lamac's CP/M or MZFMT). Put the image there with COPY, for the disk\r\n"
		.TEXT	"boot of the boot loader also SYSCOPY D:=ZSYS.SYS.\r\n$"
S_STRWBW	.TEXT	"ERROR: NOT ROMWBW\r\n$"
S_STRVER	.TEXT	"ERROR: CP/M 2.2 ONLY\r\n$"
S_STRSEL	.TEXT	"ERROR: NO SUCH DRIVE\r\n$"
S_STRFMT	.TEXT	"ERROR: NOT A 720K, 360K, 1.44M OR 1.2M FLOPPY OF LAMAC'S FORMATS\r\n$"
S_STRLAY	.TEXT	"ERROR: NO MZ BOOT TRACK (FORMAT THE DISK IN THE MZ LAYOUT)\r\n$"
S_STRIO		.TEXT	"ERROR: DISK WRITE\r\n$"
S_STRWRITE	.TEXT	"Writing the boot track of "
S_STRDRV	.TEXT	"A: ...\r\n$"
S_STRDONE	.TEXT	"Done. The disk boots in drive 0 if it holds the image file.\r\n$"
;
S_DRIVE		.DB	0
S_FUNC		.DB	0
S_WTYPE		.DB	0
S_DMA		.DW	0
S_SAVSP		.DW	0
S_BUF		.FILL	128, 0
		.FILL	64, 0
S_STACK		.EQU	$
;
; THE IPL IMAGE (4096 BYTES) FOLLOWS: HEADER SECTOR, THEN THE LOADER AT
; $1200 WITH ITS PARAMETERS
;
S_IPL		.EQU	$
;
#INCLUDE "mzipl.asm"
