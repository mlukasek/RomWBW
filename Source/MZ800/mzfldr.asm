;======================================================================
;	ROMWBW LOADER FOR THE SHARP MZ-800 WITH UNICARD
;======================================================================
;
; MZF PROGRAM, LOADED AT $1200 BY THE UNICARD MANAGER (OR STARTED AT
; POWER ON THROUGH /UNICARD/MZFLOADER.CFG).  IT:
;
;  1. DETECTS THE MEMEXT MEMORY EXPANSION (PEHU OR LUFTNER, 512K).
;     WITHOUT IT, IT SHOWS A MESSAGE AND STOPS.
;  2. MOVES ITSELF INTO THE COMMON BANK (BID_COM, $8F) AT $C000, AS THE
;     IMAGE WILL OVERWRITE THE FIRST 64K OF MEMEXT.
;  3. READS THE ROMWBW IMAGE (MZ800_STD.ROM) FROM THE UNICARD SD CARD
;     INTO MEMEXT BANKS $80, $81, ...  SEQUENTIALLY, WITHOUT SEEK
;     (SEEK DOES NOT WORK IN UNICARD FIRMWARE 0.26).  THE FILE IS
;     LOOKED FOR IN THE CURRENT UNICARD DIRECTORY, THEN IN /ROMWBW.
;     THE FULL .ROM IMAGE ALSO FILLS THE RAM DISK WITH THE ROMWBW
;     UTILITIES, THE .UPD IMAGE (FIRST 128K) LEAVES IT EMPTY.
;  4. MAPS BANK $80 AT $0000, SWITCHES TO MZ-800 MODE AND JUMPS TO $0000
;     (HBIOS).
;
; MESSAGES ARE SHOWN ON THE MZ-700 MODE TEXT SCREEN ($D000).
;
; MEMEXT (PORT $E7, PAGE OF THE CPU ADDRESS SPACE IN A12-A15, BANK AS
; DATA): PEHU HAS 8K BANKS (AN ODD PAGE FOLLOWS THE EVEN ONE), LUFTNER
; HAS 4K BANKS.  ROMWBW BANK $80+N IS MEMEXT RAM AT N * 32K FOR BOTH.
;
;======================================================================
;
MX_PORT		.EQU	$E7		; MEMEXT PAGE MAPPING PORT
UC_CMD		.EQU	$50		; UNICARD REPOSITORY COMMAND / STATUS
UC_DATA		.EQU	$51		; UNICARD REPOSITORY DATA
GDG_DMD		.EQU	$CE		; GDG DISPLAY MODE
;
UC_STSR		.EQU	$03		; RESET STATUS POINTER
UC_STORNO	.EQU	$04		; CANCEL PENDING COMMAND
UC_OPEN		.EQU	$50		; OPEN FILE (MODE, PATH)
UC_CLOSE	.EQU	$54		; CLOSE FILE
UC_SIZE		.EQU	$56		; FILE SIZE (DWORD)
;
TXT_VRAM	.EQU	$D000		; MZ-700 MODE TEXT SCREEN
TXT_ATTR	.EQU	$D800		; ... AND ITS ATTRIBUTES
TXT_COLS	.EQU	40
TXT_ROWS	.EQU	25
;
COM_BANK	.EQU	15		; BID_COM ($8F) AS 32K MEMEXT BANK
MAX_BANKS	.EQU	12		; LOAD AT MOST BANKS $80-$8B
;
MAIN_LOC	.EQU	$C000		; MAIN PART RUNS HERE (4K, COPIED WITH STACK)
;
;======================================================================
; MZF HEADER (128 BYTES)
;======================================================================
;
	.ORG	$1200 - 128
;
	.DB	$01			; OBJECT FILE
	.DB	"ROMWBW LOADER", $0D	; NAME, CR TERMINATED
	.FILL	17 - 14, $0D		; ... 17 BYTES
	.DW	LDR_END - LDR_START	; SIZE
	.DW	LDR_START		; LOAD ADDRESS
	.DW	LDR_START		; EXECUTION ADDRESS
	.FILL	104, 0			; COMMENT
;
;======================================================================
; STUB AT $1200: KNOWN MEMORY MAP, MAIN PART TO $C000
;======================================================================
;
LDR_START:
	DI
	LD	SP,LDR_START		; TEMPORARY STACK BELOW US
	LD	A,$08			; MZ-700 MODE (TEXT SCREEN, 700 MEMORY MAP)
	OUT	(GDG_DMD),A
	OUT	($E4),A			; POWER-ON MAP: RAM AT $1000-$CFFF
	LD	HL,MAIN_IMG		; COPY THE MAIN PART
	LD	DE,MAIN_LOC
	LD	BC,MAIN_END - MAIN_LOC
	LDIR
	JP	MAIN			; AND RUN IT
;
MAIN_IMG	.EQU	$
;
;======================================================================
; MAIN PART, RUNS AT $C000-$CFFF (STACK INCLUDED)
;======================================================================
;
	.ORG	MAIN_LOC
;
MAIN:
	LD	SP,MAIN_STACK		; STACK INSIDE THE COPIED AREA
	CALL	CLS			; CLEAR THE SCREEN
	LD	HL,STR_TITLE
	CALL	PRTLN
;
	; MEMEXT
	CALL	MX_DETECT		; A := 0 PEHU, 1 LUFTNER, $FF NONE
	LD	(MX_TYPE),A
	INC	A			; NONE?
	JR	NZ,MAIN1
	LD	HL,STR_NOMX
	JP	FAIL
MAIN1:
	LD	HL,STR_PEHU		; REPORT TYPE
	LD	A,(MX_TYPE)
	OR	A
	JR	Z,MAIN2
	LD	HL,STR_LUFT
MAIN2:
	CALL	PRTLN
	CALL	MX_TOCOM		; NOW RUN FROM THE COMMON BANK
;
	; UNICARD
	LD	A,UC_STORNO		; CANCEL ANYTHING PENDING
	OUT	(UC_CMD),A
	CALL	UC_STATUS		; STATUS BYTE 0
	CP	$FF			; NO CARD ANSWERS $FF
	JR	NZ,MAIN3
	LD	HL,STR_NOUC
	JP	FAIL
MAIN3:
	LD	A,UC_CLOSE		; CLOSE ANY OPEN FILE FIRST
	OUT	(UC_CMD),A
	LD	HL,STR_FILE1		; CURRENT DIRECTORY
	CALL	UC_OPENRD
	JR	Z,MAIN4
	LD	HL,STR_FILE2		; /ROMWBW
	CALL	UC_OPENRD
	JR	Z,MAIN4
	LD	HL,STR_NOFILE
	JP	FAIL
;
MAIN4:
	; NUMBER OF 32K BANKS := (SIZE + 32K - 1) / 32K, 1 .. MAX_BANKS
	; (IN A,(N) DOES NOT CHANGE THE FLAGS, SO THE CARRY CHAIN WORKS)
	LD	A,UC_SIZE
	OUT	(UC_CMD),A
	IN	A,(UC_DATA)		; SIZE BITS 0-7
	ADD	A,$FF			; + $7FFF
	IN	A,(UC_DATA)		; SIZE BITS 8-15
	ADC	A,$7F
	LD	E,A
	IN	A,(UC_DATA)		; SIZE BITS 16-23
	ADC	A,0
	LD	D,A
	IN	A,(UC_DATA)		; SIZE BITS 24-31
	OR	A			; 16M OR MORE?
	JR	NZ,MAIN6		; THEN JUST LOAD THE MAXIMUM
	LD	A,E			; BANKS := D:E >> 15
	RLA
	LD	A,D
	RLA
	JR	C,MAIN6			; 256 OR MORE BANKS
	OR	A			; EMPTY FILE?
	JR	NZ,MAIN5
	INC	A			; AT LEAST ONE BANK
MAIN5:
	CP	MAX_BANKS + 1		; TOO BIG?
	JR	C,MAIN7
MAIN6:
	LD	A,MAX_BANKS
MAIN7:
	LD	(NBANKS),A
;
	LD	HL,STR_LOAD
	CALL	PRT
	OUT	($E0),A			; RAM AT $0000-$0FFF
	XOR	A			; FIRST BANK
	LD	(BANK),A
LOAD1:
	LD	A,(BANK)		; MAP BANK AT $0000-$7FFF
	CALL	MX_LOWER
	LD	HL,0			; READ 32K
	LD	C,UC_DATA
	LD	D,128			; 128 X 256 BYTES
LOAD2:
	LD	B,0
	INIR
	DEC	D
	JR	NZ,LOAD2
	LD	A,'.'			; PROGRESS
	CALL	PUTC
	LD	HL,BANK			; NEXT BANK
	INC	(HL)
	LD	A,(NBANKS)
	CP	(HL)
	JR	NZ,LOAD1
	LD	A,UC_CLOSE		; DONE WITH THE FILE
	OUT	(UC_CMD),A
;
	; START HBIOS: BANK $80 LOW, MZ-800 MODE, RAM EVERYWHERE
	XOR	A
	CALL	MX_LOWER
	LD	A,$04			; MZ-800 MODE, 640X200
	OUT	(GDG_DMD),A
	OUT	($E0),A			; RAM AT $0000-$1FFF
	OUT	($E1),A			; RAM AT $E000-$FFFF
	IN	A,($E1)			; CG-ROM AND VRAM OUT
	JP	0			; HBIOS
;
FAIL:
	; PRINT MESSAGE HL AND STOP
	CALL	PRTLN
	LD	HL,STR_STOP
	CALL	PRTLN
	DI
	HALT
;
;----------------------------------------------------------------------
; MEMEXT DETECTION ON CPU PAGE 4 ($4000) WITH BANKS $20 AND $22.  THEIR
; FIRST BYTES ARE RESTORED.  RETURNS A = 0 PEHU, 1 LUFTNER, $FF NONE.
; PAGES 4 AND 5 ARE LEFT IDENTITY MAPPED.
;----------------------------------------------------------------------
;
MX_DETECT:
	LD	HL,$4000		; TEST ADDRESS
	LD	BC,$4000 | MX_PORT	; PAGE 4
	LD	A,$20			; BANK X
	OUT	(C),A
	LD	D,(HL)			; SAVE ORIGINAL BYTE
	LD	(HL),$AA		; MARKER X
	LD	A,$22			; BANK Y
	OUT	(C),A
	LD	E,(HL)			; SAVE ORIGINAL BYTE
	LD	(HL),$55		; MARKER Y
	LD	A,$20			; BACK TO BANK X
	OUT	(C),A
	LD	A,(HL)
	CP	$AA			; DISTINCT BANKS?
	LD	A,$FF			; NO MEMEXT
	RET	NZ			; (NOTHING TO RESTORE, SAME RAM)
	LD	B,$50			; PAGE 5, ODD PAGE OF THE PAIR
	LD	A,$22			; BANK Y
	OUT	(C),A
	LD	A,(HL)			; PEHU MAPS THE PAIR, LUFTNER PAGE 5 ONLY
	SUB	$55			; ZERO IF PEHU
	JR	Z,MX_DET1
	LD	A,1			; LUFTNER
MX_DET1:
	PUSH	AF			; SAVE TYPE
	LD	B,$40			; RESTORE THE ORIGINAL BYTES
	LD	A,$22
	OUT	(C),A
	LD	(HL),E
	LD	A,$20
	OUT	(C),A
	LD	(HL),D
	POP	AF			; TYPE
	PUSH	AF
	OR	A			; IDENTITY MAP FOR PAGES 4 AND 5
	LD	A,2			; PEHU: 8K BANK 2 AT $4000-$5FFF
	JR	Z,MX_DET2
	LD	A,4			; LUFTNER: 4K BANKS 4 AND 5
	OUT	(C),A
	LD	B,$50
	INC	A
MX_DET2:
	OUT	(C),A
	POP	AF			; TYPE
	RET
;
;----------------------------------------------------------------------
; MAP 32K MEMEXT BANK A (0-15) AT $0000-$7FFF.  BC, DE, HL DESTROYED.
;----------------------------------------------------------------------
;
MX_LOWER:
	LD	BC,$0000 | MX_PORT	; FIRST PAGE
	LD	E,A			; SAVE BANK
	LD	A,(MX_TYPE)
	OR	A			; PEHU?
	LD	A,E
	JR	NZ,MX_LOWER1
	RLCA				; PEHU: FIRST 8K BANK = BANK * 4
	RLCA
	LD	DE,$2004		; PAGE STEP $20, 4 WINDOWS
	JR	MX_LOWER2
MX_LOWER1:
	RLCA				; LUFTNER: FIRST 4K BANK = BANK * 8
	RLCA
	RLCA
	LD	DE,$1008		; PAGE STEP $10, 8 WINDOWS
MX_LOWER2:
	OUT	(C),A			; MAP ONE WINDOW
	INC	A			; NEXT BANK
	LD	L,A
	LD	A,B			; NEXT PAGE
	ADD	A,D
	LD	B,A
	LD	A,L
	DEC	E
	JR	NZ,MX_LOWER2
	RET
;
;----------------------------------------------------------------------
; MOVE THIS CODE (AND ITS STACK, $C000-$CFFF) INTO THE COMMON BANK AND
; MAP THE COMMON BANK AT $8000-$FFFF.  THE COPY GOES THROUGH A WINDOW AT
; $4000 SHOWING THE PART OF THE COMMON BANK THAT WILL APPEAR AT $C000.
; WHEN $8000-$FFFF IS SWITCHED, THE SAME BYTES ARE ALREADY THERE.
;----------------------------------------------------------------------
;
MX_TOCOM:
	LD	BC,$4000 | MX_PORT	; WINDOW: PAGE 4
	LD	A,(MX_TYPE)
	OR	A
	LD	A,COM_BANK * 4 + 2	; PEHU: 8K BANK FOR $C000-$DFFF
	JR	Z,MX_TOCOM1
	LD	A,COM_BANK * 8 + 4	; LUFTNER: 4K BANK FOR $C000-$CFFF
MX_TOCOM1:
	OUT	(C),A
	LD	HL,MAIN_LOC		; COPY $C000-$CFFF, STACK INCLUDED
	LD	DE,$4000
	LD	BC,$1000
	LDIR
	; SWITCH $8000-$FFFF TO THE COMMON BANK.  NO STACK USE FROM THE COPY
	; UNTIL HERE: A CALL WOULD PUSH ITS RETURN ADDRESS INTO THE OLD BANK.
	LD	BC,$8000 | MX_PORT	; FIRST UPPER PAGE
	LD	A,(MX_TYPE)
	OR	A
	LD	A,COM_BANK * 4		; PEHU: FIRST 8K BANK
	LD	DE,$2004		; PAGE STEP $20, 4 WINDOWS
	JR	Z,MX_TOCOM3
	LD	A,COM_BANK * 8		; LUFTNER: FIRST 4K BANK
	LD	DE,$1008		; PAGE STEP $10, 8 WINDOWS
MX_TOCOM3:
	OUT	(C),A			; MAP ONE WINDOW
	INC	A			; NEXT BANK
	LD	L,A
	LD	A,B			; NEXT PAGE
	ADD	A,D
	LD	B,A
	LD	A,L
	DEC	E
	JR	NZ,MX_TOCOM3
	LD	BC,$4000 | MX_PORT	; WINDOW BACK TO IDENTITY
	LD	A,(MX_TYPE)
	OR	A
	LD	A,2			; PEHU: 8K BANK 2
	JR	Z,MX_TOCOM2
	LD	A,4			; LUFTNER: 4K BANK 4
MX_TOCOM2:
	OUT	(C),A
	RET
;
;----------------------------------------------------------------------
; UNICARD: STATUS BYTE 0 IN A
;----------------------------------------------------------------------
;
UC_STATUS:
	LD	A,UC_STSR		; RESET STATUS POINTER
	OUT	(UC_CMD),A
	IN	A,(UC_CMD)		; BYTE 0
	RET
;
;----------------------------------------------------------------------
; UNICARD: OPEN FILE HL (ZERO TERMINATED) FOR READING.  Z IF OPEN.
;----------------------------------------------------------------------
;
UC_OPENRD:
	LD	A,UC_OPEN		; OPEN
	OUT	(UC_CMD),A
	LD	A,$01			; MODE: READ
	OUT	(UC_DATA),A
UC_OPENRD1:
	LD	A,(HL)			; PATH, TERMINATED BY A BYTE < $20
	INC	HL
	OR	A
	JR	Z,UC_OPENRD2
	OUT	(UC_DATA),A
	JR	UC_OPENRD1
UC_OPENRD2:
	LD	A,$0D			; TERMINATOR
	OUT	(UC_DATA),A
	CALL	UC_STATUS		; BIT 7 ERROR, BIT 3 FILE OPEN FOR READ
	AND	$88
	CP	$08
	RET
;
;----------------------------------------------------------------------
; TEXT OUTPUT ON THE MZ-700 MODE SCREEN
;----------------------------------------------------------------------
;
CLS:
	LD	HL,TXT_VRAM		; CHARACTERS: BLANK
	LD	DE,TXT_VRAM + 1
	LD	BC,TXT_COLS * TXT_ROWS - 1
	LD	(HL),0
	LDIR
	LD	HL,TXT_ATTR		; ATTRIBUTES: WHITE ON BLUE
	LD	DE,TXT_ATTR + 1
	LD	BC,TXT_COLS * TXT_ROWS - 1
	LD	(HL),$71
	LDIR
	LD	HL,TXT_VRAM		; CURSOR HOME
	LD	(CURSOR),HL
	LD	(LINE),HL
	RET
;
PRTLN:
	CALL	PRT			; PRINT HL, THEN NEW LINE
NEWLINE:
	LD	HL,(LINE)		; NEXT LINE
	LD	DE,TXT_COLS
	ADD	HL,DE
	LD	(LINE),HL
	LD	(CURSOR),HL
	RET
;
PRT:
	LD	A,(HL)			; PRINT ZERO TERMINATED STRING HL
	INC	HL
	OR	A
	RET	Z
	PUSH	HL
	CALL	PUTC
	POP	HL
	JR	PRT
;
PUTC:
	; ASCII CHARACTER A AT THE CURSOR (UPPER CASE, DIGITS, SOME SIGNS)
	CALL	DISPCODE
	LD	HL,(CURSOR)
	LD	(HL),A
	INC	HL
	LD	(CURSOR),HL
	RET
;
DISPCODE:
	; ASCII A -> MZ DISPLAY CODE A
	CP	'A'
	JR	C,DISPCODE1
	CP	'Z' + 1
	JR	NC,DISPCODE1
	SUB	$40			; A-Z = $01-$1A
	RET
DISPCODE1:
	CP	'0'
	JR	C,DISPCODE2
	CP	'9' + 1
	JR	NC,DISPCODE2
	SUB	$10			; 0-9 = $20-$29
	RET
DISPCODE2:
	LD	HL,DISPTBL		; OTHER SIGNS FROM A TABLE
	LD	E,A
DISPCODE3:
	LD	A,(HL)
	OR	A			; END OF TABLE: BLANK
	RET	Z
	INC	HL
	CP	E
	LD	A,(HL)
	INC	HL
	RET	Z
	JR	DISPCODE3
;
DISPTBL:	; ASCII, DISPLAY CODE
	.DB	'.', $2E, ':', $4F, ',', $2F, '-', $2A, '/', $2D, '(', $68
	.DB	')', $69, '!', $61, '?', $49, '=', $2B, '_', $2A
	.DB	0
;
;----------------------------------------------------------------------
; STRINGS AND DATA
;----------------------------------------------------------------------
;
STR_TITLE	.DB	"ROMWBW LOADER FOR SHARP MZ-800", 0
STR_PEHU	.DB	"MEMEXT: PEHU 512K", 0
STR_LUFT	.DB	"MEMEXT: LUFTNER 512K", 0
STR_NOMX	.DB	"ERROR: NO MEMEXT (PEHU OR LUFTNER 512K)", 0
STR_NOUC	.DB	"ERROR: NO UNICARD", 0
STR_NOFILE	.DB	"ERROR: MZ800_STD.ROM NOT FOUND", 0
STR_LOAD	.DB	"LOADING MZ800_STD.ROM ", 0
STR_STOP	.DB	"STOPPED.", 0
STR_FILE1	.DB	"MZ800_std.rom", 0
STR_FILE2	.DB	"/romwbw/MZ800_std.rom", 0
;
MX_TYPE		.DB	0		; 0 = PEHU, 1 = LUFTNER
NBANKS		.DB	0		; 32K BANKS TO LOAD
BANK		.DB	0		; CURRENT BANK
CURSOR		.DW	0		; TEXT CURSOR
LINE		.DW	0		; START OF THE CURRENT LINE
;
MAIN_END	.EQU	$
;
#IF (MAIN_END > (MAIN_LOC + $0F00))	; TASM: NO OPERATOR PRECEDENCE
	.ECHO	"*** ERROR: LOADER MAIN PART TOO BIG!!!\n"
	!!!
#ENDIF
;
MAIN_STACK	.EQU	MAIN_LOC + $1000	; STACK AT THE TOP OF $C000-$CFFF
;
	.ORG	MAIN_IMG + (MAIN_END - MAIN_LOC)
LDR_END		.EQU	$
;
	.END
