;======================================================================
;	ROMWBW LOADER FOR THE SHARP MZ-800 WITH UNICARD
;======================================================================
;
; MZF PROGRAM, LOADED AT $1200 BY THE UNICARD MANAGER (OR STARTED AT
; POWER ON THROUGH /UNICARD/MZFLOADER.CFG).  IT:
;
;  1. DETECTS THE MEMEXT MEMORY EXPANSION (PEHU OR LUFTNER, 512K).
;     WITHOUT IT, IT SHOWS A MESSAGE AND STOPS.
;  2. MOVES ITSELF INTO THE COMMON BANK (BID_COM, $8F) AT $C000, AS THE
;     IMAGE WILL OVERWRITE THE FIRST 64K OF MEMEXT.
;  3. READS THE ROMWBW IMAGE (MZ800_STD.ROM) FROM THE UNICARD SD CARD
;     INTO MEMEXT BANKS $80, $81, ...  SEQUENTIALLY, WITHOUT SEEK
;     (SEEK DOES NOT WORK IN UNICARD FIRMWARE 0.26).  THE FILE IS
;     LOOKED FOR IN THE CURRENT UNICARD DIRECTORY, THEN IN /ROMWBW.
;     THE FULL .ROM IMAGE ALSO FILLS THE RAM DISK WITH THE ROMWBW
;     UTILITIES, THE .UPD IMAGE (FIRST 128K) LEAVES IT EMPTY.
;  4. MAPS BANK $80 AT $0000, SWITCHES TO MZ-800 MODE AND JUMPS TO $0000
;     (HBIOS).
;
; MESSAGES ARE SHOWN ON THE MZ-700 MODE TEXT SCREEN ($D000).  THE PARTS
; SHARED WITH THE FLOPPY LOADER ARE IN MZCOMMON.ASM.
;
;======================================================================
;
MX_PORT		.EQU	$E7		; MEMEXT PAGE MAPPING PORT
UC_CMD		.EQU	$50		; UNICARD REPOSITORY COMMAND / STATUS
UC_DATA		.EQU	$51		; UNICARD REPOSITORY DATA
GDG_DMD		.EQU	$CE		; GDG DISPLAY MODE
;
UC_STSR		.EQU	$03		; RESET STATUS POINTER
UC_STORNO	.EQU	$04		; CANCEL PENDING COMMAND
UC_OPEN		.EQU	$50		; OPEN FILE (MODE, PATH)
UC_CLOSE	.EQU	$54		; CLOSE FILE
UC_SIZE		.EQU	$56		; FILE SIZE (DWORD)
;
TXT_VRAM	.EQU	$D000		; MZ-700 MODE TEXT SCREEN
TXT_ATTR	.EQU	$D800		; ... AND ITS ATTRIBUTES
TXT_COLS	.EQU	40
TXT_ROWS	.EQU	25
;
COM_BANK	.EQU	15		; BID_COM ($8F) AS 32K MEMEXT BANK
MAX_BANKS	.EQU	12		; LOAD AT MOST BANKS $80-$8B
;
MAIN_LOC	.EQU	$C000		; MAIN PART RUNS HERE (4K, COPIED WITH STACK)
;
;======================================================================
; MZF HEADER (128 BYTES)
;======================================================================
;
	.ORG	$1200 - 128
;
	.DB	$01			; OBJECT FILE
	.DB	"ROMWBW LOADER", $0D	; NAME, CR TERMINATED
	.FILL	17 - 14, $0D		; ... 17 BYTES
	.DW	LDR_END - LDR_START	; SIZE
	.DW	LDR_START		; LOAD ADDRESS
	.DW	LDR_START		; EXECUTION ADDRESS
	.FILL	104, 0			; COMMENT
;
;======================================================================
; STUB AT $1200: KNOWN MEMORY MAP, MAIN PART TO $C000
;======================================================================
;
LDR_START:
	DI
	LD	SP,LDR_START		; TEMPORARY STACK BELOW US
	LD	A,$08			; MZ-700 MODE (TEXT SCREEN, 700 MEMORY MAP)
	OUT	(GDG_DMD),A
	OUT	($E4),A			; POWER-ON MAP: RAM AT $1000-$CFFF
	LD	HL,MAIN_IMG		; COPY THE MAIN PART
	LD	DE,MAIN_LOC
	LD	BC,MAIN_END - MAIN_LOC
	LDIR
	JP	MAIN			; AND RUN IT
;
MAIN_IMG	.EQU	$
;
;======================================================================
; MAIN PART, RUNS AT $C000-$CFFF (STACK INCLUDED)
;======================================================================
;
	.ORG	MAIN_LOC
;
MAIN:
	LD	SP,MAIN_STACK		; STACK INSIDE THE COPIED AREA
	CALL	CLS			; CLEAR THE SCREEN
	LD	HL,STR_TITLE
	CALL	PRTLN
;
	CALL	MX_SETUP		; MEMEXT, THEN RUN FROM THE COMMON BANK
;
	; UNICARD
	LD	A,UC_STORNO		; CANCEL ANYTHING PENDING
	OUT	(UC_CMD),A
	CALL	UC_STATUS		; STATUS BYTE 0
	CP	$FF			; NO CARD ANSWERS $FF
	JR	NZ,MAIN3
	LD	HL,STR_NOUC
	JP	FAIL
MAIN3:
	LD	A,UC_CLOSE		; CLOSE ANY OPEN FILE FIRST
	OUT	(UC_CMD),A
	LD	HL,STR_FILE1		; CURRENT DIRECTORY
	CALL	UC_OPENRD
	JR	Z,MAIN4
	LD	HL,STR_FILE2		; /ROMWBW
	CALL	UC_OPENRD
	JR	Z,MAIN4
	LD	HL,STR_NOFILE
	JP	FAIL
;
MAIN4:
	; NUMBER OF 32K BANKS := (SIZE + 32K - 1) / 32K, 1 .. MAX_BANKS
	; (IN A,(N) DOES NOT CHANGE THE FLAGS, SO THE CARRY CHAIN WORKS)
	LD	A,UC_SIZE
	OUT	(UC_CMD),A
	IN	A,(UC_DATA)		; SIZE BITS 0-7
	ADD	A,$FF			; + $7FFF
	IN	A,(UC_DATA)		; SIZE BITS 8-15
	ADC	A,$7F
	LD	E,A
	IN	A,(UC_DATA)		; SIZE BITS 16-23
	ADC	A,0
	LD	D,A
	IN	A,(UC_DATA)		; SIZE BITS 24-31
	OR	A			; 16M OR MORE?
	JR	NZ,MAIN6		; THEN JUST LOAD THE MAXIMUM
	LD	A,E			; BANKS := D:E >> 15
	RLA
	LD	A,D
	RLA
	JR	C,MAIN6			; 256 OR MORE BANKS
	OR	A			; EMPTY FILE?
	JR	NZ,MAIN5
	INC	A			; AT LEAST ONE BANK
MAIN5:
	CP	MAX_BANKS + 1		; TOO BIG?
	JR	C,MAIN7
MAIN6:
	LD	A,MAX_BANKS
MAIN7:
	LD	(NBANKS),A
;
	LD	HL,STR_LOAD
	CALL	PRT
	OUT	($E0),A			; RAM AT $0000-$0FFF
	XOR	A			; FIRST BANK
	LD	(BANK),A
LOAD1:
	LD	A,(BANK)		; MAP BANK AT $0000-$7FFF
	CALL	MX_LOWER
	LD	HL,0			; READ 32K
	LD	C,UC_DATA
	LD	D,128			; 128 X 256 BYTES
LOAD2:
	LD	B,0
	INIR
	DEC	D
	JR	NZ,LOAD2
	LD	A,'.'			; PROGRESS
	CALL	PUTC
	LD	HL,BANK			; NEXT BANK
	INC	(HL)
	LD	A,(NBANKS)
	CP	(HL)
	JR	NZ,LOAD1
	LD	A,UC_CLOSE		; DONE WITH THE FILE
	OUT	(UC_CMD),A
;
	JP	HB_GO			; START HBIOS
;
;----------------------------------------------------------------------
; UNICARD: STATUS BYTE 0 IN A
;----------------------------------------------------------------------
;
UC_STATUS:
	LD	A,UC_STSR		; RESET STATUS POINTER
	OUT	(UC_CMD),A
	IN	A,(UC_CMD)		; BYTE 0
	RET
;
;----------------------------------------------------------------------
; UNICARD: OPEN FILE HL (ZERO TERMINATED) FOR READING.  Z IF OPEN.
;----------------------------------------------------------------------
;
UC_OPENRD:
	LD	A,UC_OPEN		; OPEN
	OUT	(UC_CMD),A
	LD	A,$01			; MODE: READ
	OUT	(UC_DATA),A
UC_OPENRD1:
	LD	A,(HL)			; PATH, TERMINATED BY A BYTE < $20
	INC	HL
	OR	A
	JR	Z,UC_OPENRD2
	OUT	(UC_DATA),A
	JR	UC_OPENRD1
UC_OPENRD2:
	LD	A,$0D			; TERMINATOR
	OUT	(UC_DATA),A
	CALL	UC_STATUS		; BIT 7 ERROR, BIT 3 FILE OPEN FOR READ
	AND	$88
	CP	$08
	RET
;
#INCLUDE "mzcommon.asm"
;
;----------------------------------------------------------------------
; STRINGS AND DATA
;----------------------------------------------------------------------
;
STR_TITLE	.DB	"ROMWBW LOADER FOR SHARP MZ-800", 0
STR_NOUC	.DB	"ERROR: NO UNICARD", 0
STR_NOFILE	.DB	"ERROR: MZ800_STD.ROM NOT FOUND", 0
STR_LOAD	.DB	"LOADING MZ800_STD.ROM ", 0
STR_FILE1	.DB	"MZ800_std.rom", 0
STR_FILE2	.DB	"/romwbw/MZ800_std.rom", 0
;
NBANKS		.DB	0		; 32K BANKS TO LOAD
BANK		.DB	0		; CURRENT BANK
;
MAIN_END	.EQU	$
;
#IF (MAIN_END > (MAIN_LOC + $0F00))	; TASM: NO OPERATOR PRECEDENCE
	.ECHO	"*** ERROR: LOADER MAIN PART TOO BIG!!!\n"
	!!!
#ENDIF
;
MAIN_STACK	.EQU	MAIN_LOC + $1000	; STACK AT THE TOP OF $C000-$CFFF
;
	.ORG	MAIN_IMG + (MAIN_END - MAIN_LOC)
LDR_END		.EQU	$
;
	.END
